"""BUILD R2 / O3 -- re-execute the bucket-(c) proof with the FIXED command, and prove
which half of the round-1 sentence was refuted.

Round 1 published: "regenerated byte-identically (sha256-16 `9ef271460a07b5f4` before and
after)". The auditor measured `fced1207f66487e1` live and called the sentence an overclaim.
Both are right about different things, and the sentence conflated them:

  PROPERTY (holds): delete -> assert ABSENT -> run the command -> the artifact comes back with
      the same bytes it had before, within one run. That is what makes it bucket (c).
  VALUE (does not hold): the published hash is not a durable receipt. A .pyc header embeds the
      SOURCE's mtime and size, so the value changes whenever the source is touched -- and the
      source WAS touched (`_b1_cited_probes.py` was ruff-formatted before commit).

Asserting the property while publishing the value as if it were the property is the defect.
So this probe measures both, and includes a control that DISTINGUISHES them: bump the source
mtime (bytes untouched, restored afterwards) and show the regenerated hash differs. Without
that control, "byte-identical" and "the hash is 9ef2..." look like the same claim.

Also re-checked here, because the round-1 command was broken (D2): the published regenerating
command must now exit 0 and must NOT dirty a tracked file.
"""

import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = "C:/Users/Prekzursil/source/ast-integrate"
HERE = os.path.join(ROOT, "command-center/slop-report")
OUT = os.path.join(HERE, "_r2_bucket_c.out.json")
CACHE = os.path.join(HERE, "__pycache__")
SOURCE = os.path.join(HERE, "_b1_cited_probes.py")
CMD = "python command-center/slop-report/_b1_control.py"


def sha16(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:16]


def snapshot():
    if not os.path.isdir(CACHE):
        return {}
    return {f: sha16(os.path.join(CACHE, f)) for f in sorted(os.listdir(CACHE))}


def regen():
    r = subprocess.run(
        [sys.executable, os.path.join(HERE, "_b1_control.py")],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=ROOT,
    )
    return r.returncode


def dirty_tracked():
    r = subprocess.run(
        [
            "git",
            "-C",
            ROOT,
            "status",
            "--porcelain",
            "--",
            "command-center/slop-report",
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return [ln for ln in r.stdout.splitlines() if not ln.startswith("??")]


def main():
    out = {
        "regenerating_command": CMD,
        "artifact": "command-center/slop-report/__pycache__",
    }
    src_sha_start = sha16(SOURCE)

    # ---- PROPERTY: delete -> absent -> regenerate -> byte-identical --------
    before = snapshot()
    shutil.rmtree(CACHE, ignore_errors=True)
    absent = not os.path.isdir(CACHE)
    tracked_dirty_pre = dirty_tracked()
    rc = regen()
    after = snapshot()
    tracked_dirty_post = dirty_tracked()
    out["property_run"] = {
        "before": before,
        "n_before": len(before),
        "absent_in_between": absent,
        "regen_rc": rc,
        "after": after,
        "n_after": len(after),
        "byte_identical": bool(before) and before == after,
        "tracked_dirty_before": tracked_dirty_pre,
        "tracked_dirty_after": tracked_dirty_post,
        "command_left_tree_clean": tracked_dirty_pre == tracked_dirty_post,
    }

    # ---- CONTROL: the VALUE is not durable --------------------------------
    # Touch the source mtime only (bytes untouched, mtime restored afterwards). If the pyc
    # hash still matched, "the hash is 9ef2..." would be a legitimate durable receipt.
    st = os.stat(SOURCE)
    try:
        os.utime(SOURCE, (st.st_atime, st.st_mtime + 120))
        shutil.rmtree(CACHE, ignore_errors=True)
        regen()
        after_touch = snapshot()
    finally:
        os.utime(SOURCE, (st.st_atime, st.st_mtime))
    src_sha_end = sha16(SOURCE)

    # restore the pyc set that matches the real source mtime
    shutil.rmtree(CACHE, ignore_errors=True)
    regen()
    restored = snapshot()

    out["value_durability_control"] = {
        "hypothesis_H_value_durable": "the published sha16 is a stable receipt",
        "hypothesis_H_value_volatile": "the sha16 tracks source mtime/size, not content identity",
        "hash_with_original_mtime": after,
        "hash_with_bumped_mtime": after_touch,
        "hashes_differ": after != after_touch,
        "source_bytes_unchanged": src_sha_start == src_sha_end,
        "source_sha16": src_sha_start,
        "restored_matches_original": restored == after,
        "verdict": "VALUE-IS-VOLATILE"
        if after != after_touch
        else "VALUE-LOOKS-DURABLE",
    }
    out["round1_published_hash"] = "9ef271460a07b5f4"
    out["auditor_measured_hash"] = "fced1207f66487e1"
    out["hash_now"] = after

    checks = {
        "existed_before": len(before) > 0,
        "absent_after_delete": absent,
        "present_after_regen": len(after) > 0,
        "byte_identical_within_run": bool(before) and before == after,
        "regen_rc_zero": rc == 0,
        "command_does_not_dirty_tracked_files": tracked_dirty_pre == tracked_dirty_post,
        "control_distinguishes_property_from_value": after != after_touch,
        "control_did_not_alter_source_bytes": src_sha_start == src_sha_end,
        "final_state_restored": restored == after,
    }
    out["checks"] = checks
    out["verdict"] = (
        "BUCKET-C-PROVEN" if all(checks.values()) else "BUCKET-C-NOT-PROVEN"
    )

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
    print(json.dumps(out, indent=1))
    return 0 if out["verdict"] == "BUCKET-C-PROVEN" else 1


if __name__ == "__main__":
    sys.exit(main())
