#!/usr/bin/env python3
"""Render DISPOSITION-TABLE.md FROM disposition.json instead of transcribing it by hand.

WHY THIS FILE EXISTS.  ``docs/mcp-audit/DISPOSITION-TABLE.md`` was hand-maintained against a
machine-generated artifact, and it drifted exactly the way that arrangement always drifts:
after round 2 re-measured the fleet, the committed table still read ``267/424 advertised
tools (63.0%); 7 further backend(s) UNMEASURED`` -- a number that had been superseded and a
residual that had been CLOSED.  A reader had no way to tell the table was stale, because a
markdown table carries no evidence of its own provenance.

Every figure here is now derived from ``disposition.json``.  Nothing is typed twice, so
nothing can disagree, and ``ci_gate.determinism()`` compares the regenerated bytes against
the committed blob -- the same treatment the other three artifacts already get.

THE FOOTER NUMBERS ARE COUNTED, NOT TYPED.  This is not stylistic.  Round 1 shipped a
success line hardcoded to ``2/2 artifacts`` while a third was being added, and the previous
version of this very table carried a hand-typed ``21/23`` next to a hand-typed counts dict.
A total that is written rather than counted is a legend that stops matching its field.

INVARIANTS (``--self-test`` proves each one FIRES on a broken input):

  G1  Every row of the source artifact reaches the table.  A renderer that silently drops
      rows would produce a shorter, entirely plausible-looking table.
  G2  No cell may contain a newline or a raw ``|``.  Either corrupts the markdown into a
      table that renders wrong while still looking like a table -- and the evidence column
      carries free prose, so this is a live hazard, not a theoretical one.
  G3  The footer's counts must re-derive from the rows.
  G4  Zero rows fails closed rather than emitting an empty table.

Read-only over a committed artifact.  Spawns nothing.  Prints no credential value.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = "disposition.json"

HEADER = (
    "| disposition | server | S1 config | S2 host | S3 mounted | S4 real call | tools | "
    "name B | schema B | evidence |"
)
RULE = "|---|---|---|---|---|---|---|---|---|---|"
HANDSHAKE = "stdio-handshake"

# The RESIDENT instrument enum, and the one place the `*` convention is defined.  Both
# this renderer and rank_disposition's legacy ``--md`` renderer import these, so the two
# cannot drift into marking different cells -- the defect class that produced a
# hand-maintained table disagreeing with its own generator in the first place.
#
# It is an ENUM rather than a prefix test on ``resident_basis`` on purpose: a renderer
# that decides by matching prose stops marking the day the prose is reworded, silently,
# and a table that quietly loses its provenance marks is worse than one that never had
# them -- every number then reads as a stdio measurement.
INSTR_STDIO = "stdio"
INSTR_CLIENT = "client-listing"
CLIENT_MARK = "*"


def resident_cell(row: dict[str, Any], field: str) -> str:
    """A resident-cost cell, marked ``*`` when the client listing took the number.

    ``--`` still means NOT MEASURED and never zero; after the round-4 join no mounted row
    should reach that branch, and ``assert_resident_completeness()`` fails the producer
    if one does.
    """
    v = row.get(field)
    if v is None:
        return "--"
    mark = CLIENT_MARK if row.get("resident_instrument") == INSTR_CLIENT else ""
    return f"{v}{mark}"


def s4_cell(row: dict[str, Any]) -> str:
    """PASS = stdio handshake; PASS* = a real in-session call instead; -- = neither."""
    if not row.get("call_verified"):
        return "--"
    return "PASS" if HANDSHAKE in (row.get("call_method") or "") else "PASS*"


def num(v: Any) -> str:
    """``--`` means NOT MEASURED and never zero -- the distinction the audit turns on."""
    return "--" if v is None else str(v)


def cells(row: dict[str, Any]) -> list[str]:
    return [
        f"**{row['disposition']}**",
        f"`{row['name']}`",
        str(row.get("config_state") or "--"),
        str(row.get("host_reachable") or "--"),
        "yes" if row.get("session_mounted") else "no",
        s4_cell(row),
        resident_cell(row, "resident_tool_count"),
        resident_cell(row, "resident_bytes"),
        num(row.get("schema_bytes")),
        str(row.get("evidence") or "--"),
    ]


def render(blob: dict[str, Any]) -> str:
    rows = blob.get("rows") or []
    if not rows:  # G4
        raise SystemExit(
            "FAILED:render-table disposition.json has no rows -- refusing to emit an "
            "empty table (fail closed)"
        )

    lines = [HEADER, RULE]
    bad: list[str] = []
    for row in rows:
        cs = cells(row)
        for i, c in enumerate(cs):  # G2
            if "\n" in c or "|" in c:
                bad.append(
                    f"{row.get('name')!r} cell[{i}] contains a newline or a pipe"
                )
        lines.append("| " + " | ".join(cs) + " |")
    if bad:
        raise SystemExit(
            "FAILED:render-table cell(s) would corrupt the markdown:\n  "
            + "\n  ".join(bad)
        )

    total = len(rows)
    verified = sum(1 for r in rows if r.get("call_verified"))  # G3
    listed = sum(1 for r in rows if r.get("resident_instrument") == INSTR_CLIENT)
    resident = sum(1 for r in rows if r.get("resident_tool_count") is not None)
    contingent = sum(1 for r in rows if r.get("schema_bytes") is not None)
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["disposition"]] = counts.get(r["disposition"], 0) + 1
    ordered = {k: counts[k] for k in ("DISABLE", "INVESTIGATE", "KEEP") if k in counts}

    lines += [
        "",
        f"*Generated by `command-center/mcp-audit/render_table.py` from `{SOURCE}` "
        f"(generated {blob.get('generated_utc_date', 'unknown')}). Do not hand-edit: "
        "`ci_gate.py` compares the regenerated bytes against this file.*",
        "",
        f"`S4 PASS` = stdio initialize+tools/list handshake.  `S4 PASS*` = a real "
        f"in-session tool call instead (HTTP transport cannot be spawned).  Both count as "
        f"S4 `call_verified`, which is their union: {verified}/{total} rows.  "
        f"Counts: {ordered}.  Throughout this table `{CLIENT_MARK}` means the same thing "
        f"in every column: **measured by the client, not by a stdio child** -- so it "
        f"marks a real measurement's instrument, never a weaker one.",
        "",
        f"RESIDENT cost -- the `tools` and `name B` columns, what every request carries "
        f"for a mounted server -- is measured on {resident}/{total} rows: "
        f"{resident - listed} sampled from a stdio child, {listed} marked `{CLIENT_MARK}` "
        f"and joined from the client's own tool listing "
        f"(`unsampled-surface.json`), which reaches the HTTP transports no stdio sweep "
        f"can spawn. `assert_resident_completeness()` fails the producer if a mounted row "
        f"carries no resident cost, or if a joined value drifts from that source.",
        "",
        f"CONTINGENT cost -- the `schema B` column -- is measured on {contingent}/{total} "
        f"rows. A `--` there is **not measured**, never zero: this client defers schemas "
        f"and never materialises them for the `{CLIENT_MARK}` rows, so no honest figure "
        f"exists and the fleet contingent total remains a LOWER BOUND. The asymmetry "
        f"between the two paragraphs is the measurement, not an omission.",
        "",
    ]
    return "\n".join(lines)


def load(base: pathlib.Path | None = None) -> dict[str, Any]:
    path = (base or HERE) / SOURCE
    if not path.exists():
        raise SystemExit(f"FAILED:render-table {path} is missing (fail closed)")
    return json.loads(path.read_text(encoding="utf-8"))


# -------------------------------------------------------------------- self-test
_GOOD: dict[str, Any] = {
    "generated_utc_date": "2026-08-14",
    "rows": [
        {
            "name": "a",
            "disposition": "KEEP",
            "config_state": "enabled",
            "host_reachable": "Connected",
            "session_mounted": True,
            "call_verified": True,
            "call_method": "stdio-handshake",
            "tool_count": 3,
            "name_bytes": 30,
            "schema_bytes": 300,
            "resident_tool_count": 3,
            "resident_bytes": 30,
            "resident_instrument": INSTR_STDIO,
            "evidence": "a real handshake returned 3 tools",
        },
        {
            # The round-4 shape: an HTTP row with NO stdio child, so tool_count/name_bytes
            # /schema_bytes are null, but a resident cost the client listing did measure.
            # schema_bytes stays null on purpose -- that is the honest asymmetry, and a
            # fixture that filled it would stop this file testing the case it exists for.
            "name": "b",
            "disposition": "DISABLE",
            "config_state": "disabled",
            "host_reachable": "FAILED",
            "session_mounted": True,
            "call_verified": False,
            "call_method": None,
            "tool_count": None,
            "name_bytes": None,
            "schema_bytes": None,
            "resident_tool_count": 5,
            "resident_bytes": 50,
            "resident_instrument": INSTR_CLIENT,
            "evidence": "no stdio child to sample; resident cost from the client listing",
        },
    ],
}


def _data_rows(text: str) -> int:
    """Data rows in a rendered table.

    ONE helper for both G1 checks on purpose: the first version counted them two
    different ways (one filtered on ``"---" not in ln``, the other subtracted a fixed 2)
    and the two disagreed by one, so the dropped-row control reported 0 and went red.
    Two spellings of the same count is how a control ends up measuring the speller.
    """
    return sum(1 for ln in text.splitlines() if ln.startswith("| ")) - 1


def self_test() -> int:
    print("== render_table self-test (G1 rows, G2 cells, G3 footer, G4 fail-closed) ==")
    problems: list[str] = []
    out = render(json.loads(json.dumps(_GOOD)))

    n_data = _data_rows(out)
    if n_data != len(_GOOD["rows"]):
        problems.append(
            f"G1 rendered {n_data} data rows for {len(_GOOD['rows'])} inputs"
        )
    print(
        f"  {'ok ' if n_data == 2 else 'BAD'} G1 every source row reaches the table ({n_data})"
    )

    # G1 must FIRE when a row is dropped -- a renderer that cannot notice a missing row
    # gives no assurance at all.
    fewer = json.loads(json.dumps(_GOOD))
    fewer["rows"] = fewer["rows"][:1]
    dropped = _data_rows(render(fewer))
    if dropped != 1:
        problems.append(f"G1 did not track a dropped row (counted {dropped})")
    print(f"  {'ok ' if dropped == 1 else 'BAD'} G1 tracks a dropped row ({dropped})")

    # G2 both states: a pipe in free prose must be refused, not silently rendered.
    for label, mutate in (
        ("pipe in evidence", lambda b: b["rows"][0].update(evidence="a | b")),
        ("newline in evidence", lambda b: b["rows"][0].update(evidence="a\nb")),
    ):
        m = json.loads(json.dumps(_GOOD))
        mutate(m)
        try:
            render(m)
            problems.append(f"G2 {label} -> SURVIVED")
            print(f"  BAD G2 {label:24} -> SURVIVED")
        except SystemExit:
            print(f"  ok  G2 {label:24} -> fired")

    # G3: the footer is counted, so changing a row's verdict must move it.
    flipped = json.loads(json.dumps(_GOOD))
    flipped["rows"][1]["disposition"] = "KEEP"
    if "{'KEEP': 2}" not in render(flipped):
        problems.append("G3 footer counts did not follow the rows")
    print(
        f"  {'ok ' if 'KEEP' in render(flipped) else 'BAD'} G3 footer counts follow the rows"
    )

    # G5 BOTH STATES on the provenance mark.  The round-4 join put real numbers into
    # cells that used to read `--`, so a reader can no longer tell which instrument took
    # one -- unless the `*` is there.  A renderer that dropped the mark would produce a
    # table where seven client-listed counts read exactly like stdio measurements, which
    # is a worse artifact than the one with seven honest `--`.  So: the mark must appear
    # on the client row, must NOT appear on the stdio row, and flipping the enum must
    # move it.  A test that only asserted "a `*` appears somewhere" would pass under both
    # hypotheses.
    marked = render(json.loads(json.dumps(_GOOD)))
    client_line = [ln for ln in marked.splitlines() if "`b`" in ln][0]
    stdio_line = [ln for ln in marked.splitlines() if "`a`" in ln][0]
    if "| 5* |" not in client_line or "| 50* |" not in client_line:
        problems.append(f"G5 client-listed row is unmarked: {client_line}")
    if "*" in stdio_line.split("|")[7]:
        problems.append(f"G5 stdio row is wrongly marked: {stdio_line}")
    print(
        f"  {'ok ' if '| 5* |' in client_line else 'BAD'} G5 client-listed cells carry "
        f"`{CLIENT_MARK}`, stdio cells do not"
    )
    flipped_instr = json.loads(json.dumps(_GOOD))
    flipped_instr["rows"][1]["resident_instrument"] = INSTR_STDIO
    unmarked = [ln for ln in render(flipped_instr).splitlines() if "`b`" in ln][0]
    if "| 5 |" not in unmarked:
        problems.append("G5 flipping the instrument did not remove the mark")
    print(
        f"  {'ok ' if '| 5 |' in unmarked else 'BAD'} G5 flipping the instrument enum "
        f"moves the mark (control fires)"
    )

    # G4 fail closed.
    try:
        render({"rows": []})
        problems.append("G4 empty rows -> SURVIVED")
        print("  BAD G4 empty rows                     -> SURVIVED")
    except SystemExit:
        print("  ok  G4 empty rows                     -> fired")

    # And the shipped artifact must actually render.
    real = render(load())
    print(f"  ok  shipped disposition.json renders ({len(real)} B)")
    if problems:
        for p in problems:
            print(f"  FAIL {p}")
        print(f"FAILED:render-table self-test {len(problems)} problem(s)")
        return 1
    print(
        "SUCCESS:render-table self-test 8/8 invariants behaved, shipped artifact renders"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default=None)
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    base = pathlib.Path(args.base) if args.base else None
    text = render(load(base))
    if args.out:
        out = pathlib.Path(args.out)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out}")
    return self_test()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
