#!/usr/bin/env python3
"""Build a 5-file live tree from the on-disk ARC-0010 registry + generator.

Four files are exact generated bytes (real registry entries on this worktree).
rules/rule.no-secrets.md is live-larger: typed body plus remainder that the
schema cannot express without an opaque passthrough.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ARC10 = HERE.parent / "ARC-0010"
sys.path.insert(0, str(ARC10))
import generator as G  # noqa: E402

from extract import LIVE_LARGER_REL, LIVE_REMAINDER, SAMPLE_RELS, lf_bytes  # noqa: E402


def load_live_registry() -> dict[str, Any]:
    return G.load_default_registry()


def generated_sample(registry: dict[str, Any] | None = None) -> dict[str, bytes]:
    registry = registry or load_live_registry()
    files = G.generate(registry)
    out = {rel: files[rel] for rel in SAMPLE_RELS}
    return out


def write_tree(files: dict[str, bytes], root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    for rel, data in files.items():
        dest = root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(lf_bytes(data))


def build_live_tree(root: Path, registry: dict[str, Any] | None = None) -> dict[str, Any]:
    """Write live/ (one live-larger) and generated/ (exact projections)."""
    files = generated_sample(registry)
    gen_root = root / "generated"
    live_root = root / "live"
    write_tree(files, gen_root)
    live_files = dict(files)
    live_files[LIVE_LARGER_REL] = lf_bytes(files[LIVE_LARGER_REL]) + LIVE_REMAINDER.encode(
        "utf-8"
    )
    write_tree(live_files, live_root)
    meta = {
        "sample_rels": list(SAMPLE_RELS),
        "live_larger": LIVE_LARGER_REL,
        "generated_bytes": {rel: len(files[rel]) for rel in SAMPLE_RELS},
        "live_bytes": {rel: len(live_files[rel]) for rel in SAMPLE_RELS},
    }
    (root / "scenario-meta.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8"
    )
    return meta
