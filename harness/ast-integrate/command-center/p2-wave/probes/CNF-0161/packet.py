#!/usr/bin/env python3
"""Owner-escalation packet for claims no vendor triangulation can settle.

Contract (catalog CNF-0161 / spec 11364-11370):
  * exactly one foundation-level question per packet entry
  * recommendation, strongest tradeoff, default if unanswered, impact
  * a settling experiment a third party can run, with a cost
  * answers recorded in OWNER-DECISIONS.md are never re-asked

CNF-0160 is the production unresolved-list source. This module does not invent
claims when that receipt is missing.

Estate files command-center/OWNER-QUESTION-PACKET.md and
command-center/OWNER-DECISIONS.md are READ-ONLY inputs. The unit-scoped packet
is command-center/receipts/CNF-0161-owner-packet.md.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

UNRESOLVED_STATUSES = frozenset(
    {
        "UNRESOLVED",
        "AMBIGUOUS-CLAIM",
        "AMBIGUOUS",
        "IRREDUCIBLE",
        "NOT-SETTLED",
        "OWNER-REQUIRED",
        "THREE-WAY-SPLIT",
    }
)
COMPOUND_RE = re.compile(
    r"\b(and|or)\s+(should|shall|can|may|do|does|is|are|will|would|must)\b",
    re.IGNORECASE,
)
DECISION_HEAD_RE = re.compile(r"^##\s+Decision:\s+(\S+)\s*$")
ENTRY_HEAD_RE = re.compile(r"^##\s+Entry:\s+(\S+)\s*$")
FIELD_RE = re.compile(r"^-\s+([a-z_]+):\s+(.*)$")
HEADING_DECISION_RE = re.compile(r"^###\s+(\S+)\s+—\s+(.*)$")
UNIT_PACKET_REL = "command-center/receipts/CNF-0161-owner-packet.md"
ESTATE_PACKET_REL = "command-center/OWNER-QUESTION-PACKET.md"
ESTATE_DECISIONS_REL = "command-center/OWNER-DECISIONS.md"
ESTATE_PACKET_MARKER = "Hand-written, NOT generated."
ESTATE_DECISIONS_MARKER = "GENERATED by tools/command-center/render.py"


def fingerprint(text: str) -> str:
    t = re.sub(r"\s+", " ", (text or "").strip().lower())
    t = t.rstrip("?").strip()
    return hashlib.sha256(t.encode("utf-8")).hexdigest()[:16]


def question_clauses(text: str) -> list[str]:
    normalized = (text or "").replace("？", "?")
    return [p.strip() for p in normalized.split("?") if p.strip()]


def is_compound_question(text: str) -> bool:
    clauses = question_clauses(text)
    if len(clauses) != 1:
        return True
    return bool(COMPOUND_RE.search(clauses[0]))


def _nonempty(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def validate_entry(entry: dict) -> list[str]:
    errors: list[str] = []
    if not isinstance(entry, dict):
        return ["entry-not-object"]
    cid = str(entry.get("claim_id") or "").strip()
    if not cid:
        errors.append("claim_id-empty")
    question = str(entry.get("question") or "")
    if not _nonempty(question):
        errors.append("question-empty")
    elif is_compound_question(question):
        errors.append("compound-question")
    for key in (
        "recommendation",
        "strongest_tradeoff",
        "default_if_unanswered",
        "impact",
    ):
        if not _nonempty(entry.get(key)):
            errors.append(f"{key}-empty")
    experiment = entry.get("settling_experiment")
    if not isinstance(experiment, dict):
        errors.append("settling_experiment-missing")
    else:
        for key in ("command", "expected_observation", "discriminating_outcome", "cost"):
            if not _nonempty(experiment.get(key)):
                errors.append(f"settling_experiment.{key}-empty")
    return errors


def load_unresolved(path: Path | None) -> dict:
    """Load CNF-0160 (or a fixture with the same shape). Never invent claims."""
    if path is None or not path.is_file():
        return {
            "status": "ABSENT",
            "exists": False,
            "path": "" if path is None else path.as_posix(),
            "claims": [],
            "reason": "CNF-0160 unresolved list is not on disk; claims are not invented",
        }
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        return {
            "status": "ABSENT",
            "exists": False,
            "path": path.as_posix(),
            "claims": [],
            "reason": f"unreadable:{type(exc).__name__}",
        }
    if not raw.strip():
        return {
            "status": "EMPTY",
            "exists": True,
            "path": path.as_posix(),
            "claims": [],
            "reason": "file exists but is empty",
        }
    try:
        doc = json.loads(raw)
    except json.JSONDecodeError as exc:
        return {
            "status": "UNPARSEABLE",
            "exists": True,
            "path": path.as_posix(),
            "claims": [],
            "reason": f"json:{exc.msg}",
        }
    if not isinstance(doc, dict):
        return {
            "status": "UNPARSEABLE",
            "exists": True,
            "path": path.as_posix(),
            "claims": [],
            "reason": "json-root-not-object",
        }
    claims = extract_unresolved_claims(doc)
    return {
        "status": "PRESENT",
        "exists": True,
        "path": path.as_posix(),
        "claims": claims,
        "reason": "parsed",
    }


def extract_unresolved_claims(doc: dict) -> list[dict]:
    found: list[dict] = []
    for key in (
        "unresolved_claims",
        "unresolved_list",
        "unresolved",
        "ambiguous_claims",
    ):
        val = doc.get(key)
        if isinstance(val, list):
            found.extend(normalize_claim(x) for x in val if isinstance(x, dict))
    for key in (
        "claims",
        "results",
        "entries",
        "trigger_evaluations",
        "evaluations",
        "discrepancies",
    ):
        val = doc.get(key)
        if not isinstance(val, list):
            continue
        for item in val:
            if not isinstance(item, dict):
                continue
            st = str(
                item.get("status")
                or item.get("verdict")
                or item.get("state")
                or item.get("triangulation_outcome")
                or item.get("outcome")
                or ""
            ).upper()
            if st in UNRESOLVED_STATUSES:
                found.append(normalize_claim(item))
    uniq: dict[str, dict] = {}
    for claim in found:
        cid = claim["id"]
        if cid and cid not in uniq:
            uniq[cid] = claim
    return list(uniq.values())


def normalize_claim(raw: dict) -> dict:
    cid = str(raw.get("id") or raw.get("claim_id") or "").strip()
    statement = str(raw.get("statement") or raw.get("claim") or raw.get("text") or "").strip()
    status = str(
        raw.get("status") or raw.get("verdict") or raw.get("state") or "UNRESOLVED"
    ).upper()
    return {
        "id": cid,
        "statement": statement,
        "status": status,
        "vendor_a_verdict": str(raw.get("vendor_a_verdict") or raw.get("anthropic") or ""),
        "vendor_b_verdict": str(raw.get("vendor_b_verdict") or raw.get("codex") or ""),
        "vendor_c_verdict": str(raw.get("vendor_c_verdict") or raw.get("third") or ""),
        "owner_question": str(raw.get("owner_question") or "").strip(),
        "recommendation": str(raw.get("recommendation") or "").strip(),
        "strongest_tradeoff": str(raw.get("strongest_tradeoff") or "").strip(),
        "default_if_unanswered": str(raw.get("default_if_unanswered") or "").strip(),
        "impact": str(raw.get("impact") or "").strip(),
        "settling_experiment": raw.get("settling_experiment")
        if isinstance(raw.get("settling_experiment"), dict)
        else {},
    }


def entry_from_claim(claim: dict) -> dict:
    cid = claim["id"]
    statement = claim.get("statement") or cid
    question = claim.get("owner_question") or (
        f"When vendor triangulation leaves {cid} unresolved, should the claim "
        f"close as AMBIGUOUS-CLAIM rather than take a majority or casting vote"
    )
    experiment = claim.get("settling_experiment") or {}
    if not experiment:
        experiment = {
            "command": (
                "PYTHONDONTWRITEBYTECODE=1 python3 -B "
                "command-center/p2-wave/probes/CNF-0161/settle_claim.py "
                f"--claim {cid}"
            ),
            "expected_observation": (
                "The three recorded vendor verdicts pairwise differ, or the "
                "CNF-0160 row still carries an unresolved status."
            ),
            "discriminating_outcome": (
                "Pairwise-distinct verdicts => keep AMBIGUOUS-CLAIM; any two "
                "agreeing => the claim is no longer owner-escalation material."
            ),
            "cost": "one local process, under 30s, no vendor rail, no credential",
        }
    return {
        "claim_id": cid,
        "question": question,
        "recommendation": claim.get("recommendation")
        or (
            f"Close {cid} as AMBIGUOUS-CLAIM. Do not treat any vendor as a "
            f"casting vote on {statement}"
        ),
        "strongest_tradeoff": claim.get("strongest_tradeoff")
        or (
            "A majority or casting vote would manufacture a verdict the "
            "triangulation rule forbids; leaving the claim open blocks every "
            "consumer that requires a terminal status"
        ),
        "default_if_unanswered": claim.get("default_if_unanswered")
        or "Close as AMBIGUOUS-CLAIM; do not count the claim as CONFIRMED or REFUTED",
        "impact": claim.get("impact")
        or (
            "Downstream confirmation rates must keep this id out of both the "
            "CONFIRMED and REFUTED denominators until an owner answer or a "
            "re-run of the named settling experiment changes the row"
        ),
        "settling_experiment": experiment,
        "question_fingerprint": fingerprint(question),
    }


def parse_decisions(text: str) -> list[dict]:
    decisions: list[dict] = []
    current: dict | None = None
    for line in (text or "").splitlines():
        head = DECISION_HEAD_RE.match(line)
        if head:
            if current:
                decisions.append(current)
            current = {
                "claim_id": head.group(1),
                "question": "",
                "question_fingerprint": "",
                "answer": "",
                "source": "",
                "recorded_at": "",
            }
            continue
        if current is None:
            continue
        field = FIELD_RE.match(line)
        if field and field.group(1) in current:
            current[field.group(1)] = field.group(2).strip()
    if current:
        decisions.append(current)
    seen = {str(item.get("claim_id") or "") for item in decisions}
    for item in parse_owner_table(text):
        cid = str(item.get("claim_id") or "")
        if cid and cid not in seen:
            decisions.append(item)
            seen.add(cid)
    for item in decisions:
        if not item.get("question_fingerprint") and item.get("question"):
            item["question_fingerprint"] = fingerprint(item["question"])
    return decisions


def parse_owner_table(text: str) -> list[dict]:
    """Parse the generated OWNER-DECISIONS.md table plus ### Answered headings."""
    rows: list[dict] = []
    for line in (text or "").splitlines():
        stripped = line.strip()
        if stripped.startswith("|"):
            cols = [c.strip() for c in stripped.split("|")]
            if len(cols) < 6:
                continue
            cid = cols[1]
            state = cols[2].upper()
            if not cid or cid in {"#", "---"} or cid.startswith("-"):
                continue
            if state != "ANSWERED":
                continue
            question = cols[4] if len(cols) > 4 else ""
            answer = cols[5] if len(cols) > 5 else ""
            if not _nonempty(answer) or answer in {"—", "-", "–"}:
                continue
            rows.append(
                {
                    "claim_id": cid,
                    "question": question,
                    "question_fingerprint": fingerprint(question) if question else "",
                    "answer": answer,
                    "source": "OWNER-DECISIONS.md table",
                    "recorded_at": "",
                }
            )
            continue
        heading = HEADING_DECISION_RE.match(stripped)
        if heading:
            cid = heading.group(1)
            answer = heading.group(2).strip()
            if cid and _nonempty(answer):
                rows.append(
                    {
                        "claim_id": cid,
                        "question": "",
                        "question_fingerprint": "",
                        "answer": answer,
                        "source": "OWNER-DECISIONS.md heading",
                        "recorded_at": "",
                    }
                )
    return rows


def estate_packet_intact(text: str) -> bool:
    return ESTATE_PACKET_MARKER in (text or "")


def estate_decisions_intact(text: str) -> bool:
    return ESTATE_DECISIONS_MARKER in (text or "")


def parse_packet(text: str) -> list[dict]:
    entries: list[dict] = []
    current: dict | None = None
    experiment: dict | None = None
    for line in (text or "").splitlines():
        head = ENTRY_HEAD_RE.match(line)
        if head:
            if current is not None:
                current["settling_experiment"] = experiment or {}
                current["question_fingerprint"] = fingerprint(str(current.get("question") or ""))
                entries.append(current)
            current = {
                "claim_id": head.group(1),
                "question": "",
                "recommendation": "",
                "strongest_tradeoff": "",
                "default_if_unanswered": "",
                "impact": "",
            }
            experiment = {
                "command": "",
                "expected_observation": "",
                "discriminating_outcome": "",
                "cost": "",
            }
            continue
        if current is None:
            continue
        field = FIELD_RE.match(line)
        if not field:
            continue
        key, value = field.group(1), field.group(2).strip()
        if key in current:
            current[key] = value
        elif experiment is not None and key in experiment:
            experiment[key] = value
    if current is not None:
        current["settling_experiment"] = experiment or {}
        current["question_fingerprint"] = fingerprint(str(current.get("question") or ""))
        entries.append(current)
    return entries


def render_packet(entries: list[dict], *, source_status: str, source_path: str, generated_at: str) -> str:
    lines = [
        "# Owner question packet",
        "",
        "Format: one foundation-level question per entry (spec 11364-11370).",
        "A compound question is not shippable. A missing default is not shippable.",
        "Answers belong in OWNER-DECISIONS.md and are never re-asked.",
        "",
        f"- generated_at: {generated_at}",
        f"- source_path: {source_path or '(none)'}",
        f"- source_status: {source_status}",
        f"- open_entry_count: {len(entries)}",
        "",
    ]
    if not entries:
        lines.extend(
            [
                "No open owner questions. Either the unresolved list was empty, or",
                "every surviving claim already has a durable answer, or the CNF-0160",
                "receipt is absent and this packet refuses to invent claims.",
                "",
            ]
        )
        return "\n".join(lines)
    for entry in entries:
        exp = entry.get("settling_experiment") or {}
        lines.extend(
            [
                f"## Entry: {entry['claim_id']}",
                "",
                f"- question: {entry['question']}",
                f"- recommendation: {entry['recommendation']}",
                f"- strongest_tradeoff: {entry['strongest_tradeoff']}",
                f"- default_if_unanswered: {entry['default_if_unanswered']}",
                f"- impact: {entry['impact']}",
                f"- command: {exp.get('command', '')}",
                f"- expected_observation: {exp.get('expected_observation', '')}",
                f"- discriminating_outcome: {exp.get('discriminating_outcome', '')}",
                f"- cost: {exp.get('cost', '')}",
                f"- question_fingerprint: {entry.get('question_fingerprint') or fingerprint(entry['question'])}",
                "",
            ]
        )
    return "\n".join(lines)


def render_decisions(decisions: list[dict]) -> str:
    lines = [
        "# Owner decisions",
        "",
        "Each recorded answer closes the matching claim_id and question fingerprint.",
        "Re-runs must not re-ask a closed question.",
        "",
    ]
    if not decisions:
        lines.extend(["No decisions recorded yet.", ""])
        return "\n".join(lines)
    for item in decisions:
        q = item.get("question") or ""
        lines.extend(
            [
                f"## Decision: {item['claim_id']}",
                "",
                f"- question: {q}",
                f"- question_fingerprint: {item.get('question_fingerprint') or fingerprint(q)}",
                f"- answer: {item.get('answer') or ''}",
                f"- source: {item.get('source') or ''}",
                f"- recorded_at: {item.get('recorded_at') or ''}",
                "",
            ]
        )
    return "\n".join(lines)


def is_answered(claim_or_entry: dict, decisions: list[dict]) -> bool:
    cid = str(claim_or_entry.get("id") or claim_or_entry.get("claim_id") or "")
    q = str(claim_or_entry.get("owner_question") or claim_or_entry.get("question") or "")
    fp = fingerprint(q) if q else ""
    for item in decisions:
        if cid and item.get("claim_id") == cid and _nonempty(item.get("answer")):
            return True
        if fp and item.get("question_fingerprint") == fp and _nonempty(item.get("answer")):
            return True
    return False


def build_packet(claims: list[dict], decisions: list[dict]) -> tuple[list[dict], list[dict]]:
    """Return (open_entries, skipped_already_answered)."""
    open_entries: list[dict] = []
    skipped: list[dict] = []
    for claim in claims:
        if not claim.get("id"):
            continue
        if is_answered(claim, decisions):
            skipped.append({"claim_id": claim["id"], "reason": "already-answered"})
            continue
        entry = entry_from_claim(claim)
        if is_answered(entry, decisions):
            skipped.append({"claim_id": claim["id"], "reason": "fingerprint-answered"})
            continue
        errors = validate_entry(entry)
        if errors:
            raise ValueError(f"unshippable packet entry {claim['id']}: {errors}")
        open_entries.append(entry)
    return open_entries, skipped


def record_answer(
    decisions: list[dict],
    *,
    claim_id: str,
    question: str,
    answer: str,
    source: str,
    recorded_at: str,
) -> list[dict]:
    if not _nonempty(answer):
        raise ValueError("empty-answer")
    fp = fingerprint(question)
    next_rows = [dict(item) for item in decisions if item.get("claim_id") != claim_id]
    next_rows.append(
        {
            "claim_id": claim_id,
            "question": question,
            "question_fingerprint": fp,
            "answer": answer.strip(),
            "source": source,
            "recorded_at": recorded_at,
        }
    )
    return next_rows
