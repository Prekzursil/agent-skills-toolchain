    add("percent", "%PROGRAMFILES(X86)%")
    add("percent", "%COMMONPROGRAMFILES%")
    add("percent", "%ALLUSERSPROFILE%")
    add("percent", "%PUBLIC%")
    add("percent", "%OneDrive%")
    add("percent", "cmd /c echo %PATH%")
    add("percent", "%PATH% & echo x")
    add("percent", "%PATH%|more")
    add("percent", "%PATH%>nul")
    add("percent", "set x=%PATH%")
    add("percent", "%PATH:~0,1%")
    add("percent", "%PATH:~-1%")
    add("percent", "!PATH!")  # delayed expansion cousin
    add("percent", "%PATH%%CD%")
    add("percent", "%%%PATH%%%")
    add("percent", "%UNDEFINED_TST0193%")
    add("percent", "100% done %PATH%")
    add("percent", "%PATH%\n%CD%")
    add("percent", "%PATH%\r\n%CD%")
    add("percent", "'%PATH%'")
    add("percent", '"%PATH%"')
    add("percent", "%PATH%$(true)")

    add("mixed", f"'; $(touch {canary}); '")
    add("mixed", f'"; $(touch {canary}); "')
    add("mixed", f"$(touch {canary}) %PATH% `id`")
    add("mixed", "it's a $(date) value")
    add("mixed", 'quote"inside$(true)')
    add("mixed", r"dollar\$notsub")
    add("mixed", "line1\n$(true)\nline3")
    add("mixed", "crlf\r\n$(true)")
