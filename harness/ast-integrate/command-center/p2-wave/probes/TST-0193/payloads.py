    add("powershell", f"$(New-Item -ItemType File -Path {canary})")
    add("powershell", "$(Get-Date)")
    add("powershell", "$(Get-Process)")
    add("powershell", f"$(Set-Content -Path {canary} -Value x)")
    add("powershell", "`$(Get-Date)")  # PS escaped subexpression
    add("powershell", "$(Write-Output x)")
    add("powershell", "iex $(Get-Date)")
    add("powershell", "& { Get-Date }")
    add("powershell", "$(1+1)")
    add("powershell", f"; New-Item {canary}")
    add("powershell", "$(Get-Content env:PATH)")
    add("powershell", "$env:PATH")
    add("powershell", "%PATH%;$(Get-Date)")
    add("powershell", "`" + f"touch {canary}`")
    add("powershell", "$(Get-ChildItem)")
    add("powershell", "$(Out-File -FilePath x)")
