    add("powershell", "@($(Get-Date))")
    add("powershell", "$(Get-Date | Out-String)")
    add("powershell", "$($(Get-Date))")
    add("powershell", "if($true){$(Get-Date)}")
    add("powershell", "\"$(Get-Date)\"")
    add("powershell", "'$(Get-Date)'")
    add("powershell", "$(Get-Date)#cmt")
    add("powershell", "$(Get-Date)`n")
    add("powershell", "$(Get-Date)`r`n")
    add("powershell", "$(Get-Date) %COMSPEC%")
    add("powershell", "$(Get-Host)")
    add("powershell", "$(Get-Location)")
    add("powershell", "$(pwd)")
    add("powershell", "$(ls)")
    add("powershell", "$(dir)")
    add("powershell", "$(echo $PID)")
    add("powershell", "$(Write-Host x)")
    add("powershell", "$(Remove-Item -Force x)")
