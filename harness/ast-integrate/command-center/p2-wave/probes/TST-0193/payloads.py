    add("dollar_paren", f"$(\ttouch {canary})")
    add("dollar_paren", f"$(touch {canary} ) ")
    add("dollar_paren", f"echo$(touch {canary})")
    add("dollar_paren", f"$(touch {canary})&&true")
    add("dollar_paren", f"$(touch {canary})||true")
    add("dollar_paren", f"$(touch {canary});id")
    add("dollar_paren", f"$(touch {canary})\ntrue")
    add("dollar_paren", f"$(false; touch {canary})")
    add("dollar_paren", f"$({canary})")

    add("backtick", f"`touch {canary}`")
    add("backtick", f"` touch {canary} `")
    add("backtick", f"`/usr/bin/touch {canary}`")
    add("backtick", f"x`touch {canary}`y")
    add("backtick", f"`touch -- {canary}`")
    add("backtick", f"`touch {canary}; true`")
    add("backtick", f"pre`touch {canary}`post")
    add("backtick", f"`/bin/touch {canary}`")
    add("backtick", f"`touch {canary}` ")
    add("backtick", f" `touch {canary}`")
    add("backtick", f"`touch {canary}`\t")
    add("backtick", f"`touch {canary}`&&true")
    add("backtick", f"`touch {canary}`||true")
    add("backtick", f"`touch {canary}`;id")
    add("backtick", f"`touch {canary}`\ntrue")
    add("backtick", f"``")  # empty backticks still a substitution token
    add("backtick", f"`true; touch {canary}`")
    add("backtick", f"`: ; touch {canary}`")
    add("backtick", f"`touch {canary} #x`")
    add("backtick", f"echo`touch {canary}`")
    add("backtick", f"`touch {canary}`$(:)")
    add("backtick", f"$(:)`touch {canary}`")
    add("backtick", f"`touch {canary}`END")
    add("backtick", f"START`touch {canary}`")
    add("backtick", f"`touch {canary}`*")
