"""300 injection payloads for TST-0193 property testing."""
from __future__ import annotations


def injection_payloads(canary: str) -> list[dict[str, str]]:
    """Return exactly 300 unique payloads. Each carries a TST0193Pxxx token."""
    rows: list[dict[str, str]] = []

    def add(family: str, body: str) -> None:
        n = len(rows)
        token = f"TST0193P{n:03d}"
        value = f"{body}{token}"
        rows.append({"family": family, "token": token, "value": value})

    add("dollar_paren", f"$(touch {canary})")
    add("dollar_paren", f"$( touch {canary} )")
    add("dollar_paren", f"$(/usr/bin/touch {canary})")
    add("dollar_paren", f"$(touch -- {canary})")
    add("dollar_paren", f"$(touch {canary}; true)")
    add("dollar_paren", f"$(touch {canary} && true)")
    add("dollar_paren", f"x$(touch {canary})y")
    add("dollar_paren", f"$(/bin/touch {canary})")
    add("dollar_paren", f"$(command touch {canary})")
    add("dollar_paren", f"$(touch {canary} | true)")
    add("dollar_paren", f"$( : ; touch {canary} )")
    add("dollar_paren", f"$(printf x; touch {canary})")
    add("dollar_paren", f"$(touch {canary} #cmt\n)")
    add("dollar_paren", f"$(IFS=; touch {canary})")
    add("dollar_paren", f"$(touch {canary})$(:)")
    add("dollar_paren", f"pre$(touch {canary})post")
