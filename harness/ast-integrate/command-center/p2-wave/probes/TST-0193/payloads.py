    add("benign_token", "caret^rev")
    add("benign_token", "percent100")  # not a %VAR% pair
    add("benign_token", "dollar")
    add("benign_token", "backtick-word")
    add("benign_token", "empty-adjacent")
    add("benign_token", "unicode-naïve")
    add("benign_token", "crlf-benign\r\nnext")
    add("benign_token", "lf-benign\nnext")
    add("benign_token", "tab-benign\there")
    add("benign_token", "-leading-dash")
    add("benign_token", "--flag-shaped")
    add("benign_token", "json {\"a\":1}")
    add("benign_token", "xml <a>b</a>")
    add("benign_token", "url https://example.invalid/x")
    add("benign_token", "path /usr/bin/true")
    add("benign_token", "winpath C:\\Windows\\System32")
    add("benign_token", "unc\\\\server\\share")

    # Deterministic padding to exactly 300 unique values.
    families = ("dollar_paren", "backtick", "percent", "mixed", "powershell", "benign_token")
    n = 0
    while len(rows) < 300:
        fam = families[n % len(families)]
        if fam == "dollar_paren":
            body = f"$(touch {canary}; echo pad{n})"
        elif fam == "backtick":
            body = f"`touch {canary}; echo pad{n}`"
        elif fam == "percent":
            body = f"%PATH%pad{n}%"
        elif fam == "mixed":
            body = f"mix{n}$(true)`id`%CD%"
        elif fam == "powershell":
            body = f"$(Get-Date)pad{n}"
        else:
            body = f"pad-benign-{n}-value"
        add(fam, body)
        n += 1

    if len(rows) != 300:
        raise RuntimeError(f"expected 300 payloads, got {len(rows)}")
    values = [r["value"] for r in rows]
    if len(set(values)) != 300:
        raise RuntimeError("payload values are not unique")
    return rows
