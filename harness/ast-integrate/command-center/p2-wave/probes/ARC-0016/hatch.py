"""Reproduce the A2 escape-hatch class against the live generator.

Typed path: opaque_body is refused (schema additionalProperties false,
then generator BANNED_KEYS).

Hatch path: copy opaque_body into generated bytes. Capture-back of a
hand-edit into opaque_body makes that hand-edit CLEAN on regenerate —
exactly the drift generated-SSOT exists to prevent.

Blast radius: one shared-path bug in provenance() is counted by
comparing generate() bytes, not asserted.
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
GEN_DIR = HERE.parent / "ARC-0010"
sys.path.insert(0, str(GEN_DIR))
import generator as G  # noqa: E402

MARKER = "<!-- HATCH-DRIFT-OPAQUE-BODY-MARKER -->\n"
OPAQUE_LIVE_COMMENT = (
    "<!-- live-larger comment and formatting not captured by typed fields -->\n"
)


def load_registry() -> dict[str, Any]:
    return G.load_default_registry()


def _skill_rel(files: dict[str, bytes]) -> str:
    for rel in sorted(files):
        if rel.startswith("skills/") and rel.endswith("SKILL.md"):
            return rel
    raise RuntimeError("no skill artifact in generate() output")


def typed_rejects_opaque_body(registry: dict[str, Any] | None = None) -> dict[str, Any]:
    """Adding opaque_body to a live skill entry must fail validate_registry."""
    registry = copy.deepcopy(registry or load_registry())
    target = None
    for entry in registry["entries"]:
        if entry.get("kind") == "skill":
            entry["opaque_body"] = OPAQUE_LIVE_COMMENT
            target = entry["id"]
            break
    if target is None:
        return {"rejected": False, "error": "no-skill-entry"}
    try:
        G.validate_registry(registry)
    except Exception as exc:
        return {
            "rejected": True,
            "entry_id": target,
            "error_type": type(exc).__name__,
            "error": str(exc)[:500],
        }
    return {"rejected": False, "entry_id": target, "error": None}


def generate_with_hatch(registry: dict[str, Any]) -> dict[str, bytes]:
    """Mutant generator: strip banned keys, generate typed, copy opaque_body onto the matching artifact."""
    stripped = copy.deepcopy(registry)
    opaques: dict[str, str] = {}
    for entry in stripped["entries"]:
        blob = entry.pop("opaque_body", None)
        if blob is None:
            continue
        if not isinstance(blob, str):
            raise TypeError("opaque_body must be str")
        opaques[entry["id"]] = blob
    files = G.generate(stripped)
    out: dict[str, bytes] = {}
    for rel, data in files.items():
        prov = G.parse_provenance(data)
        rid = (prov or {}).get("registry_id")
        if rid in opaques:
            out[rel] = data + opaques[rid].encode("utf-8")
        else:
            out[rel] = data
    return out


def blast_radius(registry: dict[str, Any] | None = None) -> dict[str, Any]:
    """Count files whose bytes change when provenance() is buggy. Shared helper = all artifacts."""
    registry = registry or load_registry()
    clean = G.generate(registry)
    n = len(clean)
    orig = G.provenance

    def buggy(entry: dict[str, Any]) -> dict[str, str]:
        p = orig(entry)
        p["generator_version"] = "0.0.0-bug"
        return p

    G.provenance = buggy  # type: ignore[assignment]
    try:
        dirty = G.generate(registry)
    finally:
        G.provenance = orig
    affected = sorted(k for k in clean if clean[k] != dirty.get(k))
    return {
        "computed_not_asserted": True,
        "method": (
            "Monkey-patch generator.provenance to rewrite generator_version to "
            "0.0.0-bug (the helper every renderer calls), then count generate() "
            "paths whose bytes differ from the unpatched run."
        ),
        "generator": "command-center/p2-wave/probes/ARC-0010/generator.py",
        "generated_file_count": n,
        "files_affected_by_one_shared_path_bug": len(affected),
        "affected_paths": affected,
        "bug": "provenance.generator_version rewritten to 0.0.0-bug",
    }


def run_drift_demo(tmp: Path, registry: dict[str, Any] | None = None) -> dict[str, Any]:
    """Typed hand-edit stays TAMPERED; hatch capture-back makes the same edit CLEAN."""
    registry = copy.deepcopy(registry or load_registry())
    clean = G.generate(registry)
    skill_rel = _skill_rel(clean)

    typed_root = tmp / "typed"
    G.write_tree(clean, typed_root)
    skill_path = typed_root / skill_rel
    skill_path.write_bytes(skill_path.read_bytes() + MARKER.encode("utf-8"))
    typed_rows = G.classify_tree(typed_root, registry)
    typed_skill = next(r for r in typed_rows if r["path"] == skill_rel)
    typed_tampered = typed_skill.get("status") == "TAMPERED"

    G.write_tree(clean, typed_root)
    restored = G.classify_tree(typed_root, registry)
    typed_restore_clean = bool(restored) and all(r.get("status") == "CLEAN" for r in restored)
    restored_skill = (typed_root / skill_rel).read_bytes()
    typed_restore_dropped_marker = MARKER.encode("utf-8") not in restored_skill

    hatch_root = tmp / "hatch"
    G.write_tree(clean, hatch_root)
    hp = hatch_root / skill_rel
    hp.write_bytes(hp.read_bytes() + MARKER.encode("utf-8"))
    extra = hp.read_bytes()[len(clean[skill_rel]) :]
    hatch_reg = copy.deepcopy(registry)
    captured_id = None
    for entry in hatch_reg["entries"]:
        if entry.get("kind") == "skill":
            entry["opaque_body"] = extra.decode("utf-8")
            captured_id = entry["id"]
            break
    hatch_files = generate_with_hatch(hatch_reg)
    hatch_matches_handedit = hatch_files.get(skill_rel) == hp.read_bytes()
    hatch_marker_present = MARKER.encode("utf-8") in hatch_files.get(skill_rel, b"")

    G.write_tree(hatch_files, hatch_root)
    # Hatch-aware "CLEAN": regenerated hatch bytes equal the captured hand-edit.
    hatch_clean_after_capture = hatch_matches_handedit and hatch_marker_present

    return {
        "skill_rel": skill_rel,
        "captured_registry_id": captured_id,
        "typed_hand_edit_tampered": typed_tampered,
        "typed_restore_clean": typed_restore_clean,
        "typed_restore_dropped_marker": typed_restore_dropped_marker,
        "hatch_capture_back_clean": hatch_clean_after_capture,
        "hatch_matches_handedit": hatch_matches_handedit,
        "hatch_reintroduces_drift": bool(
            typed_tampered
            and typed_restore_dropped_marker
            and hatch_clean_after_capture
        ),
    }
