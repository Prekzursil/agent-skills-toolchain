#!/usr/bin/env python3
"""A2 generated-SSOT generator.

Determinism: same registry bytes + same generator version => byte-identical
outputs (LF JSON/markdown, sorted keys, no timestamps).

Hand-edit rule: if generated bytes differ from regeneration of the current
registry entry AND provenance.registry_entry_sha256 still matches that entry,
the file is TAMPERED (not legitimate drift). STALE means the registry entry
changed. Restore = regenerate.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
SCHEMA_PATH = HERE / "registry.schema.json"
DEFAULT_REGISTRY = HERE / "registry.json"

GENERATOR_ID = "a2-ssot-generator"
GENERATOR_VERSION = "1.0.0"
SCHEMA_ID = "a2-registry/v1"

BANNED_KEYS = frozenset(
    {
        "opaque_body",
        "passthrough",
        "untyped_blob",
        "raw_bytes",
        "escape_hatch",
        "executable_policy",
    }
)

KIND_TO_CLASS = {
    "plugin_manifest": "plugin_manifest",
    "marketplace_entry": "marketplace_entry",
    "skill": "skill_deployment",
    "hook": "hook_deployment",
    "rule": "rule_deployment",
    "doc": "docs",
    "workflow_blueprint": "workflow_blueprint",
    "council_preset": "council_preset",
    "workflow_catalog": "workflow_catalog",
    "council_catalog": "council_catalog",
}

HEADER_RE = re.compile(
    r"^<!-- a2-generated registry_id=(?P<rid>\S+) artifact_class=(?P<cls>\S+) "
    r"generator_id=(?P<gid>\S+) generator_version=(?P<ver>\S+) "
    r"registry_entry_sha256=(?P<sha>[0-9a-f]{64}) schema=(?P<schema>\S+) -->\n"
)


def canonical_json_bytes(obj: Any) -> bytes:
    return (
        json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=True) + "\n"
    ).encode("utf-8")


def entry_digest(entry: dict[str, Any]) -> str:
    payload = {k: v for k, v in entry.items() if k != "_generated"}
    raw = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def provenance(entry: dict[str, Any]) -> dict[str, str]:
    return {
        "registry_id": entry["id"],
        "artifact_class": KIND_TO_CLASS[entry["kind"]],
        "generator_id": GENERATOR_ID,
        "generator_version": GENERATOR_VERSION,
        "registry_entry_sha256": entry_digest(entry),
        "schema": SCHEMA_ID,
    }


def md_header(entry: dict[str, Any]) -> str:
    p = provenance(entry)
    return (
        f"<!-- a2-generated registry_id={p['registry_id']} "
        f"artifact_class={p['artifact_class']} "
        f"generator_id={p['generator_id']} "
        f"generator_version={p['generator_version']} "
        f"registry_entry_sha256={p['registry_entry_sha256']} "
        f"schema={p['schema']} -->\n"
    )


def json_with_prov(entry: dict[str, Any], payload: dict[str, Any]) -> bytes:
    body = dict(payload)
    body["_generated"] = provenance(entry)
    return canonical_json_bytes(body)


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def load_schema() -> dict[str, Any]:
    return load_json(SCHEMA_PATH)


def _reject_banned(obj: Any, loc: str) -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in BANNED_KEYS:
                raise ValueError(f"inexpressible:{loc}.{k}:opaque-passthrough")
            _reject_banned(v, f"{loc}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _reject_banned(v, f"{loc}[{i}]")


def validate_registry(registry: dict[str, Any]) -> None:
    import jsonschema

    jsonschema.Draft7Validator(load_schema()).validate(registry)
    if registry.get("generator_id") != GENERATOR_ID:
        raise ValueError("generator_id mismatch")
    if registry.get("generator_version") != GENERATOR_VERSION:
        raise ValueError("generator_version mismatch")
    seen: set[str] = set()
    for entry in registry["entries"]:
        eid = entry["id"]
        if eid in seen:
            raise ValueError(f"duplicate-registry-id:{eid}")
        seen.add(eid)
        _reject_banned(entry, eid)
    by_id = {e["id"]: e for e in registry["entries"]}
    for entry in registry["entries"]:
        kind = entry["kind"]
        refs: list[str] = []
        if kind == "plugin_manifest":
            refs = (
                list(entry["skill_ids"])
                + list(entry["hook_ids"])
                + list(entry["rule_ids"])
            )
        elif kind == "marketplace_entry":
            refs = [entry["plugin_id"]]
        elif kind in {"workflow_catalog", "council_catalog"}:
            refs = list(entry["member_ids"])
        for ref in refs:
            if ref not in by_id:
                raise ValueError(f"dangling-ref:{entry['id']}->{ref}")


def output_path(entry: dict[str, Any]) -> str:
    eid = entry["id"]
    kind = entry["kind"]
    mapping = {
        "plugin_manifest": "plugin.json",
        "marketplace_entry": f"marketplace/{eid}.json",
        "skill": f"skills/{eid}/SKILL.md",
        "hook": f"hooks/{eid}.json",
        "rule": f"rules/{eid}.md",
        "doc": f"docs/{eid}.md",
        "workflow_blueprint": f"workflows/{eid}.json",
        "council_preset": f"council/presets/{eid}.json",
        "workflow_catalog": "catalogs/workflows.json",
        "council_catalog": "catalogs/council.json",
    }
    if kind not in mapping:
        raise ValueError(f"unknown-kind:{kind}")
    return mapping[kind]


def _render_skill(entry: dict[str, Any]) -> bytes:
    roles = ", ".join(entry["roles"])
    text = (
        md_header(entry)
        + "---\n"
        + f"name: {entry['name']}\n"
        + f"description: {entry['description']}\n"
        + "---\n\n"
        + f"{entry['instructions']}\n\n"
        + f"Roles: {roles}\n"
    )
    return text.encode("utf-8")


def _render_markdown(entry: dict[str, Any], title: str, body: str) -> bytes:
    return (md_header(entry) + f"# {title}\n\n{body}\n").encode("utf-8")


def generate(registry: dict[str, Any]) -> dict[str, bytes]:
    validate_registry(registry)
    entries = sorted(registry["entries"], key=lambda e: (e["kind"], e["id"]))
    by_id = {e["id"]: e for e in entries}
    out: dict[str, bytes] = {}
    for entry in entries:
        kind = entry["kind"]
        path = output_path(entry)
        if kind == "skill":
            out[path] = _render_skill(entry)
        elif kind == "rule":
            out[path] = _render_markdown(entry, entry["title"], entry["body"])
        elif kind == "doc":
            out[path] = _render_markdown(entry, entry["title"], entry["body"])
        elif kind == "plugin_manifest":
            payload = {
                "description": entry["description"],
                "hooks": [output_path(by_id[i]) for i in sorted(entry["hook_ids"])],
                "name": entry["name"],
                "rules": [output_path(by_id[i]) for i in sorted(entry["rule_ids"])],
                "skills": [output_path(by_id[i]) for i in sorted(entry["skill_ids"])],
                "version": entry["version"],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "marketplace_entry":
            payload = {
                "category": entry["category"],
                "description": entry["description"],
                "name": entry["name"],
                "plugin_id": entry["plugin_id"],
                "version": entry["version"],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "hook":
            payload = {
                "enabled": entry["enabled"],
                "event": entry["event"],
                "id": entry["id"],
                "script": entry["script"],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "workflow_blueprint":
            payload = {
                "discovery_only": entry["discovery_only"],
                "id": entry["id"],
                "stages": entry["stages"],
                "stopping": entry["stopping"],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "council_preset":
            payload = {
                "id": entry["id"],
                "roles": entry["roles"],
                "stopping": entry["stopping"],
                "voting": entry["voting"],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "workflow_catalog":
            members = [by_id[i] for i in sorted(entry["member_ids"])]
            payload = {
                "id": entry["id"],
                "members": [
                    {
                        "discovery_only": m["discovery_only"],
                        "id": m["id"],
                        "stages": m["stages"],
                        "stopping": m["stopping"],
                    }
                    for m in members
                ],
            }
            out[path] = json_with_prov(entry, payload)
        elif kind == "council_catalog":
            members = [by_id[i] for i in sorted(entry["member_ids"])]
            payload = {
                "id": entry["id"],
                "members": [
                    {
                        "id": m["id"],
                        "roles": m["roles"],
                        "stopping": m["stopping"],
                        "voting": m["voting"],
                    }
                    for m in members
                ],
            }
            out[path] = json_with_prov(entry, payload)
        else:
            raise ValueError(f"unrendered-kind:{kind}")
    return out


def write_tree(files: dict[str, bytes], root: Path) -> None:
    if root.exists():
        for p in sorted(root.rglob("*"), reverse=True):
            if p.is_file():
                p.unlink()
            elif p.is_dir():
                try:
                    p.rmdir()
                except OSError:
                    pass
    root.mkdir(parents=True, exist_ok=True)
    for rel, data in sorted(files.items()):
        dest = root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)


def parse_provenance(raw: bytes) -> dict[str, str] | None:
    text = raw.decode("utf-8")
    stripped = text.lstrip()
    if stripped.startswith("{"):
        try:
            doc = json.loads(text)
        except json.JSONDecodeError:
            return None
        g = doc.get("_generated")
        if isinstance(g, dict) and g.get("registry_id") and g.get("generator_version"):
            return {str(k): str(v) for k, v in g.items()}
        return None
    m = HEADER_RE.match(text)
    if not m:
        return None
    return {
        "registry_id": m.group("rid"),
        "artifact_class": m.group("cls"),
        "generator_id": m.group("gid"),
        "generator_version": m.group("ver"),
        "registry_entry_sha256": m.group("sha"),
        "schema": m.group("schema"),
    }


def classify(
    path: Path, registry: dict[str, Any], expected: dict[str, bytes], rel: str
) -> dict[str, Any]:
    raw = path.read_bytes() if path.is_file() else b""
    prov = parse_provenance(raw) if raw else None
    by_id = {e["id"]: e for e in registry["entries"]}
    if rel not in expected:
        return {"path": rel, "status": "ORPHAN", "reason": "no-registry-output-path"}
    if not path.is_file():
        return {"path": rel, "status": "MISSING", "reason": "expected-file-absent"}
    if not prov:
        return {"path": rel, "status": "MISSING_PROVENANCE", "reason": "header-absent"}
    rid = prov.get("registry_id")
    if rid not in by_id:
        return {"path": rel, "status": "ORPHAN", "reason": "registry-id-absent"}
    current = entry_digest(by_id[rid])
    if prov.get("registry_entry_sha256") != current:
        return {
            "path": rel,
            "status": "STALE",
            "reason": "registry-entry-changed",
            "provenance_sha": prov.get("registry_entry_sha256"),
            "registry_sha": current,
        }
    if raw.replace(b"\r\n", b"\n") != expected[rel]:
        return {
            "path": rel,
            "status": "TAMPERED",
            "reason": "bytes-differ-registry-unchanged",
        }
    return {"path": rel, "status": "CLEAN", "reason": "matches-regeneration"}


def classify_tree(root: Path, registry: dict[str, Any]) -> list[dict[str, Any]]:
    expected = generate(registry)
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    if root.exists():
        for p in sorted(root.rglob("*")):
            if p.is_file():
                rel = p.relative_to(root).as_posix()
                seen.add(rel)
                rows.append(classify(p, registry, expected, rel))
    for rel in expected:
        if rel not in seen:
            rows.append({"path": rel, "status": "MISSING", "reason": "expected-file-absent"})
    return rows


def two_run_identical(registry: dict[str, Any]) -> tuple[bool, int]:
    a = generate(registry)
    b = generate(registry)
    return a == b, len(a)


def load_default_registry() -> dict[str, Any]:
    reg = load_json(DEFAULT_REGISTRY)
    validate_registry(reg)
    return reg
