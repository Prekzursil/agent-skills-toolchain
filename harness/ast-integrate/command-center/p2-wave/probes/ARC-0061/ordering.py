REQUIRED_FIELDS = (
    "id",
    "before_plane",
    "after_plane",
    "required_order",
    "failure_if_violated",
)


def constraints() -> list[dict[str, Any]]:
    return [dict(row) for row in CONSTRAINTS]


def validate_row(row: dict[str, Any]) -> str | None:
    for key in REQUIRED_FIELDS:
        val = row.get(key)
        if not isinstance(val, str) or len(val.strip()) < 3:
            return f"missing-or-short:{key}"
    return None


def assert_complete() -> list[str]:
    ids = [c["id"] for c in CONSTRAINTS]
    if len(ids) != len(set(ids)):
        return ["duplicate-constraint-id"]
    problems: list[str] = []
    for row in CONSTRAINTS:
        why = validate_row(row)
        if why:
            problems.append(f"{row.get('id')}:{why}")
    if len(CONSTRAINTS) < 8:
        problems.append("too-few-constraints")
    return problems
