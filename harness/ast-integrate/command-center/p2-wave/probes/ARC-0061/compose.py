def _present(rel: str) -> bool:
    return (REPO / rel).is_file()


def source_presence() -> dict[str, bool]:
    return {
        "A1_DESIGN": _present(A1_DESIGN),
        "A2_DESIGN": _present(A2_DESIGN),
        "A8_DESIGN": _present(A8_DESIGN),
        "A9_DESIGN": _present(A9_DESIGN),
        "A3_DESIGN": _present("command-center/phase3/A3/DESIGN.json"),
        "A4_DESIGN": _present("command-center/phase3/A4/DESIGN.json"),
        "A5_DESIGN": _present("command-center/phase3/A5/DESIGN.json"),
        "A6_DESIGN": _present("command-center/phase3/A6/DESIGN.json"),
        "A7_DESIGN": _present("command-center/phase3/A7/DESIGN.json"),
    }


def _envelope(rows: list[dict[str, Any]], kind: str) -> dict[str, Any]:
    return {
        "architecture_id": "A9",
        "kind": kind,
        "a9_design_present": _present(A9_DESIGN),
        "source_presence": source_presence(),
        "capability_to_authority": rows,
        "control_planes": sorted(
            {a for row in rows for a in row.get("authorities") or []}
        ),
    }


def clean_design() -> dict[str, Any]:
    rows = [dict(r, authorities=list(r["authorities"])) for r in CLEAN_ROWS]
    return _envelope(rows, "singular-hybrid")


def planted_design() -> dict[str, Any]:
    rows = [dict(r, authorities=list(r["authorities"])) for r in CLEAN_ROWS]
    for row in rows:
        if row["capability"] == "authorization":
            row["authorities"] = ["A7-permission-choke", "A8-product-surface"]
            row["planted"] = True
            row["note"] = (
                "Planted duplicate: A8 command surface grows its own permission "
                "check beside the A7 choke."
            )
    doc = _envelope(rows, "planted-duplicate")
    doc["planted_capability"] = "authorization"
    doc["planted_extra_authority"] = "A8-product-surface"
    return doc


def naive_union_design() -> dict[str, Any]:
    rows = [dict(r, authorities=list(r["authorities"])) for r in CLEAN_ROWS]
    for row in rows:
        if row["capability"] in {"capability-declaration", "generated-bytes"}:
            row["authorities"] = ["A1-static-loader", "A2-ssot-generator"]
            row["note"] = (
                "Naive compose keeps A1 static capability bytes and A2 generated "
                "bytes as co-authorities."
            )
    return _envelope(rows, "naive-a1-a2-union")


def empty_design() -> dict[str, Any]:
    return _envelope([], "empty-extraction-control")


def write_fixtures(directory: Path) -> dict[str, str]:
    directory.mkdir(parents=True, exist_ok=True)
    fx = directory / "fixtures"
    fx.mkdir(parents=True, exist_ok=True)
    mapping = {
        directory / "composed-design.json": clean_design(),
        fx / "clean.json": clean_design(),
        fx / "duplicate.json": planted_design(),
        fx / "naive-union.json": naive_union_design(),
        fx / "empty.json": empty_design(),
    }
    written: dict[str, str] = {}
    for path, doc in mapping.items():
        path.write_text(
            json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        written[path.name] = str(path.relative_to(REPO)).replace("\\", "/")
    return written
