def _p(
    pid: str,
    subject: str,
    claim_a: str,
    claim_b: str,
    *,
    source_a: str,
    source_b: str,
    catalog_unit: str,
    gold: bool = False,
    scope_a: str | None = None,
    scope_b: str | None = None,
    incompatible_values: bool = False,
    url_a: str = "",
    url_b: str = "",
    as_of_a: str = "2026-07-19",
    as_of_b: str = "2026-08-06",
    signals: dict | None = None,
    fetch_sha_a: str | None = None,
    fetch_sha_b: str | None = None,
    shared_upstream: bool = False,
    same_vendor_same_input: bool = False,
    copied_from: bool = False,
    measurement_method_differs: bool = False,
) -> dict:
    row = {
        "id": pid,
        "gold": gold,
        "subject": subject,
        "scope_a": scope_a or subject,
        "scope_b": scope_b or subject,
        "incompatible_values": incompatible_values,
        "shared_upstream": shared_upstream,
        "same_vendor_same_input": same_vendor_same_input,
        "copied_from": copied_from,
        "measurement_method_differs": measurement_method_differs,
        "signals": signals or {},
        "a": {
            "role": "R2",
            "subject": subject,
            "source": source_a,
            "catalog_unit": catalog_unit,
            "catalog_path": CATALOG,
            "claim": claim_a,
            "url": url_a,
            "as_of": as_of_a,
        },
        "b": {
            "role": "R1",
            "subject": subject,
            "source": source_b,
            "catalog_unit": catalog_unit,
            "catalog_path": CATALOG,
            "claim": claim_b,
            "url": url_b,
            "as_of": as_of_b,
        },
    }
    if fetch_sha_a:
        row["a"]["fetch_sha256"] = fetch_sha_a
    if fetch_sha_b:
        row["b"]["fetch_sha256"] = fetch_sha_b
    return row


