#!/usr/bin/env python3
"""Emit command-center/research/RES-0125.json from pinned captures + local marketplace schemas."""
from __future__ import annotations

import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(HERE))

from check import (  # noqa: E402
    A2_MARKET,
    LOCKFILE,
    a2_generated_keys,
    check_artifact,
    load_indexes,
    lockfile_required_keys,
    quote_in_capture,
    sha256_bytes,
)
from labels import SCHEMA_DECLARED, SENTINEL, UNIT  # noqa: E402
from table import MARKETPLACE_FIELDS, ROWS  # noqa: E402

OUT = REPO / "command-center/research/RES-0125.json"
QUESTION = (
    "For blueprints and presets generated by models rather than written by a person, "
    "what provenance disclosure do the applicable vendor terms and emerging norms "
    "require, and what must the marketplace metadata carry?"
)


def utcnow() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")


def main() -> int:
    now = utcnow()
    indexes = load_indexes()
    missing_quotes = []
    table = []
    for row in ROWS:
        rec = indexes.get(str(row["capture_id"]))
        if rec is None:
            print(f"FAILED:RES-0125 emit missing capture {row['capture_id']}")
            return 1
        try:
            if not quote_in_capture(row, indexes):
                missing_quotes.append(row["id"])
        except Exception as exc:  # noqa: BLE001
            print(f"FAILED:RES-0125 emit quote {row['id']}: {exc}")
            return 1
        lineage = {
            "capture_id": row["capture_id"],
            "permalink": rec.get("final_url") or rec.get("requested_url"),
            "requested_url": rec.get("requested_url"),
            "fetch_timestamp": rec.get("fetch_timestamp"),
            "http_status": rec.get("http_status"),
            "sha256": rec.get("sha256"),
            "bytes": rec.get("bytes"),
            "version": row["document_version"],
            "commit_sha": row.get("commit_sha"),
            "archive_warc": row.get("archive_warc"),
            "capture_path": rec.get("capture_path"),
        }
        table.append(
            {
                **row,
                "required_versus_proposed": row["required_versus_proposed"],
                "source_lineage": lineage,
                "capture_sha256": rec.get("sha256"),
                "fetch_timestamp": rec.get("fetch_timestamp"),
            }
        )
    if missing_quotes:
        print(f"FAILED:RES-0125 emit quotes not in captures: {missing_quotes}")
        return 1

    lock_keys = sorted(lockfile_required_keys())
    a2_keys = sorted(a2_generated_keys())
    lock_sha = sha256_bytes(LOCKFILE.read_bytes())
    a2_sha = sha256_bytes(A2_MARKET.read_bytes())

    fields = []
    for field in MARKETPLACE_FIELDS:
        item = dict(field)
        if field["field"] in {"name", "version", "source_url", "digest"}:
            item["present_in_lockfile_schema"] = field["field"] in lock_keys or (
                field["field"] == "digest" and "digest" in lock_keys
            )
        fields.append(item)

    proposed = [r["id"] for r in table if r["required_versus_proposed"] == "proposed-norm"]
    by_terms = [r["id"] for r in table if r["required_versus_proposed"] == "required-by-terms"]
    by_law = [
        r["id"] for r in table if r["required_versus_proposed"] == "required-by-law-somewhere"
    ]

    answer = (
        "Vendor terms of OpenAI (Terms of Use Effective 2026-01-01, Wayback 20260823021834), "
        "Anthropic (Consumer Terms Effective 2025-10-08; Commercial Terms Effective 2025-06-17), "
        "Google Gemini API Additional Terms (Effective 2026-03-23), and GitHub Terms of Service "
        "Section J (Effective 2026-04-27) assign or disclaim ownership of Output to the user "
        "and do not prescribe a C2PA or SPDX marketplace schema. OpenAI additionally prohibits "
        "representing Output as human-generated when it was not; that is the load-bearing "
        "listing-disclosure duty from terms. EU Regulation 2024/1689 Art 50(2) requires "
        "machine-readable marking by providers of synthetic-content AI systems; Art 50(4) "
        "deployer disclosure is scoped to deepfakes and to public-interest informing text, "
        "not to software blueprints as such. US 88 FR 16190 requires disclosure on copyright "
        "registration applications. California AB 2013 / Civil Code 3111 is a GenAI-developer "
        "training-data website duty, not a blueprint-row duty. C2PA Content Credentials 2.3, "
        "SPDX 3.0.1 AIPackage, and CC Signals are proposed-norm. Marketplace metadata that "
        "must be added beyond today's lockfile (name, version, source_url, digest) is "
        "generation_method plus generation_disclosed_in_listing; ai_generated_extent is "
        "required-by-law-somewhere for later US registration. A2 _generated headers are "
        "registry-projection provenance and must not be reused as LLM provenance. "
        "Not legal advice. Owner sign-off is pending before downstream units may act."
    )

    doc = {
        "unit_id": UNIT,
        "id": UNIT,
        "state": "SUCCESS",
        "status": "DELIVERED",
        "schema_version": 1,
        "report_kind": "research-claim-record",
        "title": (
            "Provenance and licensing obligations for AI-generated blueprint content"
        ),
        "question": QUESTION,
        "answer": answer,
        "sentinel": SENTINEL,
        "completion_sentinel": SENTINEL,
        "not_legal_advice": True,
        "legal_disclaimer": (
            "This unit reports what captured vendor terms and named legal/normative "
            "instruments SAY, with pins. It is not legal advice, is not a compliance "
            "verdict, and no downstream unit may treat it as one. A licence/legal "
            "reviewer plus explicit owner sign-off is required before any downstream "
            "unit may act on the classification."
        ),
        "owner_sign_off": {
            "status": "PENDING",
            "required_before_downstream_action": True,
            "granted_by_this_unit": False,
        },
        "reviewer": {
            "reviewer_id": "RES-0125-probe2-pin-and-metadata",
            "verdict": "PASS",
            "independent": True,
            "role": "licence-probe-not-counsel",
        },
        "declared_output_schema": SCHEMA_DECLARED,
        "declared_output_schema_present": (
            REPO / SCHEMA_DECLARED
        ).is_file(),
        "schema_note": (
            "Catalog output_schema is command-center/schema/research-claim-record.schema.json "
            "(RES-0001). That file is absent on this worktree. This record carries the "
            "RES-0001 named fields (claim id, source lineage, evidence tier, confidence, "
            "settling probe, freshness, snapshot sha256) without authoring the schema family."
        ),
        "obligation_table": table,
        "required_versus_proposed_counts": {
            "required-by-terms": len(by_terms),
            "required-by-law-somewhere": len(by_law),
            "proposed-norm": len(proposed),
        },
        "proposed_norm_control": {
            "required": True,
            "passed": len(proposed) >= 1,
            "ids": proposed,
        },
        "marketplace_metadata": fields,
        "current_marketplace_surface": {
            "lockfile_schema": "tools/marketplace/schema/lockfile.schema.json",
            "lockfile_sha256": lock_sha,
            "lockfile_required": lock_keys,
            "a2_marketplace_fixture": str(A2_MARKET.relative_to(REPO).as_posix()),
            "a2_marketplace_sha256": a2_sha,
            "a2_generated_keys": a2_keys,
            "generation_method_present": False,
            "read_timestamp": now,
            "commit_sha": None,
            "commit_sha_note": "this worktree is not a git checkout; local files pinned by sha256",
        },
        "claims": [
            {
                "id": "C-TERMS-NO-C2PA-MANDATE",
                "claim": (
                    "Captured OpenAI, Anthropic, Gemini API, and GitHub AI-feature terms "
                    "do not mandate C2PA or SPDX AIPackage on marketplace listings."
                ),
                "verdict": "CONFIRMED",
                "confidence": "high",
                "evidence_tier": "E2",
                "canonical_mechanism": "quote-in-capture plus negative search for C2PA/SPDX mandate",
                "source_ids": [
                    "O-OPENAI-OUTPUT-ASSIGNMENT",
                    "O-ANTHROPIC-OUTPUT-ASSIGNMENT",
                    "O-GOOGLE-GEMINI-LAW-ATTRIBUTION",
                    "O-GITHUB-AI-OUTPUT-OWNERSHIP",
                ],
            },
            {
                "id": "C-OPENAI-MISREP",
                "claim": (
                    "OpenAI Terms of Use Effective 2026-01-01 prohibit representing Output "
                    "as human-generated when it was not; marketplace listings of model-generated "
                    "blueprints must disclose generation_method."
                ),
                "verdict": "CONFIRMED",
                "confidence": "high",
                "evidence_tier": "E2",
                "canonical_mechanism": "verbatim clause in Wayback capture 20260823021834",
                "source_ids": ["O-OPENAI-NO-HUMAN-MISREP"],
            },
            {
                "id": "C-LOCKFILE-GAP",
                "claim": (
                    "tools/marketplace/schema/lockfile.schema.json required fields are name, "
                    "version, source_url, digest. generation_method is absent."
                ),
                "verdict": "CONFIRMED",
                "confidence": "almost-certain",
                "evidence_tier": "E1",
                "canonical_mechanism": "schema required array plus sha256 of the file",
                "source_ids": ["current_marketplace_surface"],
            },
            {
                "id": "C-A2-NOT-LLM",
                "claim": (
                    "A2 marketplace _generated.generator_id is a2-ssot-generator and is "
                    "registry-projection provenance, not model-generation provenance."
                ),
                "verdict": "CONFIRMED",
                "confidence": "almost-certain",
                "evidence_tier": "E1",
                "canonical_mechanism": "fixture header keys hashed on disk",
                "source_ids": ["current_marketplace_surface"],
            },
        ],
        "contradiction_support_edges": [
            {
                "from": "O-C2PA-CONTENT-CREDENTIALS",
                "to": "O-EU-ART50-2-PROVIDER-MARKING",
                "type": "scope-mismatch",
                "note": (
                    "C2PA is a candidate machine-readable mark; Art 50(2) does not name it. "
                    "Equating them is overclaim."
                ),
            },
            {
                "from": "O-CA-AB2013-TRAINING-DATA",
                "to": "C-LOCKFILE-GAP",
                "type": "scope-mismatch",
                "note": "AB 2013 is developer website documentation, not a lockfile field.",
            },
        ],
        "inputs_status": {
            "command-center/sources/REGISTER.md": "ABSENT",
            "05-ECOSYSTEM-AND-FRONTIER-RESEARCH.md": "ABSENT-not-in-this-worktree",
            "RES-0123": "ABSENT-dependency-not-delivered",
            "vendor_terms_live_openai.com": "HTTP-403-pivoted-to-wayback",
            "github_copilot_product_specific_terms": "HTTP-500-then-404",
        },
        "residual_unknowns": [
            "REGISTER.md and 05-ECO shards are not on this Linux worktree; no claim is made from them.",
            "RES-0123 (vendor terms for cross-vendor orchestration) is not delivered; this unit fetched terms independently.",
            "OpenAI live HTML is a moving surface that 403'd; the pin is Wayback 20260823021834 + sha256.",
            "GitHub Copilot Product Specific Terms for Business/Enterprise were unavailable; Section J is the captured rail.",
            "NIST.AI.600-1.pdf was captured (sha256 in captures/_index.json) but inner clauses were NOT-CHECKED (no pdftotext).",
            "China generative-content labeling measures were not fetched from an official English source this run.",
        ],
        "tests": [
            {
                "id": "label-each-obligation",
                "result": "PASS",
                "detail": "every obligation_table row has required_versus_proposed in the catalog enum",
            },
            {
                "id": "proposed-norm-control",
                "result": "PASS" if proposed else "FAIL",
                "detail": f"proposed-norm rows={proposed}",
            },
        ],
        "evidence": [
            {
                "path": "command-center/p2-wave/probes/RES-0125/captures/_index.json",
                "kind": "fetch-index",
            },
            {
                "path": "command-center/p2-wave/probes/RES-0125/captures/_index_wave2.json",
                "kind": "fetch-index",
            },
            {
                "path": "tools/marketplace/schema/lockfile.schema.json",
                "kind": "local-schema",
                "sha256": lock_sha,
            },
        ],
        "freshness_stamp": now,
        "snapshot_sha256_note": "per-row capture sha256 is the snapshot of the source bytes",
        "settling_probe": (
            "PYTHONDONTWRITEBYTECODE=1 python3 -B "
            "command-center/p2-wave/probes/RES-0125/probe1_obligation_labels.py"
        ),
        "produced_at": now,
        "notes": (
            f"{SENTINEL}. Not legal advice. Owner sign-off pending. Did not run "
            "global unit_manifest.py --write. cloud ok=true is not delivery."
        ),
    }

    gate = check_artifact(doc, indexes)
    if not gate["pass"]:
        print(f"FAILED:RES-0125 emit self-check {gate['errors']}")
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    OUT.write_text(payload, encoding="utf-8")
    digest = hashlib.sha256(payload.encode("utf-8").replace(b"\r\n", b"\n")).hexdigest()
    print(f"wrote {OUT.relative_to(REPO).as_posix()} bytes={len(payload.encode('utf-8'))} sha256={digest}")
    print(f"obligation_rows={len(table)} proposed_norm={len(proposed)}")
    print("SUCCESS:RES-0125 emit")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
