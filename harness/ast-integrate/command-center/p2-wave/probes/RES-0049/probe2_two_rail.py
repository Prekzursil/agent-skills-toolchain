#!/usr/bin/env python3
"""Probe 2: two-rail evidence, spec quotes, E3 mutant, independent refuter.

Does not re-parse GitHub Actions job graphs (probe 1). Reads pinned
spec captures and grades rails.
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(HERE))
import rails as R  # noqa: E402

ART = REPO / "command-center/research/RES-0049.json"

QUOTES = {
    "command-center/p2-wave/probes/RES-0049/captures/slsa-v1.0-levels.html": [
        "Signed provenance, generated by a hosted build platform",
        "Provenance showing how the package was built",
        "Build L2: Hosted build platform",
    ],
    "command-center/p2-wave/probes/RES-0049/captures/slsa-v1.0-requirements.html": [
        "not on an individual",
        "GitHub Actions, Google Cloud Build, Travis CI",
        "The build process MUST generate provenance",
    ],
    "command-center/p2-wave/probes/RES-0049/captures/in-toto-statement.md": [
        "https://in-toto.io/Statement/v1",
        "Each element MUST have `digest` set",
    ],
}


def fail(msg: str) -> int:
    print(f"FAILED:RES-0049-probe2 {msg}")
    return 1


def main() -> int:
    if not ART.is_file() or ART.stat().st_size <= 0:
        return fail("artifact missing")
    text = ART.read_text(encoding="utf-8")
    if "SUCCESS:RES-0049" not in text:
        return fail("sentinel-absent")
    doc = json.loads(text)
    st = str(doc.get("state") or "").upper()
    if st in {"BLOCKED", "FAILED", "SEVERED", "TIMEOUT"}:
        return fail(f"self-declared:{st}")

    ok, why = R.check_rails(REPO, doc)
    print(f"rails_ok={ok} {why}")
    if not ok:
        return fail(f"rails:{why}")

    mutant = copy.deepcopy(doc)
    dropped = False
    for claim in mutant["claims"]:
        if claim.get("id") == "C1-max-without-hosted-builder" and len(claim.get("rails") or []) >= 2:
            claim["rails"] = claim["rails"][:1]
            claim["evidence_tier"] = "E1"
            dropped = True
            break
    if not dropped:
        return fail("no-rail-to-drop")
    mok, mwhy = R.check_rails(REPO, mutant)
    print(f"mutant_one_rail_ok={mok} {mwhy}")
    if mok:
        return fail("one-rail-mutant-was-accepted")
    grade, gwhy = R.grade_claim(REPO, mutant["claims"][0])
    print(f"mutant_grade={grade} {gwhy}")
    if grade != "E3":
        return fail(f"one-rail-not-E3:{grade}")

    for rel, needles in QUOTES.items():
        body = (REPO / rel).read_text(encoding="utf-8", errors="replace")
        for needle in needles:
            if needle not in body:
                return fail(f"quote-miss:{rel}:{needle[:60]}")
            print(f"quote ok {rel} :: {needle[:48]}")

    lv = doc.get("level_verdict") or {}
    if "hosted" not in str(lv.get("named_delta_to_next_level") or "").lower():
        return fail("delta-missing-hosted")
    if lv.get("in_toto_every_agent_artifact") is not False:
        return fail("intoto-every-artifact-overclaim")
    if "SLSA Build L1" not in str(lv.get("achievable_without_hosted_builder") or ""):
        return fail("max-not-L1")

    rev = doc.get("reviewer") or {}
    if rev.get("independent") is not True:
        return fail("reviewer-not-independent")
    if str(rev.get("default") or "").upper() != "REFUTED":
        return fail("reviewer-default-not-REFUTED")

    refuted = [c for c in doc.get("claims") or [] if c.get("verdict") == "REFUTED"]
    if not refuted:
        return fail("no-REFUTED-claim")
    if refuted[0].get("id") != "C4-ubuntu-latest-is-not-l2":
        return fail("expected-C4-refuted")

    print("SUCCESS:RES-0049-probe2 two-rail E3-mutant spec-quotes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
