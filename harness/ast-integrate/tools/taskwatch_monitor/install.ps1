# install.ps1 — install taskwatch_monitor:
#   - Creates the venv at <ScriptDir>\.venv using uv sync
#   - Adds a PATH shim 'taskwatch.cmd' to the first existing user bin dir
#     (or $env:USERPROFILE\.local\bin if none exists yet)
#
# Usage:
#   .\install.ps1
#   .\install.ps1 -ShimDir "C:\my\bin"  # custom shim location
#
# Mirrors tools\mcp-manager\install.ps1 (the proven cov-gated template): same
# $ScriptDir pattern, same uv-sync + user-PATH-shim flow.

param(
    [string]$ShimDir = ""
)

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$UvExe     = "C:\Users\Prekzursil\.local\bin\uv.exe"

if (-not (Test-Path $UvExe)) {
    $UvExe = (Get-Command uv -ErrorAction SilentlyContinue)?.Source
    if (-not $UvExe) {
        Write-Error "uv not found. Install with: winget install astral-sh.uv"
        exit 1
    }
}

# ── 1. Create/update venv ─────────────────────────────────────────────────────
Write-Host "[install] Running uv sync in $ScriptDir ..."
Push-Location $ScriptDir
& $UvExe sync
if ($LASTEXITCODE -ne 0) {
    Pop-Location
    Write-Error "uv sync failed (exit $LASTEXITCODE). Aborting."
    exit 1
}
Pop-Location
Write-Host "[install] venv ready at $ScriptDir\.venv"

# ── 2. Determine shim directory ────────────────────────────────────────────────
if (-not $ShimDir) {
    $Candidates = @(
        "$env:USERPROFILE\.local\bin",
        "$env:APPDATA\Local\bin",
        "$env:USERPROFILE\bin"
    )
    foreach ($c in $Candidates) {
        if (Test-Path $c) { $ShimDir = $c; break }
    }
    if (-not $ShimDir) {
        # Create the first candidate
        $ShimDir = "$env:USERPROFILE\.local\bin"
        New-Item -ItemType Directory -Force -Path $ShimDir | Out-Null
        Write-Host "[install] Created shim directory: $ShimDir"
    }
}

# ── 3. Write taskwatch.cmd shim ───────────────────────────────────────────────
# The CLI uses relative imports (from . import engine, store) so it MUST be run
# as a module (python -m cli.app), never as a bare script path.
$ShimPath = Join-Path $ShimDir "taskwatch.cmd"
$UvRun    = $UvExe

@"
@echo off
REM taskwatch shim — generated by install.ps1
cd /d "$ScriptDir"
"$UvRun" run python -m cli.app %*
"@ | Set-Content -Path $ShimPath -Encoding ASCII

Write-Host "[install] Shim written: $ShimPath"

# ── 4. Ensure shim dir is on PATH (user scope) ────────────────────────────────
$UserPath = [System.Environment]::GetEnvironmentVariable("PATH", "User")
if ($UserPath -notlike "*$ShimDir*") {
    [System.Environment]::SetEnvironmentVariable(
        "PATH",
        "$ShimDir;$UserPath",
        "User"
    )
    Write-Host "[install] Added $ShimDir to user PATH. Restart your shell to pick it up."
} else {
    Write-Host "[install] $ShimDir is already on user PATH."
}

Write-Host ""
Write-Host "Installation complete."
Write-Host "  Run: taskwatch status --watch     (after restarting your shell)"
Write-Host "  Or:  .\launch.ps1                  (no restart needed)"
