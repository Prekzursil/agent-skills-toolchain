#!/usr/bin/env python3
r"""todo-surfacer/hook.py - FORGED inject discipline (Stop).

Generated by forge-discipline. Conforms to the dispatcher check-interface:
  main(argv) reads the hook payload on stdin and prints ONE hookSpecificOutput
  JSON (or nothing). It can be folded into _dispatch/manifest.json as a single
  line, or run standalone as its own settings.json command.

Trigger kind : response
Fires        : when the trigger matches the source; emits additionalContext.
Stays silent : otherwise (no output).
FAIL-OPEN    : any error -> exit 0, no output. Opt-out: env FORGE_TODO_SURFACER_OFF=1
               or a .disabled file in this directory.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

THIS = Path(__file__).resolve().parent
DISABLED = THIS / ".disabled"

NAME = "todo-surfacer"
EVENT = "Stop"
KIND = "response"
FIELD = None
ACTION = "You left {count} open TODO/FIXME marker(s) in your final message. Capture them as open loops before they are lost."
NEEDS_STATE = False
_PATTERN = re.compile("\\b(TODO|FIXME)\\b|- \\[ \\]", re.IGNORECASE)

_STATE_ROOT = Path(
    os.environ.get("FORGE_STATE_ROOT") or (Path.home() / ".claude" / "forge-state")
)
STATE_DIR = _STATE_ROOT / NAME
STATE_FILE = STATE_DIR / "ledger.ndjson"


def _disabled() -> bool:
    return DISABLED.exists() or os.environ.get(
        "FORGE_TODO_SURFACER_OFF", ""
    ).lower() in ("1", "on", "true")


def _dig(payload: dict, path):
    """Read a dotted path (e.g. 'tool_input.command') from the payload."""
    if not path:
        return None
    cur = payload
    for part in str(path).split("."):
        if isinstance(cur, dict):
            cur = cur.get(part)
        else:
            return None
    return cur


# See journey-coverage/check.py for the measurement behind this budget.
_TAIL_BYTES = 8 * 1024 * 1024


def _tail_lines(transcript_path):
    """Backward (newest-first) line iterator from the shared bounded reader, or None."""
    try:
        shared = str(Path(__file__).resolve().parent.parent / "_shared")
        if shared not in sys.path:
            sys.path.insert(0, shared)
        from transcript_tail import iter_tail_lines
    except Exception:
        return None
    return iter_tail_lines(transcript_path, max_bytes=_TAIL_BYTES)


def _parts(ev) -> list:
    """Text parts of ONE record — the unchanged per-record body of the original scan.

    A THIRD distinct variant in this repo: role is taken from `message` when that is a dict
    and from the record otherwise, content falls back to the record, bare-string blocks are
    kept, and the join is " ". Only the IO is shared; this predicate stays verbatim.
    """
    msg = ev.get("message") if isinstance(ev, dict) else None
    role = (msg or {}).get("role") if isinstance(msg, dict) else ev.get("role")
    if role != "assistant":
        return []
    content = (msg or ev).get("content")
    parts = []
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                parts.append(str(block.get("text") or ""))
            elif isinstance(block, str):
                parts.append(block)
    elif isinstance(content, str):
        parts.append(content)
    return parts


def _final_assistant_text_forward(transcript_path) -> tuple:
    """The original O(session-length) scan. Retained as the EXACTNESS fallback."""
    path = Path(transcript_path)
    if not path.exists():
        return "", False
    last = ""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    ev = json.loads(line)
                except Exception:
                    continue
                if not isinstance(ev, dict):
                    continue
                parts = _parts(ev)
                if parts:
                    last = " ".join(parts)
    except Exception:
        return "", False
    return last, True


def _final_assistant_text(transcript_path) -> tuple:
    """(text, ok) — last assistant message. O(tail), not O(session length).

    The forward scan settles on the LAST record with text parts; from EOF the FIRST such
    record is that same record, so the output is byte-identical by construction.
    `ok=False` means the transcript could not be READ (P2-01 NOT-CHECKED); an absent path is
    a separate state and returns `("", True)` — there is nothing to fail to read.
    """
    if not transcript_path:
        return "", True
    for line in _tail_lines(transcript_path) or ():
        try:
            ev = json.loads(line)
        except Exception:
            continue
        if not isinstance(ev, dict):
            continue
        parts = _parts(ev)
        if parts:
            return " ".join(parts), True
    return _final_assistant_text_forward(transcript_path)


def _source(payload: dict) -> tuple:
    """(source_text, ok). ok=False only when a transcript was named but unreadable."""
    if KIND == "always":
        return "", True
    if KIND == "response":
        return _final_assistant_text(payload.get("transcript_path"))
    return str(_dig(payload, FIELD) or ""), True


def _seen(key: str, session: str) -> bool:
    if not STATE_FILE.exists():
        return False
    try:
        with STATE_FILE.open("r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except Exception:
                    continue
                if rec.get("key") == key and rec.get("session") == session:
                    return True
    except Exception:
        return False
    return False


def _record(key: str, session: str, count: int) -> None:
    try:
        STATE_DIR.mkdir(parents=True, exist_ok=True)
        with STATE_FILE.open("a", encoding="utf-8") as fh:
            fh.write(
                json.dumps(
                    {"ts": time.time(), "session": session, "key": key, "count": count}
                )
                + "\n"
            )
    except Exception:
        pass


def build_message(payload: dict):
    """Pure predicate: return the additionalContext string, or None to stay silent."""
    if _disabled():
        return None
    if KIND == "always":
        return ACTION.replace("{count}", "0")
    src, ok = _source(payload)
    if not ok:
        # TYPED SILENCE (P2-01): a transcript was named and could not be read, so the final
        # message was never scanned for open markers. Previously indistinguishable from
        # "scanned it, found none" — both produced zero bytes.
        return (
            "NOT-CHECKED: your final message could not be read (transcript unreadable), so "
            "it was NOT scanned for open TODO/FIXME markers. This silence is not a pass."
        )
    if not src:
        return None
    count = len(list(_PATTERN.finditer(src)))
    if count == 0:
        return None
    if NEEDS_STATE:
        session = str(payload.get("session_id") or "default")
        # nosemgrep: python.lang.security.insecure-hash-algorithms.insecure-hash-algorithm-sha1 -- non-cryptographic dedup key, not a security control
        key = hashlib.sha1(
            src.encode("utf-8", "replace"), usedforsecurity=False
        ).hexdigest()
        if _seen(key, session):
            return None
        _record(key, session, count)
    return ACTION.replace("{count}", str(count))


def main(argv=None) -> int:
    try:
        raw = sys.stdin.read() or "{}"
        try:
            payload = json.loads(raw)
        except Exception:
            payload = {}
        if not isinstance(payload, dict):
            payload = {}
        msg = build_message(payload)
        if msg:
            print(
                json.dumps(
                    {
                        "hookSpecificOutput": {
                            "hookEventName": EVENT,
                            "additionalContext": msg,
                        }
                    }
                )
            )
    except Exception:
        pass  # fail-open: never crash a session
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
