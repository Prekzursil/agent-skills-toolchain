"""DEPLOY -- render and install the ``agentrail.cmd`` shim, under a GUARD. PURE decision layer.

LEDGER-PROVEN DATA LOSS THIS GUARDS: ``New-Item -Force`` on an existing FILE truncates it. The
same class applies to any unconditional write. So the decision is a pure function of "does the
target already exist", it is unit-tested in both states, and there is a mutation row
(``deploy-guard-to-unconditional-write``) that removes the guard and requires the check to go
RED. The write itself goes through :class:`~agentrail.ports.RailFileSystem`, so nothing here
touches a real disk unless a caller hands it a real filesystem.

``-Force`` on a DIRECTORY is idempotent and safe; on a FILE it is destructive. That asymmetry is
why :meth:`~agentrail.ports.RailFileSystem.write_text` may create parent directories freely
while this module refuses to overwrite a file it did not just create.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from agentrail.ports import RailFileSystem

DEPLOY_ACTIONS: tuple[str, ...] = ("write", "skip-exists", "overwrite")
"""``skip-exists`` is the DEFAULT for an existing target. ``overwrite`` needs an explicit opt-in."""

SHIM_NAME = "agentrail.cmd"

MARKER = r"agentrail\agentrail\__init__.py"
"""What proves a candidate directory really is a tools root, rather than merely existing."""

_SHIM_HEAD = """@echo off
rem agentrail <args> -- config-driven multi-rail agent dispatch CLI.
rem THIN SHIM: the dispatch policy, the completion AND-gate, the closed failure taxonomy and the
rem argv cap all live in the fully-gated `agentspec` core; `agentrail` is the rail-binding shell
rem over it. This .cmd only puts both package roots on PYTHONPATH and hands off.
rem
rem The candidate roots below are tried IN ORDER and the first one that actually contains the
rem package wins. A single hardcoded root would be the same defect class as a hardcoded codex
rem path: a shim generated from a throwaway git worktree dies the moment that worktree is
rem pruned, and one generated from a checkout that has not merged yet is dead on arrival.
rem Generated by `agentrail deploy`. Re-run with --overwrite to refresh.
setlocal
set "AGENTRAIL_TOOLS="
"""

_SHIM_TAIL = f"""if not defined AGENTRAIL_TOOLS (
  echo FAILED:agentrail env-missing-agentrail no checkout carrying {MARKER} was found 1>&2
  echo next: check out a branch containing tools/agentrail, then re-run agentrail deploy --overwrite 1>&2
  exit /b 1
)
if defined PYTHONPATH (
  set "PYTHONPATH=%AGENTRAIL_TOOLS%\\agentrail;%AGENTRAIL_TOOLS%\\agentspec;%PYTHONPATH%"
) else (
  set "PYTHONPATH=%AGENTRAIL_TOOLS%\\agentrail;%AGENTRAIL_TOOLS%\\agentspec"
)
python -m agentrail %*
endlocal & exit /b %errorlevel%
"""
"""``endlocal`` alone RESETS ERRORLEVEL to 0, so a bare one made the shim exit 0 for EVERY
failure -- a fail-open gate on the only entry point used outside the checkout.

MEASURED, four-way control, each .cmd running ``python -c "sys.exit(7)"``::

    no_endlocal                                 -> exit 7   (propagates)
    with_endlocal                               -> exit 0   (clobbered)
    setlocal + endlocal (the shim's exact shape) -> exit 0   (clobbered)
    endlocal & exit /b %errorlevel%             -> exit 7   (the fix)

``%errorlevel%`` is expanded when ``cmd`` PARSES the line, which happens before ``endlocal``
runs on it, so the pre-reset value is the one that reaches ``exit /b``. Everything that
branches on the exit code -- CI, ``longrun``'s SUCCESS:/FAILED: wrapper, ``&&`` chaining, an
orchestrator's ``if errorlevel 1`` -- read success on an unresolvable executable, a refused
unverified rail, a policy violation and a severed stream until this line existed."""


@dataclass(frozen=True, slots=True)
class DeployDecision:
    """What a deploy WOULD do, decided before anything is written."""

    action: str
    target: str
    rationale: str

    @property
    def writes(self) -> bool:
        return self.action in {"write", "overwrite"}


def decide(target: str, *, exists: bool, overwrite: bool = False) -> DeployDecision:
    """The guard, as a pure function. ``exists`` comes from the caller's filesystem port."""
    if not target.strip():
        raise ValueError("deploy target must be non-empty")
    if not exists:
        return DeployDecision(
            action="write",
            target=target,
            rationale=f"{target} does not exist; writing a fresh shim",
        )
    if overwrite:
        return DeployDecision(
            action="overwrite",
            target=target,
            rationale=f"{target} exists and --overwrite was passed explicitly",
        )
    return DeployDecision(
        action="skip-exists",
        target=target,
        rationale=(
            f"{target} already exists; refusing to truncate it. Diff it and re-run with "
            f"--overwrite if the shim is genuinely stale."
        ),
    )


def render_shim(tools_dirs: Sequence[str]) -> str:
    """Render the .cmd body, probing ``tools_dirs`` in order for the first real checkout."""
    # Normalise FIRST, then de-duplicate: "/a/tools" and "/a/tools/" are the same root, and
    # emitting a probe twice would make the shim look like it has a fallback when it has one root.
    roots = tuple(
        dict.fromkeys(
            value.strip().rstrip("/\\").replace("/", "\\")
            for value in tools_dirs
            if value.strip()
        )
    )
    if not roots:
        raise ValueError("at least one non-empty tools_dir is required")
    probes = "".join(
        f'if not defined AGENTRAIL_TOOLS if exist "{root}\\{MARKER}" '
        f'set "AGENTRAIL_TOOLS={root}"\n'
        for root in roots
    )
    return f"{_SHIM_HEAD}{probes}{_SHIM_TAIL}"


def deploy_shim(
    fs: RailFileSystem,
    *,
    target: str,
    tools_dirs: Sequence[str],
    overwrite: bool = False,
) -> DeployDecision:
    """Decide, then write only if the decision says so. The ONLY write path in this module."""
    decision = decide(target, exists=fs.is_file(target), overwrite=overwrite)
    if decision.writes:
        fs.write_text(target, render_shim(tools_dirs))
    return decision
