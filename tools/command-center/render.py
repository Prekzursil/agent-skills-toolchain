"""Render the DERIVED command-center files from the catalog.

Three of the thirteen artifacts are pure functions of the catalog, so they are
generated rather than maintained: STATUS.md, OWNER-DECISIONS.md and
ARTIFACT-MANIFEST.json. A hand-maintained status page beside a machine-readable
catalog is two sources of truth, and the one a human edits is the one that goes
15 days stale while work continues -- the measured root cause this whole lane
exists to fix (`REGISTER.md:74`, RESUME.json).

`--check` re-renders in memory and diffs against disk, so CI can fail on drift
instead of discovering it a fortnight later.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

if __package__ in (None, ""):  # pragma: no cover - import shim for direct runs
    sys.path.insert(0, str(Path(__file__).resolve().parent))

import catalog as cat
import validate as val

GENERATED_BANNER = (
    "<!-- GENERATED by tools/command-center/render.py from WORK-UNIT-CATALOG.json. "
    "Do not hand-edit: run `python tools/command-center/close.py ...` and re-render. -->"
)

# The 13 files Prompt Two names at `_USER-PROMPTS.md:10590-10602`, plus the
# append-only event log at `:10603`.
CONTRACTED_ARTIFACTS = (
    "PROGRAM-CHARTER.md",
    "OWNER-DECISIONS.md",
    "WORK-UNIT-CATALOG.json",
    "DEPENDENCY-GRAPH.json",
    "ARTIFACT-MANIFEST.json",
    "CLAIM-REGISTRY.json",
    "TEST-REGISTRY.json",
    "RISK-REGISTER.md",
    "UNKNOWNS-REGISTER.md",
    "RELEASE-CHECKLIST.md",
    "ROLLBACK-MANIFEST.md",
    "RUNBOOK.md",
    "STATUS.md",
    "events/EVENTS.jsonl",
)

PROGRAM_ORDER = ("A-toolchain", "HARNESS", "MONITOR", "B-workflow_design")


def _table(rows: list[list[str]], header: list[str]) -> list[str]:
    out = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] * len(header)) + "|",
    ]
    out.extend(
        "| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |"
        for row in rows
    )
    return out


def render_status(catalog: dict[str, Any]) -> str:
    violations, stats = val.validate(catalog, graph=cat.build_graph(catalog))
    graph = cat.build_graph(catalog)
    ready = [
        node["id"]
        for node in graph["nodes"]
        if node["open"]
        and not [dep for dep in node["blocked_by"] if _is_open(catalog, dep)]
    ]
    blocked = [
        node["id"]
        for node in graph["nodes"]
        if node["open"] and node["id"] not in ready
    ]
    gated = sorted(
        item["id"] for item in cat.open_items(catalog) if item.get("owner_gate")
    )
    deferred = sorted(
        item["id"] for item in cat.open_items(catalog) if item.get("defer")
    )

    lines = [
        GENERATED_BANNER,
        "",
        "# STATUS",
        "",
        f"**{stats['open']} open / {stats['items']} total.** "
        f"Reachability: {'ALL items reach a final disposition' if not violations else str(len(violations)) + ' VIOLATIONS'}. "
        f"Graph: {stats['edges']} edges, acyclic={stats['acyclic']}.",
        "",
        "Regenerate: `python tools/command-center/render.py`. "
        "Verify: `python tools/command-center/validate.py`.",
        "",
        "## Open by program",
        "",
    ]
    rows = []
    for program in PROGRAM_ORDER:
        items = [
            item for item in cat.open_items(catalog) if item.get("program") == program
        ]
        rows.append(
            [
                program,
                str(len(items)),
                str(len([i for i in items if i["id"] in ready])),
                str(len([i for i in items if i["id"] in blocked])),
                str(len([i for i in items if i["id"] in gated])),
            ]
        )
    lines += _table(rows, ["program", "open", "ready", "blocked", "owner-gated"])
    lines += [
        "",
        "## Ready now (no open dependency)",
        "",
        ", ".join(sorted(ready)) or "_none_",
        "",
        "## Blocked (waiting on another item)",
        "",
        ", ".join(sorted(blocked)) or "_none_",
        "",
        "## Waiting on an owner answer",
        "",
        ", ".join(gated) or "_none_",
        "",
        "## Deferred (still open; returns on its own)",
        "",
        ", ".join(deferred) or "_none_",
        "",
        "## Critical path (register section 5, ordered)",
        "",
    ]
    lines += [
        "1. `R-B08` live credentials — owner decision + quarantine (rotation is the owner's).",
        "2. `R-B06` write the basic-memory notes — the measured cause of the forgetting.",
        "3. `R-M01` + `R-M02` one TOML stanza and a 13-file redeploy — highest yield per effort.",
        "4. `R-A03` + `R-A04` owner input packet and the de-scope ruling — gates all of Program A.",
        "5. `R-H01` + `R-H02` + `R-H03` make the resume pointer true and machine-readable.",
        "6. `R-H10` deploy the rule delta — 18 of 20 live rule files differ from the repo.",
        "7. `R-A28` + `R-A29` → `R-A30` → `R-A31` → `R-A01` — newly unblocked chain to Prompt Two.",
        "8. `R-H06` write honest PARTIAL receipts.",
        "9. `R-M18` enrol the monitor program.",
        "",
    ]
    if violations:
        lines += ["## VIOLATIONS", ""] + [f"- {entry}" for entry in violations] + [""]
    return "\n".join(lines)


def _is_open(catalog: dict[str, Any], item_id: str) -> bool:
    item = cat.by_id(catalog).get(item_id)
    return bool(item) and cat.is_open(item)


def render_owner_decisions(catalog: dict[str, Any]) -> str:
    questions = catalog.get("owner_questions", [])
    gated: dict[str, list[str]] = {}
    for item in cat.items(catalog):
        for gate in item.get("owner_gate", []) or []:
            gated.setdefault(str(gate), []).append(str(item["id"]))
    open_count = sum(1 for q in questions if str(q.get("state", "")).upper() == "OPEN")
    lines = [
        GENERATED_BANNER,
        "",
        "# OWNER-DECISIONS",
        "",
        f"**{open_count} open of {len(questions)}.** Send as ONE batch — the owner asked "
        "explicitly not to be interrupted piecemeal (`sources/REGISTER.md` section 6).",
        "",
        "An answered question is recorded here by flipping its `state` in "
        "`WORK-UNIT-CATALOG.json` and re-rendering; the items it gates then stop "
        "counting it as a live blocker and must show a next smallest action instead "
        "(validator check REACH-4).",
        "",
    ]
    rows = [
        [
            str(q.get("id", "")),
            str(q.get("state", "")),
            ", ".join(sorted(gated.get(str(q.get("id", "")), []))) or "—",
            str(q.get("text", ""))[:200],
        ]
        for q in questions
    ]
    lines += _table(rows, ["#", "state", "blocks", "question"])
    lines.append("")
    return "\n".join(lines)


def render_manifest(root: Path) -> dict[str, Any]:
    """Hash every contracted artifact ON DISK.

    Prompt Two's Phase 14 requires the manifest be *verified on disk* before a
    completion report; a manifest listing paths it never stat-ed is the "a file
    path in text is not proof the file exists" failure it names at `:10646`."""
    entries = []
    for name in CONTRACTED_ARTIFACTS:
        path = root / name
        if name == "ARTIFACT-MANIFEST.json":
            # A manifest cannot hash itself: writing the hash changes the bytes
            # that were hashed, so `--check` would report drift forever. Record
            # presence, which is the part that is actually verifiable.
            # `present` is constant True, not `path.is_file()`: at generation time
            # the file does not exist yet and at check time it does, so probing it
            # would make the manifest disagree with itself on every first run.
            entries.append(
                {
                    "path": f"command-center/{name}",
                    "present": True,
                    "bytes": 0,
                    "sha256": "(self)",
                }
            )
        elif path.is_file():
            raw = path.read_bytes()
            entries.append(
                {
                    "path": f"command-center/{name}",
                    "present": True,
                    "bytes": len(raw),
                    "sha256": hashlib.sha256(raw).hexdigest(),
                }
            )
        else:
            entries.append(
                {
                    "path": f"command-center/{name}",
                    "present": False,
                    "bytes": 0,
                    "sha256": "",
                }
            )
    return {
        "schema_version": cat.SCHEMA_VERSION,
        "contract": "_USER-PROMPTS.md:10590-10603 (13 files + append-only event logs)",
        "derivation": "tools/command-center/render.py:render_manifest",
        "verified_on_disk": True,
        "present": sum(1 for entry in entries if entry["present"]),
        "expected": len(CONTRACTED_ARTIFACTS),
        "artifacts": entries,
    }


def outputs(root: Path, catalog: dict[str, Any]) -> dict[Path, str]:
    """path -> exact intended text content (the manifest is JSON, handled apart)."""
    return {
        root / "STATUS.md": render_status(catalog),
        root / "OWNER-DECISIONS.md": render_owner_decisions(catalog),
    }


def write_all(root: Path, catalog: dict[str, Any]) -> list[Path]:
    written: list[Path] = []
    for path, text in outputs(root, catalog).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            text if text.endswith("\n") else text + "\n", encoding="utf-8", newline="\n"
        )
        written.append(path)
    manifest_path = root / "ARTIFACT-MANIFEST.json"
    cat.save(render_manifest(root), manifest_path)
    written.append(manifest_path)
    return written


def check_all(root: Path, catalog: dict[str, Any]) -> list[str]:
    drift: list[str] = []
    for path, text in outputs(root, catalog).items():
        want = text if text.endswith("\n") else text + "\n"
        if not path.is_file():
            drift.append(f"{path.name} missing")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != want:
            drift.append(f"{path.name} differs from its rendering")
    manifest_path = root / "ARTIFACT-MANIFEST.json"
    if not manifest_path.is_file():
        drift.append("ARTIFACT-MANIFEST.json missing")
    else:
        on_disk = json.loads(manifest_path.read_text(encoding="utf-8"))
        # The manifest hashes its siblings, so compare against a rendering taken
        # with the siblings in their INTENDED state, not their current one.
        if on_disk != render_manifest(root):
            drift.append("ARTIFACT-MANIFEST.json does not match the files on disk")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(cat.command_center_dir()))
    parser.add_argument("--catalog", default=None)
    parser.add_argument(
        "--check", action="store_true", help="fail on drift instead of rewriting"
    )
    args = parser.parse_args(argv)
    root = Path(args.root)
    try:
        catalog = cat.load(args.catalog) if args.catalog else cat.load()
    except Exception as exc:
        print(f"FAILED:cc-render cannot read the catalog: {exc}")
        return 1
    if args.check:
        drift = check_all(root, catalog)
        for entry in drift:
            print(f"  {entry}")
        if drift:
            print(f"FAILED:cc-render drift={len(drift)}")
            return 1
        print("SUCCESS:cc-render no drift")
        return 0
    written = write_all(root, catalog)
    print(f"SUCCESS:cc-render wrote={len(written)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry
    raise SystemExit(main())
