"""Render the DERIVED command-center files from the catalog.

Two of the thirteen artifacts are pure functions of the catalog, so they are
generated rather than maintained: OWNER-DECISIONS.md and ARTIFACT-MANIFEST.json.
STATUS.md is owned by CC-0013 (`command-center/status_derive.py`): it is a
measurement from EVENTS.jsonl + receipts + the shared completion predicate, and
its hand-edit gate is `command-center/status_gate.py`. This module still lists
STATUS.md in CONTRACTED_ARTIFACTS so the manifest hashes the on-disk file, but
it no longer regenerates STATUS.md from the register catalog.

`--check` re-renders in memory and diffs against disk, so CI can fail on drift
instead of discovering it a fortnight later.
"""

