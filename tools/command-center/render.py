# Committed-blob reader (IMP-0439). Loaded lazily so a missing measure-guard package
# fails closed at hash time rather than at import of this module.
_BLOBREAD = None


def _blobread():
    global _BLOBREAD
    if _BLOBREAD is None:
        blob_path = Path(__file__).resolve().parents[1] / "measure-guard" / "blobread.py"
        import importlib.util

        spec = importlib.util.spec_from_file_location("blobread", blob_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot load {blob_path}")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _BLOBREAD = mod
    return _BLOBREAD


def provenance_bytes(root: Path, name: str) -> bytes:
    """Bytes that provenance must hash: the COMMITTED blob when available and clean.

    IMP-0439: hashing raw working-tree bytes made Windows (core.autocrlf=true) and
    Linux disagree. Prefer ``git cat-file -p``. When the working tree is dirty
    relative to HEAD (e.g. just-written derived STATUS.md), fall back to
    LF-normalised working-tree bytes — those are what will be committed and are
    platform-stable. Never hash raw CRLF working-tree bytes as if they were the blob.
    """
    path = root / name
    if not path.is_file():
        return b""
    wt_raw = path.read_bytes()
    wt_lf = wt_raw.replace(b"\r\n", b"\n")
    rel = f"command-center/{name}".replace("\\", "/")
    repo = root.parent
    try:
        blob = _blobread().read_blob(rel, "HEAD", repo=repo)
    except Exception:
        return wt_lf
    # Clean checkout (LF worktree or CRLF+norm == blob): trust the blob.
    # Dirty / just-rendered derived file: trust LF worktree (pending commit).
    return blob if wt_lf == blob else wt_lf


def working_tree_raw_hash(root: Path, name: str) -> str:
    """SHA-256 of raw working-tree bytes (no LF normalisation). Control for IMP-0439."""
    path = root / name
    if not path.is_file():
        return ""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def blob_hash(root: Path, name: str) -> str:
    """SHA-256 of the committed blob, or empty string if unreadable."""
    rel = f"command-center/{name}".replace("\\", "/")
    try:
        data = _blobread().read_blob(rel, "HEAD", repo=root.parent)
    except Exception:
        return ""
    return hashlib.sha256(data).hexdigest()


