#!/usr/bin/env python3
"""
wiztree_analyze.py — stream a WizTree full CSV export and produce a space-reclaim
report: safe-to-delete slop (regenerable, no personal data) vs decision-needed
(large files/folders that may be personal or belong to active projects).

Memory-light: single streaming pass, keeps only bounded top-N heaps + category sums.
Never deletes anything. Output is a markdown report + a machine-readable JSON sidecar.

Usage:
  python wiztree_analyze.py "<wiztree_csv>" [--out <report.md>] [--top 120] [--min-file-mb 200] [--min-folder-mb 500]
"""
import csv, sys, os, json, heapq, argparse, datetime

# (label, [lowercased path tokens], autonomy)  -- FIRST match wins (order = priority)
# autonomy: SAFE = regenerable, no personal data, safe to auto-clear
#           REVIEW = could be needed / active project / personal -> present, do not auto-delete
CATEGORIES = [
    ("Recycle Bin",                 ["$recycle.bin"],                                   "SAFE"),
    ("Windows Temp",                ["\\appdata\\local\\temp\\", "\\windows\\temp\\", "\\local\\temp\\"], "SAFE"),
    ("Crash dumps / WER",           [".dmp", "\\crashdumps\\", "\\windows\\minidump\\", "\\wer\\", "werfault"], "SAFE"),
    ("Windows Update cache",        ["\\softwaredistribution\\download\\", "\\windows\\installer\\$patchcache$"], "SAFE"),
    ("Delivery Optimization",       ["\\deliveryoptimization\\"],                       "SAFE"),
    ("Thumbnail/icon cache",        ["\\explorer\\thumbcache", "\\explorer\\iconcache"], "SAFE"),
    ("Browser/Electron HTTP cache", ["\\code cache\\", "\\gpucache\\", "\\cache_data\\",
                                     "\\service worker\\cachestorage\\", "\\dawncache\\",
                                     "\\component_crx_cache\\", "\\graphitedawncache\\"], "SAFE"),
    ("pip cache",                   ["\\pip\\cache\\", "\\.cache\\pip\\"],               "SAFE"),
    ("npm cache",                   ["\\npm-cache\\", "\\.npm\\_cacache\\"],             "SAFE"),
    ("uv / cargo / nuget cache",    ["\\uv\\cache\\", "\\.cargo\\registry\\cache\\",
                                     "\\.cargo\\registry\\src\\", "\\nuget\\v3-cache\\",
                                     "\\nuget\\packages\\"],                             "SAFE"),
    ("gradle / go cache",           ["\\.gradle\\caches\\", "\\go\\pkg\\mod\\cache\\"],  "SAFE"),
    ("HuggingFace/torch model cache",["\\huggingface\\hub\\", "\\.cache\\huggingface\\",
                                     "\\torch\\hub\\", "\\.cache\\torch\\"],             "REVIEW"),
    ("Docker/WSL disk images",      [".vhdx", "\\docker\\", "dockerdesktopwsl", "\\wsl\\"], "REVIEW"),
    ("node_modules",                ["\\node_modules\\"],                               "REVIEW"),
    ("build output (target/dist/.next)", ["\\target\\", "\\dist\\", "\\.next\\", "\\.turbo\\", "\\build\\"], "REVIEW"),
    ("__pycache__ / .pyc",          ["\\__pycache__\\", ".pyc"],                         "REVIEW"),
    ("venv / conda envs",           ["\\venv\\", "\\.venv\\", "\\site-packages\\", "\\envs\\", "\\anaconda3\\", "\\miniconda3\\"], "REVIEW"),
    ("Codex sessions/logs",         ["\\.codex\\sessions\\", "\\.codex\\log", "\\.codex\\archive"], "REVIEW"),
    ("Claude projects/todos",       ["\\.claude\\projects\\", "\\.claude\\todos\\", "\\.claude\\shell-snapshots\\"], "REVIEW"),
    ("Cursor cache/logs",           ["\\cursor\\", "\\.cursor\\"],                       "REVIEW"),
    ("Downloads",                   ["\\downloads\\"],                                   "REVIEW"),
    ("Installers (.msi/.iso/.exe)", [".iso", ".msi", "installer"],                       "REVIEW"),
]

def categorize(path_lower):
    for label, tokens, autonomy in CATEGORIES:
        for t in tokens:
            if t in path_lower:
                return label, autonomy
    return None, None

def human(n):
    n = float(n)
    for u in ("B","KB","MB","GB","TB"):
        if n < 1024 or u == "TB":
            return f"{n:.2f} {u}"
        n /= 1024

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--out", default=None)
    ap.add_argument("--top", type=int, default=120)
    ap.add_argument("--min-file-mb", type=int, default=200)
    ap.add_argument("--min-folder-mb", type=int, default=500)
    a = ap.parse_args()

    min_file = a.min_file_mb * 1024 * 1024
    min_folder = a.min_folder_mb * 1024 * 1024
    drive = "?"
    total_used = free = 0
    n_files = n_folders = 0
    cat_bytes = {}         # label -> [bytes, autonomy]
    top_files = []         # min-heap (size, path)
    top_folders = []       # min-heap (size, path)  depth>=4 folders

    with open(a.csv, "r", encoding="utf-8", errors="replace", newline="") as f:
        f.readline()                     # skip "Generated by WizTree" comment
        rdr = csv.reader(f)
        header = next(rdr, None)
        # WizTree CLI (11-col) and GUI (23-col) exports differ; find columns by name.
        hidx = {h.strip().lower(): i for i, h in enumerate(header)} if header else {}
        i_name = hidx.get("file name", 0)
        i_size = hidx.get("size", 1)
        i_free = hidx.get("freespace", None)
        for row in rdr:
            if len(row) < 2:
                continue
            name = row[i_name]
            try:
                size = int(row[i_size])
            except (ValueError, IndexError):
                continue
            is_folder = name.endswith("\\")
            if is_folder:
                n_folders += 1
                depth = name.count("\\")
                if depth == 1 and drive == "?":
                    drive = name[:2]
                    total_used = size
                    # free space column (found by header name; layout varies CLI vs GUI)
                    try: free = int(row[i_free]) if i_free is not None else 0
                    except (ValueError, IndexError): free = 0
                if size >= min_folder and depth >= 4:
                    if len(top_folders) < a.top:
                        heapq.heappush(top_folders, (size, name))
                    elif size > top_folders[0][0]:
                        heapq.heapreplace(top_folders, (size, name))
            else:
                n_files += 1
                if size >= min_file:
                    if len(top_files) < a.top:
                        heapq.heappush(top_files, (size, name))
                    elif size > top_files[0][0]:
                        heapq.heapreplace(top_files, (size, name))
                # categorize FILE bytes only (no folder double-count)
                lab, autonomy = categorize(name.lower())
                if lab:
                    e = cat_bytes.setdefault(lab, [0, autonomy])
                    e[0] += size

    top_files.sort(reverse=True)
    top_folders.sort(reverse=True)
    cats = sorted(cat_bytes.items(), key=lambda kv: kv[1][0], reverse=True)
    safe_total = sum(v[0] for _, v in cats if v[1] == "SAFE")
    review_total = sum(v[0] for _, v in cats if v[1] == "REVIEW")

    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(a.csv)),
                                f"wiztree-analysis_{drive[0]}_{datetime.datetime.now():%Y-%m-%d}.md")
    L = []
    L.append(f"# WizTree space report — drive {drive}  ({ts})")
    L.append(f"Source: `{a.csv}`")
    L.append(f"Used: {human(total_used)} | Free: {human(free)} | Files: {n_files:,} | Folders: {n_folders:,}\n")
    L.append(f"**Safe-to-clear (regenerable) total: {human(safe_total)}** | Review-needed categorized: {human(review_total)}\n")

    L.append("## A. SAFE to auto-clear (regenerable, no personal data)")
    L.append("| Category | Size |")
    L.append("|---|---|")
    for lab, (b, au) in cats:
        if au == "SAFE":
            L.append(f"| {lab} | {human(b)} |")

    L.append("\n## B. REVIEW — decision needed (may be personal / active project)")
    L.append("| Category | Size |")
    L.append("|---|---|")
    for lab, (b, au) in cats:
        if au == "REVIEW":
            L.append(f"| {lab} | {human(b)} |")

    L.append(f"\n## C. Largest individual files (>= {a.min_file_mb} MB, top {a.top}) — review each")
    L.append("| Size | Path |")
    L.append("|---|---|")
    for size, path in top_files:
        L.append(f"| {human(size)} | `{path}` |")

    L.append(f"\n## D. Largest folders (>= {a.min_folder_mb} MB, depth>=4, top {a.top}) — review each")
    L.append("| Size | Path |")
    L.append("|---|---|")
    for size, path in top_folders:
        L.append(f"| {human(size)} | `{path}` |")

    with open(out, "w", encoding="utf-8") as w:
        w.write("\n".join(L))
    # JSON sidecar for the permanent-rule tooling
    js = out.rsplit(".", 1)[0] + ".json"
    with open(js, "w", encoding="utf-8") as w:
        json.dump({
            "generated": ts, "drive": drive, "used": total_used, "free": free,
            "n_files": n_files, "n_folders": n_folders,
            "safe_total": safe_total, "review_total": review_total,
            "categories": {lab: {"bytes": b, "autonomy": au} for lab, (b, au) in cats},
            "top_files": [[s, p] for s, p in top_files],
            "top_folders": [[s, p] for s, p in top_folders],
        }, w, indent=2)

    # concise stdout summary
    print(f"REPORT={out}")
    print(f"JSON={js}")
    print(f"DRIVE={drive} USED={human(total_used)} FREE={human(free)} FILES={n_files:,}")
    print(f"SAFE_TOTAL={human(safe_total)}  REVIEW_TOTAL={human(review_total)}")
    print("--- SAFE categories ---")
    for lab, (b, au) in cats:
        if au == "SAFE":
            print(f"  {human(b):>12}  {lab}")
    print("--- REVIEW categories ---")
    for lab, (b, au) in cats:
        if au == "REVIEW":
            print(f"  {human(b):>12}  {lab}")
    print("--- top 15 files ---")
    for size, path in top_files[:15]:
        print(f"  {human(size):>12}  {path}")
    print("--- top 25 folders (depth>=4) ---")
    for size, path in top_folders[:25]:
        print(f"  {human(size):>12}  {path}")

if __name__ == "__main__":
    main()
