#!/usr/bin/env python3
"""Directives register: standing instructions, captured, judged, and verified applied.

WHY THIS EXISTS
Owner, 2026-09-24: "i keep saying along different sessions stuff that comes up
situational and some get buried and never acted upon it feels, i want discipline
that knows whats benefic and whats worse, and knows how to make the good decision
and so basically think proactively".

This is a DIFFERENT kind of thing from the neighbours, and conflating them is why
directives get lost:

  TASKBOX.md     work IN FLIGHT       -- closes in hours or days
  OPEN-LOOPS.md  open ITEMS w/ owners -- closes when someone does the thing
  >> DIRECTIVES  standing INSTRUCTIONS -- never "closes"; it must stay APPLIED

A directive is not done when you act on it once. "Always push" is not finished
by pushing once -- it is finished when a mechanism makes it true by default and
something verifies that mechanism still works. So a directive tracks WHERE it is
enforced and whether that enforcement is still PROVEN, not whether it was obeyed.

THE JUDGEMENT FIELD IS THE POINT
The owner asked for discipline that "knows whats benefic and whats worse". So each
directive carries an explicit assessment, written down, arguable:

  BENEFICIAL    adopt and enforce mechanically
  CONDITIONAL   beneficial within a stated boundary; record the boundary
  COSTLY        real downside; record it so the trade is visible, not silent
  NEEDS-SCOPE   ambiguous as stated; the ambiguity is recorded, not guessed at

Recording COSTLY or NEEDS-SCOPE is not refusing. It is refusing to pretend a
trade-off does not exist -- which is what makes a later reversal honest instead
of a contradiction.

Usage:
  python scripts/directives.py add "<verbatim owner words>" --judge BENEFICIAL \\
      --why "..." --applied "file:line, file:line" [--date 2026-09-24]
  python scripts/directives.py verify D-3 "evidence the enforcement still holds"
  python scripts/directives.py stale D-3 "why it no longer applies"
  python scripts/directives.py list
  python scripts/directives.py check      # exit 1 if any is UNVERIFIED
"""
from __future__ import annotations

import datetime
import json
import os
import sys

HOME = os.path.expanduser("~")
AGENTS = os.path.join(HOME, ".agents")
STORE = os.path.join(AGENTS, "knowledge", "DIRECTIVES.json")
REPORT = os.path.join(AGENTS, "knowledge", "DIRECTIVES.md")

JUDGEMENTS = ("BENEFICIAL", "CONDITIONAL", "COSTLY", "NEEDS-SCOPE")


def _today():
    return datetime.date.today().isoformat()


def load():
    try:
        with open(STORE, encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return {"version": 1, "next_id": 1, "directives": []}


def save(db):
    os.makedirs(os.path.dirname(STORE), exist_ok=True)
    with open(STORE, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(db, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    write_report(db)


def find(db, did):
    did = did.upper()
    if not did.startswith("D-"):
        did = "D-" + did
    for d in db["directives"]:
        if d["id"] == did:
            return d
    return None


def write_report(db):
    live = [d for d in db["directives"] if d.get("state") != "STALE"]
    stale = [d for d in db["directives"] if d.get("state") == "STALE"]
    lines = [
        "# Directives register",
        "",
        "**Generated by `scripts/directives.py`. Do not hand-edit.**",
        "",
        "Standing instructions from the owner, captured VERBATIM, each with an explicit",
        "judgement, the place it is actually enforced, and evidence that the enforcement",
        "still holds.",
        "",
        "A directive never \"completes\". Acting on it once is not the same as it being",
        "true by default. What closes a directive is a MECHANISM plus proof the mechanism",
        "still works -- which is why the last column is evidence, not a tick.",
        "",
        "Judgements: **BENEFICIAL** adopt · **CONDITIONAL** good within a stated boundary ·",
        "**COSTLY** real downside, recorded so the trade is visible · **NEEDS-SCOPE**",
        "ambiguous as stated, ambiguity recorded rather than guessed.",
        "",
        "Last updated %s." % _today(),
        "",
        "## Active (%d)" % len(live),
        "",
    ]
    if live:
        for d in sorted(live, key=lambda x: x["id"]):
            mark = "VERIFIED" if d.get("verified") else "**UNVERIFIED**"
            lines += [
                "### %s — %s (%s)" % (d["id"], d["judge"], mark),
                "",
                "> %s" % d["text"].replace("\n", "\n> "),
                "",
                "- **Said:** %s" % d.get("date", "?"),
                "- **Why this judgement:** %s" % d.get("why", ""),
                "- **Enforced at:** %s" % (d.get("applied") or "_nowhere yet — this is the gap_"),
            ]
            if d.get("boundary"):
                lines.append("- **Boundary:** %s" % d["boundary"])
            if d.get("cost"):
                lines.append("- **Accepted cost:** %s" % d["cost"])
            if d.get("verified"):
                lines.append("- **Evidence:** %s" % d["verified"])
            lines.append("")
    else:
        lines += ["_None recorded._", ""]

    if stale:
        lines += ["## Superseded (%d)" % len(stale), "",
                  "| ID | Directive | Why it no longer applies |", "|---|---|---|"]
        for d in stale:
            lines.append("| %s | %s | %s |" % (d["id"], d["text"][:70], d.get("stale_reason", "")))
        lines.append("")
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def findings(db):
    """What gap-check surfaces. Empty means silent."""
    out = []
    unverified = [d["id"] for d in db["directives"]
                  if d.get("state") != "STALE" and not d.get("verified")]
    unapplied = [d["id"] for d in db["directives"]
                 if d.get("state") != "STALE" and not d.get("applied")]
    if unapplied:
        out.append("%d directive(s) recorded but enforced NOWHERE: %s -- this is exactly "
                   "the 'said it, never acted on it' failure"
                   % (len(unapplied), ", ".join(unapplied[:6])))
    only_unverified = [i for i in unverified if i not in unapplied]
    if only_unverified:
        out.append("%d directive(s) applied but never verified: %s"
                   % (len(only_unverified), ", ".join(only_unverified[:6])))
    return out


def main(argv):
    if not argv:
        print(__doc__)
        return 0
    db = load()
    cmd = argv[0]

    def opt(name, default=""):
        for i, a in enumerate(argv):
            if a == "--" + name and i + 1 < len(argv):
                return argv[i + 1]
        return default

    if cmd == "add":
        if len(argv) < 2:
            print('usage: add "<verbatim>" --judge <J> --why "..." [--applied "..."]')
            return 2
        judge = opt("judge", "NEEDS-SCOPE").upper()
        if judge not in JUDGEMENTS:
            print("  judge must be one of: %s" % ", ".join(JUDGEMENTS))
            return 2
        did = "D-%d" % db["next_id"]
        db["next_id"] += 1
        db["directives"].append({
            "id": did, "text": argv[1], "judge": judge,
            "why": opt("why"), "applied": opt("applied"),
            "boundary": opt("boundary"), "cost": opt("cost"),
            "date": opt("date", _today()), "state": "ACTIVE",
            "verified": opt("verified"),
        })
        save(db)
        print("  %s %s  %s" % (did, judge, argv[1][:60]))
        return 0

    if cmd in ("verify", "stale", "apply"):
        if len(argv) < 3:
            print("usage: %s D-<n> \"<text>\"" % cmd)
            return 2
        d = find(db, argv[1])
        if not d:
            print("  no directive %r" % argv[1])
            return 2
        text = " ".join(argv[2:])
        if cmd == "verify":
            d["verified"] = text
        elif cmd == "apply":
            d["applied"] = text
        else:
            d["state"] = "STALE"
            d["stale_reason"] = text
        save(db)
        print("  %s %s: %s" % (d["id"], cmd, text[:70]))
        return 0

    if cmd == "list":
        for d in db["directives"]:
            if d.get("state") == "STALE":
                continue
            print("  %-5s %-12s %-6s %s" % (
                d["id"], d["judge"], "OK" if d.get("verified") else "UNVER",
                d["text"][:58]))
        return 0

    if cmd == "check":
        f = findings(db)
        if not f:
            n = len([d for d in db["directives"] if d.get("state") != "STALE"])
            print("SUCCESS:directives - %d active, all applied and verified" % n)
            return 0
        for x in f:
            print("  " + x)
        print("FAILED:directives-unapplied")
        return 1

    print("unknown command %r" % cmd)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
