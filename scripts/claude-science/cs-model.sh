#!/bin/bash
# cs-model — switch the Claude Science daemon's model provider, with revert.
#
#   cs-model glm        bridge via the LOCAL TWO-PLANE ROUTER (~/.local/bin/
#                       cs_glm_router.py): /v1/messages -> GLM coding plan
#                       (model names mapped, auth swapped to the ZAI key);
#                       session/OAuth plane -> api.anthropic.com untouched.
#                       A blunt ANTHROPIC_BASE_URL=z.ai does NOT work — it
#                       breaks the account plane (measured 2026-09-20:
#                       "claude.ai session expired ... could not be
#                       refreshed"). v1 of this script did exactly that.
#   cs-model anthropic  remove the bridge (native Anthropic / Max OAuth) and
#                       stop the router. THE REVERT PATH.
#   cs-model status     active bridge + router process state
#
# Writes ~/.claude-science/daemon-env (export-prefixed; sourced by ~/.profile
# and cs-start/cs-recover before `claude-science serve`). Restart after a
# switch: `cs fix`. Never edits or regenerates credentials.

set -euo pipefail
ENVFILE="$HOME/.claude-science/daemon-env"
ROUTER="$HOME/.local/bin/cs_glm_router"  # deploy loop strips .py
ROUTER_PORT="${CS_ROUTER_PORT:-8231}"
ROUTER_LOG="$HOME/.claude-science/logs/glm-router.log"
MODE="${1:-status}"

router_pid() { pgrep -f "cs_glm_rout[e]r" | head -1 || true; }

start_router() {
  local key="$1"
  if [ -n "$(router_pid)" ]; then
    echo "  router already running (pid $(router_pid))"
    return
  fi
  mkdir -p "$HOME/.claude-science/logs"
  nohup env ZAI_API_KEY="$key" python3 "$ROUTER" >>"$ROUTER_LOG" 2>&1 &
  sleep 1.5
  if [ -n "$(router_pid)" ]; then
    echo "  router started (pid $(router_pid), port $ROUTER_PORT)"
  else
    echo "FAILED:cs-model router did not start (see $ROUTER_LOG)" >&2
    exit 1
  fi
}

glm_env() {
  local best="" bestname=""
  for pair in "prekzursil1993:ZAI_API_KEY_prekzursil1993" "realprekzursil:ZAI_API_KEY_realprekzursil"; do
    name="${pair%%:*}"; var="${pair##*:}"
    key="${!var:-}"
    [ -n "$key" ] || continue
    code=$(curl -s -o /dev/null -w '%{http_code}' -m 30 \
      -H "Authorization: Bearer $key" -H 'Content-Type: application/json' \
      -d '{"model":"glm-4.6","messages":[{"role":"user","content":"hi"}],"max_tokens":1}' \
      https://api.z.ai/api/coding/paas/v4/chat/completions || echo 000)
    echo "  probe $name -> HTTP $code" >&2
    if [ "$code" = "200" ] && [ -z "$best" ]; then best="$key"; bestname="$name"; fi
  done
  if [ -z "$best" ]; then
    echo "FAILED:cs-model no healthy GLM plan key (both probes non-200)" >&2
    exit 1
  fi
  start_router "$best"
  cat >"$ENVFILE" <<EOF
# generated by cs-model glm $(date -u +%Y-%m-%dT%H:%M:%SZ) — key: $bestname (probe-selected)
# export prefixes are LOAD-BEARING (sourced by ~/.profile + cs-start/cs-recover).
# v2: base URL is the LOCAL ROUTER, not z.ai directly — the daemon's session
# plane must keep reaching api.anthropic.com or auth collapses.
export CS_MODEL_BRIDGE=glm-router
export ANTHROPIC_BASE_URL=http://127.0.0.1:$ROUTER_PORT
export ANTHROPIC_MODEL=glm-4.6
EOF
  chmod 600 "$ENVFILE"
  echo "SUCCESS:cs-model bridge=glm-router (key $bestname, router :$ROUTER_PORT) — restart to apply: cs fix"
}

case "$MODE" in
  glm)
    glm_env
    ;;
  anthropic|revert|native)
    rm -f "$ENVFILE"
    if [ -n "$(router_pid)" ]; then
      kill "$(router_pid)" 2>/dev/null || true
      echo "  router stopped"
    fi
    echo "SUCCESS:cs-model bridge removed (native Anthropic) — restart to apply: cs fix"
    ;;
  status)
    if [ -f "$ENVFILE" ]; then
      echo "bridge: active ($(grep -oE 'CS_MODEL_BRIDGE=.*' "$ENVFILE" | cut -d= -f2))"
      grep -E '^export ANTHROPIC' "$ENVFILE"
      echo "router: pid $(router_pid || echo none)"
    else
      echo "bridge: none (native Anthropic / Max OAuth)"
      echo "router: pid $(router_pid || echo none)"
    fi
    ;;
  *)
    echo "usage: cs-model [glm|anthropic|status]" >&2
    exit 2
    ;;
esac
