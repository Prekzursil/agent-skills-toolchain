#!/usr/bin/env python3
"""Task box: in-flight work that must survive compaction.

WHY THIS EXISTS
Owner, 2026-09-24: "there must be a clear task box so stuff doesnt get lost in
memory or compaction or in the depths of conversation ... you need to find a way
to make this benefic not bad".

The gap it fills, precisely:

  TodoWrite            ephemeral -- dies with the session, invisible after compaction
  event-ledger         objective turn history -- what HAPPENED, not what is PENDING
  basic-memory         semantic recall -- durable, but must be queried to be seen
  OPEN-LOOPS.md        durable LOOPS with owners and review-by dates
  >> TASKBOX.md <<     the missing layer: what is IN FLIGHT right now

Demonstrated failure this is built for: a grill produced questions G-1..G-17,
answered three, and G-4 and G-7..G-17 evaporated into conversation depth. Nothing
was broken -- they were simply never written anywhere that outlived the context.

WHAT MAKES IT BENEFICIAL RATHER THAN OVERHEAD
  - ONE LINE to add a task. If capture is expensive, capture stops happening.
  - SELF-SURFACING. gap-check reads it at Stop, so you never have to remember to
    look. A task box you must remember to read is the same as no task box.
  - AUTO-ARCHIVES. Done items move to an archive section, so the live list stays
    short and is worth reading. An ever-growing list gets ignored.
  - GRADUATES. A task still open after `--stale-days` is telling you it is not a
    task but a LOOP, and should move to OPEN-LOOPS.md with an owner and a date.
  - Never blocks anything. It is a record, not a gate.

Usage:
  python scripts/taskbox.py add "ship the grill merge" [--owner C] [--next "run tests"]
  python scripts/taskbox.py start T-3
  python scripts/taskbox.py block T-3 "waiting on home to come online"
  python scripts/taskbox.py done  T-3 "pushed 81d7e0ea, suites green"
  python scripts/taskbox.py drop  T-3 "superseded by T-7"
  python scripts/taskbox.py list
  python scripts/taskbox.py check          # what gap-check calls; exit 1 if stale
"""
from __future__ import annotations

import datetime
import json
import os
import sys

HOME = os.path.expanduser("~")
AGENTS = os.path.join(HOME, ".agents")
STORE = os.path.join(AGENTS, "knowledge", "TASKBOX.json")
REPORT = os.path.join(AGENTS, "knowledge", "TASKBOX.md")

OPEN_STATES = ("TODO", "DOING", "BLOCKED")
STALE_DAYS = 3


def _now():
    return datetime.datetime.now().replace(microsecond=0).isoformat(" ")


def _today():
    return datetime.date.today()


def _age_days(iso):
    try:
        d = datetime.datetime.fromisoformat(iso).date()
        return (_today() - d).days
    except Exception:
        return 0


def load():
    try:
        with open(STORE, encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return {"version": 1, "next_id": 1, "tasks": []}


def save(db):
    os.makedirs(os.path.dirname(STORE), exist_ok=True)
    with open(STORE, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(db, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    write_report(db)


def find(db, tid):
    tid = tid.upper()
    if not tid.startswith("T-"):
        tid = "T-" + tid
    for t in db["tasks"]:
        if t["id"] == tid:
            return t
    return None


def write_report(db):
    live = [t for t in db["tasks"] if t["state"] in OPEN_STATES]
    closed = [t for t in db["tasks"] if t["state"] not in OPEN_STATES]
    order = {"BLOCKED": 0, "DOING": 1, "TODO": 2}
    live.sort(key=lambda t: (order.get(t["state"], 9), t["id"]))

    lines = [
        "# Task box",
        "",
        "**Generated by `scripts/taskbox.py`. Do not hand-edit.**",
        "",
        "What is IN FLIGHT right now. This survives compaction, which the session's",
        "own todo list does not. A task still open after %d days is not a task, it is"
        % STALE_DAYS,
        "a LOOP -- move it to `OPEN-LOOPS.md` with an owner and a review-by date.",
        "",
        "`gap-check` reads this at Stop, so nothing here depends on remembering to look.",
        "",
        "Last updated %s." % _now(),
        "",
        "## Open (%d)" % len(live),
        "",
    ]
    if live:
        lines += ["| ID | State | Task | Next action | Owner | Age |",
                  "|---|---|---|---|---|---|"]
        for t in live:
            age = _age_days(t["opened"])
            flag = " ⚠" if age > STALE_DAYS else ""
            nxt = t.get("next") or ""
            if t["state"] == "BLOCKED":
                nxt = "BLOCKED: " + (t.get("blocker") or "blocker not named")
            lines.append("| %s | %s%s | %s | %s | %s | %dd |" % (
                t["id"], t["state"], flag, t["what"], nxt, t.get("owner", "C"), age))
        lines.append("")
    else:
        lines += ["_Nothing in flight._", ""]

    if closed:
        lines += ["## Closed (%d, most recent first)" % len(closed), "",
                  "| ID | State | Task | Outcome | Closed |", "|---|---|---|---|---|"]
        for t in sorted(closed, key=lambda t: t.get("closed", ""), reverse=True)[:25]:
            lines.append("| %s | %s | %s | %s | %s |" % (
                t["id"], t["state"], t["what"], t.get("outcome", ""), t.get("closed", "")))
        lines.append("")
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def findings(db):
    """What gap-check surfaces. Empty list means silent."""
    out = []
    stale, unnamed = [], []
    for t in db["tasks"]:
        if t["state"] not in OPEN_STATES:
            continue
        if _age_days(t["opened"]) > STALE_DAYS:
            stale.append("%s (%dd, %s)" % (t["id"], _age_days(t["opened"]), t["state"]))
        if t["state"] == "BLOCKED" and not t.get("blocker"):
            unnamed.append(t["id"])
    if stale:
        out.append("%d task(s) open past %d days -- promote to an OPEN-LOOPS row with an "
                   "owner, or close them: %s" % (len(stale), STALE_DAYS, ", ".join(stale[:6])))
    if unnamed:
        out.append("%d task(s) BLOCKED with no blocker named: %s"
                   % (len(unnamed), ", ".join(unnamed[:6])))
    return out


def main(argv):
    if not argv:
        print(__doc__)
        return 0
    db = load()
    cmd = argv[0]

    if cmd == "add":
        if len(argv) < 2:
            print("usage: add \"<what>\" [--owner X] [--next \"...\"]")
            return 2
        what = argv[1]
        owner, nxt = "C", ""
        for i, a in enumerate(argv):
            if a == "--owner" and i + 1 < len(argv):
                owner = argv[i + 1]
            if a == "--next" and i + 1 < len(argv):
                nxt = argv[i + 1]
        tid = "T-%d" % db["next_id"]
        db["next_id"] += 1
        db["tasks"].append({"id": tid, "what": what, "state": "TODO",
                            "owner": owner, "next": nxt, "opened": _now()})
        save(db)
        print("  %s TODO  %s" % (tid, what))
        return 0

    if cmd in ("start", "done", "drop", "block"):
        if len(argv) < 2:
            print("usage: %s T-<n> [note]" % cmd)
            return 2
        t = find(db, argv[1])
        if not t:
            print("  no task %r" % argv[1])
            return 2
        note = " ".join(argv[2:])
        if cmd == "start":
            t["state"] = "DOING"
            t.pop("blocker", None)
            if note:
                t["next"] = note
        elif cmd == "block":
            t["state"] = "BLOCKED"
            t["blocker"] = note or ""
        else:
            t["state"] = "DONE" if cmd == "done" else "DROPPED"
            t["outcome"] = note
            t["closed"] = _now()
        save(db)
        print("  %s -> %s  %s" % (t["id"], t["state"], note))
        return 0

    if cmd == "list":
        live = [t for t in db["tasks"] if t["state"] in OPEN_STATES]
        if not live:
            print("  nothing in flight")
            return 0
        for t in live:
            print("  %-5s %-8s %-52s %s" % (t["id"], t["state"], t["what"][:52],
                                            t.get("next", "")[:40]))
        return 0

    if cmd == "check":
        f = findings(db)
        if not f:
            print("SUCCESS:taskbox - nothing stale")
            return 0
        for x in f:
            print("  " + x)
        print("FAILED:taskbox-stale")
        return 1

    print("unknown command %r" % cmd)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
