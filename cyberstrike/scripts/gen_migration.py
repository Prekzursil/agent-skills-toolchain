#!/usr/bin/env python3
"""Phase-3 migration table generator (G-4/G-12; content-keyed, live-derived).

Parses the CURRENT live instruction surface (the 5 files that constitute the
model-facing payload post-Phase-1) into directive clauses, keys each clause by
a content hash (sha8 of normalized text), and maps EVERY clause to a
destination via scripts/migration_map.json.

Assert: zero unmapped clauses AND zero stale mapping keys. Any edit to a live
file that changes clause content makes this script exit non-zero (drift gate,
feeds T-11/T-12).

Usage:
  python scripts/gen_migration.py --dump            # print clause JSON (build aid)
  python scripts/gen_migration.py                   # generate MIGRATION-TABLE.md
"""
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LIVE_FILES = [
    "config.md",
    "AGENTS.md",
    "CONTEXT.md",
    "instructions-recon.md",
    "instructions-fullpower-estate.md",
]
MAP_PATH = REPO / "scripts" / "migration_map.json"
OUT_PATH = REPO / "MIGRATION-TABLE.md"

LIST_RE = re.compile(r"^(\s*)(?:[-*+]|\d+\.)\s+")
TABLE_RE = re.compile(r"^\s*\|")
SEP_RE = re.compile(r"^\s*\|[\s:|-]+\|\s*$")
HEAD_RE = re.compile(r"^#{1,6}\s")


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\r\n", "\n").replace("\r", "")).strip()


def key_of(text: str) -> str:
    """Content key = first 12 hex of sha256 over the normalized clause text.
    (Called 'sha8' colloquially in the task text; it is a content hash, not a
    credential hash.)"""
    return hashlib.sha256(norm(text).encode("utf-8")).hexdigest()[:12]


def parse_clauses(path: Path):
    """Clause = one list item / one table row / one paragraph block. Headings
    become block context. Continuation (more-indented or plain) lines fold into
    the current clause; a plain paragraph with no open list item is its own
    clause."""
    clauses = []
    heading = "(top)"
    cur = None  # [lines, start_line, kind, heading]

    def flush():
        nonlocal cur
        if cur and norm(" ".join(cur[0])):
            clauses.append({
                "file": path.name,
                "line": cur[1],
                "heading": cur[3],
                "kind": cur[2],
                "text": norm(" ".join(cur[0])),
            })
        cur = None

    for n, raw in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
        line = raw.rstrip()
        if HEAD_RE.match(line):
            flush()
            heading = norm(line.lstrip("#"))
            continue
        if not line.strip():
            flush()
            continue
        if SEP_RE.match(line):
            continue  # table separator
        if TABLE_RE.match(line):
            flush()
            cur = [[line.strip()], n, "table-row", heading]
            continue
        m = LIST_RE.match(line)
        if m:
            flush()
            cur = [[line.strip()], n, "list-item", heading]
            continue
        # continuation or paragraph
        if cur is not None:
            cur[0].append(line.strip())
        else:
            cur = [[line.strip()], n, "paragraph", heading]
    flush()
    return clauses


def all_clauses():
    out = []
    for name in LIVE_FILES:
        out.extend(parse_clauses(REPO / name))
    return out


def dedupe(clauses):
    """'map EVERY unique directive clause' — identical normalized text across
    files collapses to one row; sources list every carrier."""
    by_key = {}
    for c in clauses:
        k = key_of(c["text"])
        if k in by_key:
            by_key[k]["sources"].append(f"{c['file']}:{c['line']}")
        else:
            by_key[k] = {"text": c["text"], "sources": [f"{c['file']}:{c['line']}"],
                         "kind": c["kind"], "heading": c["heading"]}
    return by_key


def main():
    clauses = all_clauses()
    by_key = dedupe(clauses)
    if "--dump" in sys.argv:
        json.dump(by_key, sys.stdout, indent=1, ensure_ascii=False)
        return 0
    mapping = json.loads(MAP_PATH.read_text(encoding="utf-8"))
    unmapped = [k for k in by_key if k not in mapping]
    stale = [k for k in mapping if k not in by_key]
    n_drop = sum(1 for v in mapping.values() if v["dest"].startswith("DROPPED"))

    lines = [
        "# MIGRATION-TABLE.md — Phase-3 contract rewrite (GENERATED; do not hand-edit)",
        "",
        "Generated by `scripts/gen_migration.py` from the live instruction surface",
        f"({', '.join(LIVE_FILES)}). Content-keyed by sha8 of the normalized clause text:",
        "editing any live file invalidates its key and fails the generator (drift gate, T-11).",
        "",
        f"- clauses parsed: {len(clauses)}; unique: {len(by_key)}; mapped: {len(by_key) - len(unmapped)}; "
        f"dropped-with-reason: {n_drop}",
        f"- assert: unmapped == 0 -> **{len(unmapped) == 0}** (unmapped: {len(unmapped)}, stale keys: {len(stale)})",
        "",
        "Destinations: `AGENTS.new §0-§7` · `CONTEXT.new (script-generated)` · "
        "`HOME-ELEVATION-PROPOSAL (class 1-4)` · `cyberstrike.json (machine config, not prose)` · "
        "`DROPPED (reason)`.",
        "",
    ]
    order = {"AGENTS.new": 0, "CONTEXT.new": 1, "HOME-ELEVATION": 2,
             "cyberstrike.json": 3, "DROPPED": 4}
    rows = sorted(by_key.items(),
                  key=lambda kv: (order.get(mapping.get(kv[0], {}).get("dest", "zz").split()[0], 9),
                                  mapping.get(kv[0], {}).get("dest", ""),
                                  kv[1]["sources"][0]))
    cur_dest = None
    for k, c in rows:
        dest = mapping[k]["dest"] if k in mapping else "!!UNMAPPED!!"
        base = dest.split()[0]
        if base != cur_dest:
            lines.append(f"\n## -> {base}\n")
            lines.append("| key | clause (file:line) | destination | note |")
            lines.append("|---|---|---|---|")
            cur_dest = base
        note = mapping[k]["note"] if k in mapping else "UNMAPPED"
        txt = c["text"][:160] + ("…" if len(c["text"]) > 160 else "")
        txt = txt.replace("|", "\\|")
        src = ", ".join(c["sources"])
        lines.append(f"| `{k}` | {txt} ({src}) | {dest} | {note} |")
    lines.append("")
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"clauses={len(clauses)} unique={len(by_key)} unmapped={len(unmapped)} "
          f"stale={len(stale)} dropped={n_drop}")
    if unmapped or stale:
        for k in unmapped[:10]:
            print("UNMAPPED", k, by_key[k]["sources"], by_key[k]["text"][:100])
        for k in stale[:10]:
            print("STALE", k, mapping[k]["dest"])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
