#!/usr/bin/env python3
"""Shard21 w3: rebuild TST-0158 receipt from the live merge experiment.

The receipt on disk was the refute-era C5 artifact (merger did not refuse
at its measure time; since fixed). The dead prior shard had already rebuilt
a rich receipt (sha 8172 bytes) but it was overwritten. This regenerates it
from emit_receipt.py, then applies the builder-state discipline:
  - state=BLOCKED with failure.classification ["reviewer-absent"] (the
    emitted reviewer block is the builder-authored probe, not an
    independent reviewer - keeping it as SUCCESS would self-certify);
  - receipt_core required fields the emitter lacks;
  - a history block preserving the superseded refute-era receipt identity.
"""
import hashlib
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path.home() / "p2-g1"
OUT = REPO / "command-center" / "receipts" / "TST-0158.json"
EMIT = REPO / "command-center" / "p2-wave" / "probes" / "TST-0158" / "emit_receipt.py"

OLD_SHA = "49d337f1db92fe1a281e2a7a29acb4cdbade9b622c7b62e35eee04aa6d366ee3"

# 1) regenerate from the live experiment
r = subprocess.run([sys.executable, "-B", str(EMIT)], cwd=str(REPO), capture_output=True, text=True)
if r.returncode != 0:
    print("FAILED:0158-rebuild emitter did not pass")
    print((r.stdout or "")[-2000:], (r.stderr or "")[-2000:])
    raise SystemExit(1)
print((r.stdout or "").strip().splitlines()[0])

# 2) builder-state discipline + receipt_core required fields
doc = json.loads(OUT.read_text(encoding="utf-8"))
now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

reviewer = doc.pop("reviewer", None)
doc["builder_self_check"] = {
    "verdict": (reviewer or {}).get("verdict", "PASS"),
    "independent": False,
    "reviewer_id": "builder (probe2 independent-intersection recomputation)",
    "notes": (
        "Probe 2 recomputes the id set-intersection without reading "
        "merge_catalog.collision_ids as authority and requires "
        "catalog.by_id last-wins to hide the 31 ids. It is builder-authored "
        "machinery, NOT an independent reviewer; the SUCCESS closure is "
        "therefore withheld."
    ),
}
doc["state"] = "BLOCKED"
doc["failure"] = {
    "classification": ["reviewer-absent"],
    "reason": (
        "Builder emitted the live receipt (merger refuses the 31-way M-NN "
        "seed; disjoint control clean; last-wins negative control red) but "
        "no independent reviewer has closed THIS receipt. An independent "
        "reviewer must re-run the named probes and flip state to SUCCESS."
    ),
}
doc.setdefault("spec_anchor", "command-center/WORK-UNIT-CATALOG.json#TST-0158")
doc.setdefault(
    "timestamps",
    {
        "started_at": now,
        "ended_at": now,
        "duration_seconds": 0,
        "note": "regenerated by shard21-wave3 rebuild; live experiment runtime in probes/TST-0158 runtime fixtures",
    },
)
doc.setdefault(
    "retry",
    {
        "count": 1,
        "policy": "two strikes then pivot (AGENTS.md 4b)",
        "note": "prior builder attempt died mid-flight; this is the first rebuild",
    },
)
doc["superseded_receipt"] = {
    "sha256": OLD_SHA,
    "bytes": 30064,
    "state": "SUCCESS",
    "refute_outcome": "REFUTED",
    "success_withheld": True,
    "measured_then": (
        "production merger exit 0, refused=false, collision_ids_reported=0 "
        "(last-wins behavior); the merger has since been fixed and the "
        "live re-run refuses with the full 31-id list"
    ),
    "reviewer_closure": "openai/gpt-5.2 C5 review wave 2026-08-21 - applied to THAT artifact, does not carry to this rebuild",
}

OUT.write_text(json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")
raw = OUT.read_bytes().replace(b"\r\n", b"\n")
print(f"rebuilt {OUT.name} state=BLOCKED bytes={len(raw)} sha256={hashlib.sha256(raw).hexdigest()}")
