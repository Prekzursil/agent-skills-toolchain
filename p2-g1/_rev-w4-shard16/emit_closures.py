#!/usr/bin/env python3
"""Emit independent-reviewer closures for wave-4 shard-16.

Writes the reviewer stamp ONLY into receipts the r3 verification
(verify_out.json, generated by verify_w4s16.py) holds PASS with zero failing
checks, and only when the simulated post-closure receipt strict-validates
against receipt_core BEFORE the write, then read-back strict-revalidates and
builder content is asserted preserved. FAIL units (TST-0018, TST-0028) are
asserted byte-untouched.

Formatting preserved from the current receipts: indent=1, LF, UTF-8, trailing
newline (detected per file from the raw bytes before any write).
"""
from __future__ import annotations

import hashlib
import json
import sys
import time
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

REPO = Path(r"C:/Users/Prekzursil/p2-g1")
OUT = REPO / "_rev-w4-shard16" / "closure_report.json"
REVIEWER_ID = "claude-opus-5-5-independent-reviewer-w4s16-2026-10-26"

# builder content that must survive the closure byte-identical (JSON-value
# equality after round-trip). extensions is handled separately (the closure
# ADDS a key; existing builder keys must all survive).
PRESERVE_KEYS = [
    "schema_version", "unit_id", "spec_anchor", "min_bytes_threshold",
    "artifacts", "evidence", "produced_by", "retry", "timestamps",
    "manifest_registration", "notes", "ts",
]


def load_core_validator():
    from jsonschema import Draft202012Validator
    sch = json.loads(
        (REPO / "platform" / "schema" / "receipt.schema.json").read_text(encoding="utf-8")
    )
    core = dict(sch["$defs"]["receipt_core"])
    core["$defs"] = sch["$defs"]
    Draft202012Validator.check_schema(core)
    return Draft202012Validator(core)


def rsha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def detect_format(raw: bytes) -> dict:
    text = raw.decode("utf-8")
    lines = text.split("\n")
    indent = 2
    if len(lines) > 1 and lines[1].startswith(" "):
        indent = len(lines[1]) - len(lines[1].lstrip(" "))
    return {
        "indent": indent,
        "trailing_nl": raw.endswith(b"\n"),
        "crlf": b"\r\n" in raw,
    }


def serialize(doc: dict, fmt: dict) -> bytes:
    text = json.dumps(doc, indent=fmt["indent"], ensure_ascii=False)
    if fmt["trailing_nl"]:
        text += "\n"
    data = text.encode("utf-8")
    if fmt["crlf"]:
        data = data.replace(b"\n", b"\r\n")
    return data


def main() -> int:
    verify = json.loads(
        (REPO / "_rev-w4-shard16" / "verify_out.json").read_text(encoding="utf-8")
    )
    core_v = load_core_validator()

    pass_units = [u for u in verify["units"] if not verify["results"][u]["fails"]]
    fail_units = [u for u in verify["units"] if verify["results"][u]["fails"]]
    report: dict = {
        "reviewer": REVIEWER_ID,
        "date": time.strftime("%Y-%m-%d"),
        "units_pass": pass_units,
        "units_fail": fail_units,
        "written": [],
        "skipped": [],
        "fail_units_untouched": {},
    }

    snap_fail = {
        u: rsha(REPO / "command-center" / "receipts" / f"{u}.json") for u in fail_units
    }

    for uid in pass_units:
        res = verify["results"][uid]
        if not res.get("closable"):
            report["skipped"].append({
                "unit": uid, "why": "verify PASS but not closable",
                "state": "receipt left untouched"})
            continue
        sim = res.get("sim")
        if sim is None:
            report["skipped"].append({"unit": uid, "why": "no simulated closure"})
            continue

        # --- pre-write strict validation (belt and braces: re-validated here,
        # independent of the verifier's own check) ---
        errs = sorted(core_v.iter_errors(sim), key=lambda e: list(e.absolute_path))
        if errs:
            report["skipped"].append({
                "unit": uid, "why": "simulated closure invalid at emit time",
                "errors": [e.message[:200] for e in errs[:5]]})
            print(f"{uid} SKIP (sim invalid at emit: {len(errs)} errors)")
            continue
        assert sim["state"] == "SUCCESS", uid
        assert sim["reviewer"]["verdict"] == "PASS" and sim["reviewer"]["independent"] is True, uid
        assert "failure" not in sim, uid
        assert str(sim["sentinel"]).startswith(("SUCCESS:", "SENTINEL:")), uid

        rpath = REPO / "command-center" / "receipts" / f"{uid}.json"
        raw = rpath.read_bytes()
        before_builder = json.loads(raw.decode("utf-8"))
        fmt = detect_format(raw)
        data = serialize(sim, fmt)
        rpath.write_bytes(data)

        # --- read-back + strict re-validate + builder-content preservation ---
        back = json.loads(rpath.read_text(encoding="utf-8"))
        back_errs = sorted(core_v.iter_errors(back), key=lambda e: list(e.absolute_path))
        assert not back_errs, f"{uid} read-back invalid: {[e.message[:150] for e in back_errs]}"
        assert back["state"] == "SUCCESS" and back["reviewer"]["verdict"] == "PASS", uid
        assert back["reviewer"]["independent"] is True, uid
        for key in PRESERVE_KEYS:
            assert back.get(key) == before_builder.get(key), f"{uid} builder content altered: {key}"
        # builder extensions keys all survive; only w4s16_reviewer_closure added
        back_ext = back.get("extensions") or {}
        old_ext = before_builder.get("extensions") or {}
        for k, v in old_ext.items():
            assert back_ext.get(k) == v, f"{uid} builder extensions altered: {k}"
        assert back_ext.get("w4s16_reviewer_closure", {}).get("reviewer") == REVIEWER_ID, uid
        # live artifact row untouched and still matches the artifact
        out_rel = res["output_path"]
        live = hashlib.sha256(
            (REPO / out_rel).read_bytes().replace(b"\r\n", b"\n")).hexdigest()
        assert back["artifacts"][0]["sha256"] == live, uid

        report["written"].append({
            "unit": uid, "bytes": len(data),
            "state": "SUCCESS", "reviewer_verdict": "PASS", "independent": True,
            "read_back_strict_errors": 0,
        })
        print(f"{uid} CLOSED state=SUCCESS reviewer=PASS independent=true ({len(data)}B)")

    for uid in fail_units:
        after = rsha(REPO / "command-center" / "receipts" / f"{uid}.json")
        untouched = after == snap_fail[uid]
        report["fail_units_untouched"][uid] = {
            "untouched": untouched,
            "sha256_before": snap_fail[uid],
            "sha256_after": after,
            "failing_checks": verify["results"][uid]["fails"],
            "state_left_as": json.loads(
                (REPO / "command-center" / "receipts" / f"{uid}.json")
                .read_text(encoding="utf-8")).get("state"),
        }
        print(f"{uid} FAIL receipt untouched={untouched} "
              f"(state stays {report['fail_units_untouched'][uid]['state_left_as']})")
        assert untouched, f"{uid} receipt was modified - contract violation"

    for uid in verify["units"]:
        res = verify["results"][uid]
        if uid in pass_units and not res.get("closable"):
            continue  # recorded in skipped above

    OUT.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    n = len(report["written"])
    ns = len(report["skipped"])
    print(f"{'SUCCESS' if n + ns == len(pass_units) else 'FAILED'}:w4s16 closures emitted "
          f"written={n} skipped={ns} fail-untouched={len(fail_units)}")
    return 0 if n + ns == len(pass_units) else 1


if __name__ == "__main__":
    raise SystemExit(main())
