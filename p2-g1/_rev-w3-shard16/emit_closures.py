#!/usr/bin/env python3
"""Emit independent-reviewer closures for wave-3 shard-16.

Writes the reviewer stamp ONLY into receipts that the r5 verification
(verify_out.json, generated by verify_shard16_w3.py) holds PASS with zero
failing checks, and only when the simulated post-closure receipt strict-
validates against receipt_core BEFORE the write. FAIL units (RES-0037,
RES-0112) are asserted byte-untouched.

Formatting preserved from the builder receipts: 2-space indent, CRLF, UTF-8.
"""
from __future__ import annotations

import hashlib
import importlib.util
import io
import json
import sys
from pathlib import Path

# NOTE: no TextIOWrapper here - importing verify_shard16_w3 already re-wraps
# sys.stdout over the same buffer, and a second wrapper's GC closes the shared
# buffer mid-run (measured: crash after the first write). reconfigure() is
# non-owning and safe under import.
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass
REPO = Path(r"C:/Users/Prekzursil/p2-g1")
OUT = REPO / "_rev-w3-shard16" / "closure_report.json"

spec = importlib.util.spec_from_file_location(
    "w3s16_verify", REPO / "_rev-w3-shard16" / "verify_shard16_w3.py"
)
V = importlib.util.module_from_spec(spec)
sys.modules["w3s16_verify"] = V
spec.loader.exec_module(V)

verify = json.loads((REPO / "_rev-w3-shard16" / "verify_out.json").read_text(encoding="utf-8"))
cat = json.loads(
    (REPO / "command-center" / "WORK-UNIT-CATALOG.json").read_text(encoding="utf-8")
)
wu = {u.get("id"): u for u in cat.get("work_units", [])}
core_v = V.load_core_validator()
assert core_v is not None, "jsonschema unavailable - refuse to write"

PASS_UNITS = [u for u in V.UNITS if not verify["results"][u]["fails"]]
FAIL_UNITS = [u for u in V.UNITS if verify["results"][u]["fails"]]


def rsha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


snap_fail = {u: rsha(REPO / "command-center" / "receipts" / f"{u}.json") for u in FAIL_UNITS}

report = {"written": [], "skipped": [], "fail_units_untouched": {}}
for uid in PASS_UNITS:
    res = verify["results"][uid]
    assert not res["fails"], f"{uid} has fails; refusing"
    rpath = REPO / "command-center" / "receipts" / f"{uid}.json"
    receipt = json.loads(rpath.read_text(encoding="utf-8"))
    if receipt.get("state") == "SUCCESS":
        report["skipped"].append({"unit": uid, "why": "already SUCCESS"})
        continue
    named_probes, _ = V.load_named_probes(uid)
    sim = V.build_closure(receipt, uid, wu[uid], res.get("probes") or {}, named_probes)
    errs = sorted(core_v.iter_errors(sim), key=lambda e: list(e.absolute_path))
    if errs:
        report["skipped"].append(
            {"unit": uid, "why": "simulated closure invalid", "errors": [e.message[:200] for e in errs]}
        )
        print(f"{uid} SKIP (simulated closure invalid: {len(errs)} errors)")
        continue

    raw = rpath.read_bytes()
    trailing_nl = raw.endswith(b"\n")
    crlf = raw.count(b"\r\n") > 0 and raw.count(b"\r\n") == raw.count(b"\n")
    text = json.dumps(sim, indent=2, ensure_ascii=False)
    if trailing_nl:
        text += "\n"
    data = text.encode("utf-8")
    if crlf:
        data = data.replace(b"\n", b"\r\n")

    # post-conditions before write: closure fields exactly as verified
    assert sim["state"] == "SUCCESS"
    assert sim["reviewer"]["verdict"] == "PASS" and sim["reviewer"]["independent"] is True
    assert "failure" not in sim

    rpath.write_bytes(data)

    # read back + strict re-validate
    back = json.loads(rpath.read_text(encoding="utf-8"))
    back_errs = sorted(core_v.iter_errors(back), key=lambda e: list(e.absolute_path))
    assert not back_errs, f"{uid} read-back invalid: {[e.message[:150] for e in back_errs]}"
    assert back["state"] == "SUCCESS" and back["reviewer"]["verdict"] == "PASS"
    assert back["reviewer"]["independent"] is True
    # builder content preserved: artifacts + evidence + sentinel identical
    for key in ("artifacts", "evidence", "sentinel", "spec_anchor", "unit_id",
                "min_bytes_threshold", "produced_by", "retry", "timestamps"):
        assert back.get(key) == receipt.get(key), f"{uid} builder content altered: {key}"
    report["written"].append({"unit": uid, "bytes": len(data), "read_back_strict_errors": 0})
    print(f"{uid} CLOSED state=SUCCESS reviewer=PASS independent=true ({len(data)}B)")

for uid in FAIL_UNITS:
    after = rsha(REPO / "command-center" / "receipts" / f"{uid}.json")
    untouched = after == snap_fail[uid]
    report["fail_units_untouched"][uid] = {
        "untouched": untouched,
        "sha256_before": snap_fail[uid],
        "sha256_after": after,
        "failing_checks": verify["results"][uid]["fails"],
    }
    print(f"{uid} FAIL receipt untouched={untouched}")
    assert untouched, f"{uid} receipt was modified - contract violation"

(OUT).write_text(
    json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)
n = len(report["written"])
print(f"SUCCESS:w3s16 closures emitted written={n} skipped={len(report['skipped'])} "
      f"fail-untouched={len(FAIL_UNITS)}") if n + len(report["skipped"]) == len(PASS_UNITS) else None
