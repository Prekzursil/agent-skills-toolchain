def main() -> int:
    raw = CATALOG.read_text(encoding="utf-8")
    doc = json.loads(raw)
    assert json.dumps(doc, indent=1, ensure_ascii=False) == raw, (
        "serialiser drift; refusing to write"
    )

    qs = doc["owner_questions"]
    by_id = {q.get("id"): q for q in qs}

    touched = []
    for qid, payload in ANSWERS.items():
        q = by_id.get(qid)
        if q is None:
            print(f"FAILED:answer-oq no such question {qid}")
            return 1
        if q.get("state") == "ANSWERED":
            print(f"  {qid} already ANSWERED - skipped")
            continue
        q["state"] = "ANSWERED"
        q["answer"] = payload["answer"]
        q["answer_detail"] = payload["answer_detail"]
        q["answered_on"] = TODAY
        q["answer_provenance"] = PROV
        touched.append(qid)

    added = []
    for entry in NEW:
        if entry["id"] in by_id:
            print(f"  {entry['id']} already exists - skipped")
            continue
        qs.append(entry)
        added.append(entry["id"])

    CATALOG.write_text(
        json.dumps(doc, indent=1, ensure_ascii=False), encoding="utf-8", newline=""
    )
    still_open = sum(1 for q in qs if q.get("state") == "OPEN")
    print(f"  answered: {', '.join(touched) or 'none'}")
    print(f"  added:    {', '.join(added) or 'none'}")
    print(f"  owner_questions now: {len(qs)} total, {still_open} OPEN")
    print(
        "\nSUCCESS:answer-oq catalog updated -- run render.py to project into OWNER-DECISIONS.md"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
