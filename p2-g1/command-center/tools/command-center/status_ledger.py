"""STATUS.md as a derived measurement of EVENTS.jsonl plus receipts.

A hand-maintained status board is the 'plausible digest is not a receipt' failure
CC-0013 exists to close. Every integer in the generated file carries the query
that produced it; add_metric refuses a blank query. Two renders over unchanged
inputs are byte-identical: the file is stamped with generating_commit and a
ledger_clock taken from the event log, never datetime.now().

Zero events (missing or empty log) yields program status NOT-STARTED, never a
green token, even when receipts claim SUCCESS.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from itertools import zip_longest
from pathlib import Path
from typing import Any, Iterable

if __package__ in (None, ""):  # pragma: no cover - import shim for direct runs
    sys.path.insert(0, str(Path(__file__).resolve().parent))

import status_predicate as sp  # noqa: E402

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parents[1]
GENESIS = "0" * 64
CHAIN_EXCLUDE = frozenset({"prev_sha256", "prev_hash", "prev", "sha256", "hash"})
FORBIDDEN_PROGRAM_STATUS = frozenset(
    {
        "GREEN",
        "SUCCESS",
        "COMPLETE",
        "COMPLETED",
        "PASS",
        "PASSED",
        "OK",
        "HEALTHY",
        "DONE",
        "DONE-VERIFIED",
    }
)
EVENT_RECORDS_QUERY = (
    "count JSON objects parsed from command-center/events/EVENTS.jsonl "
    "(blank lines skipped; non-objects counted as unparseable)"
)
BANNER = (
    "<!-- GENERATED by tools/command-center/status_ledger.py from "
    "events/EVENTS.jsonl plus receipts/*.json plus the CC-0003 reducer when "
    "importable. Do not hand-edit: run `python3 tools/command-center/status_ledger.py` "
    "or `python3 tools/command-center/status_ledger.py --check`. -->"
)


class UnqueriedNumber(ValueError):
    """Raised when a generator tries to emit a count with no query."""


def status_path(root: Path) -> Path:
    return Path(root) / "STATUS.md"


def generating_commit(start: Path | None = None) -> dict[str, Any]:
    """Stamp the generator, not wall-clock. Missing git is a measurement, not a crash."""
    base = Path(start) if start is not None else REPO
    git = base / ".git"
    if not git.exists():
        return {
            "available": False,
            "sha": "",
            "reason": (
                f"worktree {base} is not a git repository; git rev-parse HEAD "
                "cannot stamp a generating commit"
            ),
        }
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(base),
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {
            "available": False,
            "sha": "",
            "reason": f"git rev-parse HEAD failed: {type(exc).__name__}",
        }
    sha = (proc.stdout or "").strip()
    if proc.returncode != 0 or not sha:
        return {
            "available": False,
            "sha": "",
            "reason": f"git rev-parse HEAD rc={proc.returncode}",
        }
    return {"available": True, "sha": sha, "reason": "git rev-parse HEAD"}


def add_metric(rows: list[dict[str, Any]], name: str, value: int, query: str) -> None:
    """Append a queried integer. A blank query is a claim; refuse it."""
    if type(value) is not int:
        raise TypeError(f"metric {name!r} value must be int, not {type(value).__name__}")
    if not str(query).strip():
        raise UnqueriedNumber(f"refusing unqueried number {name}={value}")
    rows.append({"name": str(name), "value": value, "query": str(query).strip()})


def _events_path(root: Path) -> Path:
    return Path(root) / "events" / "EVENTS.jsonl"


def load_events(root: Path) -> tuple[list[dict[str, Any]], int]:
    path = _events_path(root)
    if not path.is_file():
        return [], 0
    records: list[dict[str, Any]] = []
    unparseable = 0
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    for line in text.splitlines():
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            unparseable += 1
            continue
        if not isinstance(obj, dict):
            unparseable += 1
            continue
        records.append(obj)
    return records, unparseable


def _canon(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def verify_hash_chain(records: Iterable[dict[str, Any]]) -> dict[str, Any]:
    """prev_sha256 + canonical body -> sha256. Unchained records are not a break.

    Algorithm matches ARC-0086 (prev + newline + canonical chain body). Records
    without chain fields are counted as unchained, not as a tamper.
    """
    prev = GENESIS
    intact = 0
    chained = 0
    first_break: int | None = None
    break_reason = ""
    for index, rec in enumerate(records):
        if not isinstance(rec, dict):
            continue
        has_link = any(k in rec for k in ("sha256", "hash", "prev_sha256", "prev_hash", "prev"))
        if not has_link:
            continue
        chained += 1
        declared_prev = rec.get("prev_sha256") or rec.get("prev_hash") or rec.get("prev")
        declared = rec.get("sha256") or rec.get("hash")
        body = {k: rec[k] for k in rec if k not in CHAIN_EXCLUDE}
        computed = hashlib.sha256(f"{prev}\n{_canon(body)}".encode("utf-8")).hexdigest()
        if declared_prev != prev:
            first_break = index
            break_reason = "prev_sha256-mismatch"
            break
        if not isinstance(declared, str) or declared != computed:
            first_break = index
            break_reason = "record-digest-mismatch"
            break
        intact += 1
        prev = declared
    return {
        "chained_records": chained,
        "intact_links": intact,
        "first_break": first_break,
        "break_reason": break_reason,
        "unchained_ok": chained == 0,
    }


def load_receipts(root: Path) -> dict[str, Any]:
    directory = Path(root) / "receipts"
    files = sorted(directory.glob("*.json")) if directory.is_dir() else []
    parseable = 0
    unparseable = 0
    success = 0
    blocked = 0
    for path in files:
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            unparseable += 1
            continue
        if not isinstance(doc, dict):
            unparseable += 1
            continue
        parseable += 1
        state = str(doc.get("state") or doc.get("status") or "").upper()
        if state in {"SUCCESS", "COMPLETED"}:
            success += 1
        elif state in {"BLOCKED", "FAILED", "SEVERED", "TIMEOUT"}:
            blocked += 1
    return {
        "total": len(files),
        "parseable": parseable,
        "unparseable": unparseable,
        "success": success,
        "blocked": blocked,
    }


def ledger_clock(events: list[dict[str, Any]]) -> str:
    """Stable stamp: max event ts, not wall clock. Empty log -> n/a."""
    stamps: list[str] = []
    for rec in events:
        ts = rec.get("ts")
        if isinstance(ts, str) and ts.strip():
            stamps.append(ts.strip())
    if not stamps:
        return "n/a"
    return max(stamps)


def program_status(event_count: int) -> str:
    if event_count <= 0:
        return "NOT-STARTED"
    return "IN-PROGRESS"


def _metric_line(name: str, value: int, query: str) -> str:
    return f"| `{name}` | {value} | {query} |"


def collect_metrics(root: Path) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    events, unparseable = load_events(root)
    chain = verify_hash_chain(events)
    receipts = load_receipts(root)
    loaded = sp.consume_reducer()
    rows: list[dict[str, Any]] = []
    add_metric(rows, "event_records", len(events), EVENT_RECORDS_QUERY)
    add_metric(
        rows,
        "event_unparseable",
        unparseable,
        "count EVENTS.jsonl lines that are non-blank but not a JSON object",
    )
    add_metric(
        rows,
        "event_chain_links_verified",
        int(chain["intact_links"]),
        "count hash-chain links verified as prev_sha256 + canonical body -> sha256",
    )
    add_metric(
        rows,
        "receipts_total",
        int(receipts["total"]),
        "count *.json files that are direct children of command-center/receipts/",
    )
    add_metric(
        rows,
        "receipts_parseable",
        int(receipts["parseable"]),
        "count receipts/*.json files that parse as a JSON object",
    )
    add_metric(
        rows,
        "receipts_success",
        int(receipts["success"]),
        "count parsed receipts whose state is SUCCESS or COMPLETED",
    )
    add_metric(
        rows,
        "receipts_blocked",
        int(receipts["blocked"]),
        "count parsed receipts whose state is BLOCKED, FAILED, SEVERED or TIMEOUT",
    )
    add_metric(
        rows,
        "receipts_unparseable",
        int(receipts["unparseable"]),
        "count receipts/*.json files that do not parse as a JSON object",
    )
    add_metric(
        rows,
        "cc0003_reducer_importable",
        1 if loaded["importable"] else 0,
        "1 if status_predicate.load_reducer() imported the CC-0003 module, else 0",
    )
    aux = {
        "events": events,
        "chain": chain,
        "receipts": receipts,
        "reducer": loaded,
        "program": program_status(len(events)),
        "ledger_clock": ledger_clock(events),
    }
    return rows, aux


def render_markdown(root: Path) -> str:
    root = Path(root)
    rows, aux = collect_metrics(root)
    commit = generating_commit(REPO)
    sha = commit["sha"] if commit.get("available") else "unavailable"
    reducer = aux["reducer"]
    reducer_token = "IMPORTABLE" if reducer["importable"] else "NOT-CHECKED"
    chain = aux["chain"]
    if chain["unchained_ok"]:
        chain_token = "NOT-CHECKED"
        chain_note = "event records do not carry chain fields; CC-0007 links are not claimed"
    elif chain["first_break"] is None and chain["intact_links"] == chain["chained_records"]:
        chain_token = "VERIFIED"
        chain_note = "every chained record matched prev_sha256 + canonical body -> sha256"
    else:
        chain_token = "BROKEN"
        chain_note = chain["break_reason"] or "hash-chain break"
    program = aux["program"]
    if program in FORBIDDEN_PROGRAM_STATUS:
        raise RuntimeError(f"refusing to emit forbidden program status {program!r}")
    lines = [
        BANNER,
        "",
        "# STATUS",
        "",
        "Derived measurement. Not a hand-written claim.",
        "",
        "- generator: `tools/command-center/status_ledger.py`",
        f"- generating_commit: `{sha}`",
        f"- ledger_clock: `{aux['ledger_clock']}`",
        "",
        "## Program status",
        "",
        f"`{program}`",
        "",
        "Zero events yield `NOT-STARTED` even when a receipt claims SUCCESS. "
        "Receipts cannot paint the board green.",
        "",
        "## Metrics",
        "",
        "Every integer below carries the query that produced it. A count with no query is refused.",
        "",
        "| metric | value | query |",
        "|---|---|---|",
    ]
    for row in rows:
        lines.append(_metric_line(row["name"], row["value"], row["query"]))
    lines += [
        "",
        "## CC-0003 reducer",
        "",
        f"`{reducer_token}`",
        "",
        f"- reducer_id: `{reducer['reducer_id']}`",
        f"- source: `{reducer['source'] or 'absent'}`",
        f"- reason: `{reducer['reason']}`",
        "",
        "The reducer is consumed when importable (imported and identified). "
        "Absence is `NOT-CHECKED`, which is not a pass. This file does not "
        "evaluate Gate A over receipts; that remains the reducer's job.",
        "",
        "## Hash chain",
        "",
        f"`{chain_token}`",
        "",
        chain_note,
        "",
    ]
    text = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    return text


def write_status(root: Path) -> Path:
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    path = status_path(root)
    path.write_text(render_markdown(root), encoding="utf-8", newline="\n")
    return path


def check_status(root: Path) -> tuple[bool, list[str]]:
    root = Path(root)
    path = status_path(root)
    expected = render_markdown(root)
    if not path.is_file():
        return False, [f"STATUS.md missing at {path.as_posix()}"]
    actual = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if actual == expected:
        return True, []
    msgs: list[str] = []
    for index, (got, want) in enumerate(
        zip_longest(actual.splitlines(), expected.splitlines(), fillvalue=""),
        start=1,
    ):
        if got != want:
            msgs.append(f"line {index}: drifted: {got!r} expected {want!r}")
    if not msgs:
        msgs.append("STATUS.md drifted (trailing whitespace or newline)")
    return False, msgs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        default=str(REPO / "command-center"),
        help="command-center directory (events/, receipts/, STATUS.md)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail on drift instead of rewriting STATUS.md",
    )
    args = parser.parse_args(argv)
    root = Path(args.root)
    if args.check:
        ok, msgs = check_status(root)
        for entry in msgs:
            print(entry)
        if not ok:
            print(f"FAILED:status-ledger drift={len(msgs)}")
            return 1
        print("SUCCESS:status-ledger no drift")
        return 0
    written = write_status(root)
    print(f"SUCCESS:status-ledger wrote={written.as_posix()}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry
    raise SystemExit(main())
