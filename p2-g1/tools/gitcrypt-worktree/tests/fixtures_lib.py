"""Fixture builders for the git-crypt worktree doctor tests.

Every fixture is an isolated throwaway repository built from scratch inside
pytest's ``tmp_path``. Nothing here touches a real repository, a real key, or
any credential file. The only "secret" material is the literal
``SYNTHETIC_FIXTURE_04B_NOT_A_REAL_SECRET``.

git-crypt keys generated by ``git-crypt init`` below are real symmetric keys,
but each decrypts nothing except its own throwaway fixture.
"""

from __future__ import annotations

import os
import shutil
import subprocess

SYNTHETIC = b'{"note":"SYNTHETIC_FIXTURE_04B_NOT_A_REAL_SECRET","v":"AAAABBBB"}\n'
SYNTHETIC_2 = b'{"note":"SYNTHETIC_FIXTURE_04B_NOT_A_REAL_SECRET","v":"CCCCDDDD"}\n'

GITCRYPT_MAGIC = b"\x00GITCRYPT\x00"


def require_git_crypt():
    if shutil.which("git-crypt") is None:
        raise RuntimeError(
            "git-crypt is not on PATH; these tests cannot prove anything "
            "without it and must not be skipped silently"
        )


def git(args, cwd, check=True):
    proc = subprocess.run(
        ["git", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if check and proc.returncode != 0:
        raise RuntimeError(
            f"git {' '.join(args)} (cwd={cwd}) failed rc={proc.returncode}\n"
            f"stdout={proc.stdout}\nstderr={proc.stderr}"
        )
    return proc


def read_head(path, n=len(GITCRYPT_MAGIC)):
    with open(path, "rb") as handle:
        return handle.read(n)


def is_ciphertext(path):
    return read_head(path) == GITCRYPT_MAGIC


def sha256(path):
    import hashlib

    h = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def create_seeded_repo(repo):
    """Throwaway git repo for disjoint-index / teardown probes (no git-crypt)."""
    from pathlib import Path

    repo = Path(repo)
    repo.mkdir(parents=True, exist_ok=True)
    git(["init", "-q", "-b", "main"], cwd=repo)
    git(["config", "user.email", "fixture@example.invalid"], cwd=repo)
    git(["config", "user.name", "fixture"], cwd=repo)
    git(["config", "commit.gpgsign", "false"], cwd=repo)
    git(["config", "core.autocrlf", "false"], cwd=repo)
    (repo / "a.txt").write_text("A\n", encoding="utf-8")
    (repo / "b.txt").write_text("B\n", encoding="utf-8")
    (repo / "shared.txt").write_text("S\n", encoding="utf-8")
    git(["add", "."], cwd=repo)
    git(["commit", "-q", "-m", "seed"], cwd=repo)
    return repo


def init_repo(repo, secrets=("secret.json",)):
    """A healthy git-crypt repo whose shared filters use an absolute --key-file.

    The absolute ``--key-file`` matters: ``git-crypt init`` writes a filter
    with no key path, and git-crypt then resolves the key relative to
    ``--git-dir``. For a LINKED worktree that is ``.git/worktrees/<name>``,
    where no key exists -- so ``git worktree add`` fails outright with
    ``required = true``. Measured, see the remediation report.
    """
    require_git_crypt()
    repo.mkdir(parents=True, exist_ok=True)
    git(["init", "-q", "-b", "main"], cwd=repo)
    git(["config", "user.email", "fixture@example.invalid"], cwd=repo)
    git(["config", "user.name", "fixture"], cwd=repo)
    git(["config", "commit.gpgsign", "false"], cwd=repo)
    git(["config", "core.autocrlf", "false"], cwd=repo)
    git(["config", "extensions.worktreeConfig", "true"], cwd=repo)

    attrs = "".join(f"{name} filter=git-crypt diff=git-crypt\n" for name in secrets)
    (repo / ".gitattributes").write_bytes(attrs.encode())
    (repo / "README.md").write_bytes(b"fixture\n")
    git(["add", "--", ".gitattributes", "README.md"], cwd=repo)
    git(["commit", "-q", "-m", "init"], cwd=repo)

    subprocess.run(
        ["git-crypt", "init"], cwd=str(repo), capture_output=True, check=True
    )
    key = (repo / ".git" / "git-crypt" / "keys" / "default").resolve()
    key_s = str(key).replace("\\", "/")
    git(
        ["config", "filter.git-crypt.smudge", f"git-crypt smudge --key-file={key_s}"],
        cwd=repo,
    )
    git(
        ["config", "filter.git-crypt.clean", f"git-crypt clean --key-file={key_s}"],
        cwd=repo,
    )
    git(["config", "filter.git-crypt.required", "true"], cwd=repo)
    git(
        ["config", "diff.git-crypt.textconv", f"git-crypt diff --key-file={key_s}"],
        cwd=repo,
    )

    payloads = [SYNTHETIC, SYNTHETIC_2]
    for i, name in enumerate(secrets):
        (repo / name).write_bytes(payloads[i % len(payloads)])
    git(["add", "--", *secrets], cwd=repo)
    git(["commit", "-q", "-m", "secrets"], cwd=repo)

    # Two independent confirmations that the STORED blob is encrypted.
    for name in secrets:
        blob = subprocess.run(
            ["git", "cat-file", "-p", f"HEAD:{name}"],
            cwd=str(repo),
            capture_output=True,
            check=True,
        ).stdout
        assert blob.startswith(GITCRYPT_MAGIC), f"{name} blob is not encrypted"
        assert b"SYNTHETIC_FIXTURE" not in blob, f"{name} blob leaks plaintext"
    return repo, key_s


def add_worktree(repo, path, branch):
    git(["worktree", "add", "-q", str(path), "-b", branch], cwd=repo)
    return path


def make_ciphertext_worktree(
    repo, path, branch, declare=True, secrets=("secret.json",)
):
    """A worktree deliberately configured to keep ciphertext on disk."""
    add_worktree(repo, path, branch)
    git(["config", "--worktree", "filter.git-crypt.smudge", "cat"], cwd=path)
    git(["config", "--worktree", "filter.git-crypt.clean", "cat"], cwd=path)
    git(["config", "--worktree", "filter.git-crypt.required", "false"], cwd=path)
    if declare:
        git(["config", "--worktree", "gitcrypt.worktreeMode", "ciphertext"], cwd=path)
    for name in secrets:
        os.remove(path / name)
        git(["checkout", "--", name], cwd=path)
        assert is_ciphertext(path / name), f"{name} did not stay ciphertext"
    return path


def worktree_config_path(repo, entry):
    return repo / ".git" / "worktrees" / entry / "config.worktree"
