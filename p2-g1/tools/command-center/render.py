"""Render the DERIVED command-center files from the catalog.

Three of the thirteen artifacts are pure functions of the catalog, so they are
generated rather than maintained: STATUS.md, OWNER-DECISIONS.md and
ARTIFACT-MANIFEST.json. A hand-maintained status page beside a machine-readable
catalog is two sources of truth, and the one a human edits is the one that goes
15 days stale while work continues -- the measured root cause this whole lane
exists to fix (`REGISTER.md:74`, RESUME.json).

`--check` re-renders in memory and diffs against disk, so CI can fail on drift
instead of discovering it a fortnight later.
"""

