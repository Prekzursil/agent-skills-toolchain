"""Register-on-write + consumer-read gate for ARTIFACT-MANIFEST.json (CC-0009).

Completion conditions 11 and 12 (_USER-PROMPTS.md:10643-10644) require that an
output was registered in the artifact manifest AND that downstream consumers can
actually read it. A path string in the manifest is not proof the file exists, and
existence is not proof the declared consumer can parse it.

This module ships two primitives:

  * ``register_on_write`` — measure bytes on disk and upsert the entry into a
    manifest shaped like ``command-center/ARTIFACT-MANIFEST.json``.
  * ``probe_manifest_consumers`` — open EVERY manifest entry with the consumer
    that claims to read it (explicit ``consumer`` field, else inferred from
    suffix). Registered-but-absent and registered-but-unreadable both fail.

The live contracted manifest is regenerated by ``tools/command-center/render.py``
from a fixed 14-name tuple; ``register_on_write`` is therefore the write-side
registration API for unit outputs (and for tests), while ``probe_manifest_consumers``
is the read-side gate that the both-states control runs against the live file.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Mapping, Sequence

__all__ = [
    "GATE_ID",
    "DEFAULT_MANIFEST",
    "ConsumerResult",
    "ProbeReport",
    "infer_consumer",
    "register_on_write",
    "probe_manifest_consumers",
    "load_manifest",
    "write_manifest_atomic",
]

GATE_ID = "platform/lib/artifact_manifest_gate.py@v1"
DEFAULT_MANIFEST = "command-center/ARTIFACT-MANIFEST.json"

#: Known consumer ids. Each returns (ok, summary) where summary cites the first
#: parsed key or a record count (evidence_requirement for CC-0009).
ConsumerFn = Callable[[Path], tuple[bool, str]]


def _sha256_lf(data: bytes) -> tuple[str, int]:
    lf = data.replace(b"\r\n", b"\n")
    return hashlib.sha256(lf).hexdigest(), len(lf)


def _consume_json(path: Path) -> tuple[bool, str]:
    try:
        text = path.read_text(encoding="utf-8")
        obj = json.loads(text)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        return False, f"json.loads FAILED: {type(exc).__name__}: {exc}"
    if isinstance(obj, dict):
        keys = list(obj.keys())
        first = keys[0] if keys else "<empty-object>"
        return True, f"json.loads ok; first_key={first!r}; key_count={len(keys)}"
    if isinstance(obj, list):
        return True, f"json.loads ok; type=list; record_count={len(obj)}"
    return True, f"json.loads ok; type={type(obj).__name__}"


def _consume_jsonl(path: Path) -> tuple[bool, str]:
    try:
        raw = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return False, f"jsonl read FAILED: {type(exc).__name__}: {exc}"
    lines = [ln for ln in raw.splitlines() if ln.strip()]
    if not lines:
        return False, "jsonl FAILED: zero non-empty records"
    for i, ln in enumerate(lines):
        try:
            json.loads(ln)
        except json.JSONDecodeError as exc:
            return False, f"jsonl FAILED at record {i}: {exc}"
    first_keys = ""
    try:
        first = json.loads(lines[0])
        if isinstance(first, dict) and first:
            first_keys = f"; first_key={next(iter(first))!r}"
    except json.JSONDecodeError:
        pass
    return True, f"jsonl ok; record_count={len(lines)}{first_keys}"


def _consume_utf8_text(path: Path) -> tuple[bool, str]:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return False, f"utf8-text FAILED: {type(exc).__name__}: {exc}"
    if not text.strip():
        return False, "utf8-text FAILED: empty after strip"
    first = next((ln.strip() for ln in text.splitlines() if ln.strip()), "")
    return True, f"utf8-text ok; bytes={len(text.encode('utf-8'))}; first_line={first[:80]!r}"


def _consume_self_manifest(path: Path) -> tuple[bool, str]:
    """The ARTIFACT-MANIFEST self entry cannot be digested; still must parse as JSON."""
    ok, summary = _consume_json(path)
    if not ok:
        return ok, summary
    return True, f"self-manifest {summary}"


CONSUMERS: dict[str, ConsumerFn] = {
    "json.loads": _consume_json,
    "jsonl": _consume_jsonl,
    "utf8-text": _consume_utf8_text,
    "self-manifest": _consume_self_manifest,
}


def infer_consumer(rel_path: str, entry: Mapping[str, Any] | None = None) -> str:
    """Resolve the consumer that claims to read this entry."""
    if entry is not None:
        declared = entry.get("consumer")
        if isinstance(declared, str) and declared.strip():
            return declared.strip()
        if entry.get("sha256") == "(self)":
            return "self-manifest"
    lower = rel_path.replace("\\", "/").lower()
    if lower.endswith(".jsonl"):
        return "jsonl"
    if lower.endswith(".json"):
        return "json.loads"
    if lower.endswith((".md", ".txt", ".rst")):
        return "utf8-text"
    return "utf8-text"


@dataclass(frozen=True)
class ConsumerResult:
    path: str
    consumer: str
    exists: bool
    read_ok: bool
    summary: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "consumer": self.consumer,
            "exists": self.exists,
            "read_ok": self.read_ok,
            "summary": self.summary,
        }


@dataclass
class ProbeReport:
    manifest_path: str
    gate_id: str = GATE_ID
    results: list[ConsumerResult] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return bool(self.results) and all(r.read_ok for r in self.results)

    @property
    def failing(self) -> list[ConsumerResult]:
        return [r for r in self.results if not r.read_ok]

    def to_dict(self) -> dict[str, Any]:
        return {
            "gate_id": self.gate_id,
            "manifest_path": self.manifest_path,
            "ok": self.ok,
            "entry_count": len(self.results),
            "failing_count": len(self.failing),
            "failing": [r.to_dict() for r in self.failing],
            "results": [r.to_dict() for r in self.results],
        }

    def sentinel_line(self) -> str:
        if self.ok:
            return (
                f"SUCCESS:artifact-manifest-gate entries={len(self.results)} "
                f"all_consumers_read_ok"
            )
        names = [r.path for r in self.failing[:5]]
        return (
            f"FAILED:artifact-manifest-gate failing={len(self.failing)}/{len(self.results)} "
            f"paths={names}"
        )


def load_manifest(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_manifest_atomic(path: Path, doc: Mapping[str, Any]) -> None:
    """Atomic publish so a killed writer never leaves a torn manifest."""
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = (json.dumps(doc, indent=2, ensure_ascii=True) + "\n").encode("utf-8")
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=str(path.parent),
    )
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, path)
    except Exception:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass
        raise


def register_on_write(
    root: Path,
    artifact_rel: str,
    *,
    consumer: str | None = None,
    manifest_rel: str = DEFAULT_MANIFEST,
    unit_id: str | None = None,
) -> dict[str, Any]:
    """Measure ``artifact_rel`` on disk and upsert it into the manifest.

    Fails closed if the artifact is absent — registering a path string without
    bytes is exactly the defect this gate exists to stop.
    """
    root = Path(root)
    rel = artifact_rel.replace("\\", "/")
    target = root / rel
    if not target.is_file():
        raise FileNotFoundError(
            f"register_on_write refused: {rel} is absent on disk "
            "(a file path in text is not proof the file exists)"
        )
    raw = target.read_bytes()
    digest, nbytes = _sha256_lf(raw)
    consumer_id = consumer or infer_consumer(rel)
    if consumer_id not in CONSUMERS:
        raise ValueError(f"unknown consumer {consumer_id!r}; known={sorted(CONSUMERS)}")

    man_path = root / manifest_rel
    if man_path.is_file():
        manifest = load_manifest(man_path)
    else:
        manifest = {
            "schema_version": 1,
            "contract": "CC-0009 register-on-write",
            "derivation": GATE_ID,
            "verified_on_disk": True,
            "artifacts": [],
        }

    entries = manifest.get("artifacts")
    if not isinstance(entries, list):
        entries = []
        manifest["artifacts"] = entries

    entry: dict[str, Any] = {
        "path": rel,
        "present": True,
        "bytes": nbytes,
        "sha256": digest,
        "consumer": consumer_id,
    }
    if unit_id:
        entry["unit_id"] = unit_id

    replaced = False
    for i, existing in enumerate(entries):
        if isinstance(existing, dict) and str(existing.get("path", "")).replace(
            "\\", "/"
        ) == rel:
            entries[i] = {**existing, **entry}
            replaced = True
            break
    if not replaced:
        entries.append(entry)

    manifest["present"] = sum(
        1 for e in entries if isinstance(e, dict) and e.get("present") is not False
    )
    manifest["expected"] = len(entries)
    manifest["verified_on_disk"] = True
    manifest["derivation"] = GATE_ID
    write_manifest_atomic(man_path, manifest)
    return entry


def probe_manifest_consumers(
    root: Path,
    *,
    manifest_rel: str = DEFAULT_MANIFEST,
) -> ProbeReport:
    """Open every manifest entry with its declared (or inferred) consumer."""
    root = Path(root)
    man_path = root / manifest_rel
    report = ProbeReport(manifest_path=manifest_rel)
    if not man_path.is_file():
        report.results.append(
            ConsumerResult(
                path=manifest_rel,
                consumer="manifest-load",
                exists=False,
                read_ok=False,
                summary=f"manifest absent at {man_path}",
            )
        )
        return report

    try:
        manifest = load_manifest(man_path)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        report.results.append(
            ConsumerResult(
                path=manifest_rel,
                consumer="manifest-load",
                exists=True,
                read_ok=False,
                summary=f"manifest unreadable: {type(exc).__name__}: {exc}",
            )
        )
        return report

    entries = manifest.get("artifacts")
    if not isinstance(entries, list) or not entries:
        report.results.append(
            ConsumerResult(
                path=manifest_rel,
                consumer="manifest-load",
                exists=True,
                read_ok=False,
                summary="manifest has no artifacts array (empty registration is a fail)",
            )
        )
        return report

    for entry in entries:
        if not isinstance(entry, dict):
            report.results.append(
                ConsumerResult(
                    path="<malformed>",
                    consumer="manifest-load",
                    exists=False,
                    read_ok=False,
                    summary="non-object artifact entry",
                )
            )
            continue
        rel = str(entry.get("path") or "").replace("\\", "/")
        if not rel:
            report.results.append(
                ConsumerResult(
                    path="<missing-path>",
                    consumer="manifest-load",
                    exists=False,
                    read_ok=False,
                    summary="artifact entry carries no path",
                )
            )
            continue
        if entry.get("present") is False:
            # Explicitly marked absent is still a failure for the consumer gate:
            # a registration that admits absence is registered-but-absent.
            report.results.append(
                ConsumerResult(
                    path=rel,
                    consumer=infer_consumer(rel, entry),
                    exists=False,
                    read_ok=False,
                    summary="manifest marks present=false (registered-but-absent)",
                )
            )
            continue

        consumer_id = infer_consumer(rel, entry)
        target = root / rel
        if not target.is_file():
            report.results.append(
                ConsumerResult(
                    path=rel,
                    consumer=consumer_id,
                    exists=False,
                    read_ok=False,
                    summary=(
                        "registered-but-absent: path in manifest but stat says missing "
                        "(a file path in text is not proof the file exists)"
                    ),
                )
            )
            continue

        fn = CONSUMERS.get(consumer_id)
        if fn is None:
            report.results.append(
                ConsumerResult(
                    path=rel,
                    consumer=consumer_id,
                    exists=True,
                    read_ok=False,
                    summary=f"unknown consumer {consumer_id!r}",
                )
            )
            continue
        ok, summary = fn(target)
        report.results.append(
            ConsumerResult(
                path=rel,
                consumer=consumer_id,
                exists=True,
                read_ok=ok,
                summary=summary,
            )
        )
    return report


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo-root", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--manifest", default=DEFAULT_MANIFEST)
    sub = ap.add_subparsers(dest="cmd", required=True)

    reg = sub.add_parser("register", help="register-on-write an artifact into the manifest")
    reg.add_argument("path", help="repo-relative artifact path")
    reg.add_argument("--consumer", default=None)
    reg.add_argument("--unit-id", default=None)

    sub.add_parser("probe", help="probe every manifest entry with its consumer")

    ns = ap.parse_args(list(argv) if argv is not None else None)
    root = Path(ns.repo_root)

    if ns.cmd == "register":
        try:
            entry = register_on_write(
                root,
                ns.path,
                consumer=ns.consumer,
                manifest_rel=ns.manifest,
                unit_id=ns.unit_id,
            )
        except (OSError, ValueError, FileNotFoundError) as exc:
            print(f"FAILED:register-on-write {exc}")
            return 1
        print(json.dumps(entry, indent=2))
        print(f"SUCCESS:register-on-write {entry['path']} -> {ns.manifest}")
        return 0

    report = probe_manifest_consumers(root, manifest_rel=ns.manifest)
    print(json.dumps(report.to_dict(), indent=2))
    print(report.sentinel_line())
    return 0 if report.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
