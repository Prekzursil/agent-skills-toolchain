r"""CC-0013 — derive command-center/STATUS.md as a measurement.

STATUS.md is generated from:
  * command-center/events/EVENTS.jsonl
  * command-center/receipts/*.json
  * the shared completion predicate (platform/lib/completion_predicate.py)

Every numeric claim in the board carries the query that produced it. A count
with no query is refused. Empty events force board status NOT-STARTED and never
a green program status. Generation stamps use the generating git commit plus a
deterministic generation_time derived from the newest event timestamp (or the
epoch sentinel when there are zero events), so two runs over unchanged inputs
are byte-identical.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Mapping

REPO = Path(__file__).resolve().parents[1]
EVENTS_REL = "command-center/events/EVENTS.jsonl"
RECEIPTS_REL = "command-center/receipts"
STATUS_REL = "command-center/STATUS.md"
REDUCER_ID = "platform/lib/completion_predicate.py@v1"
GENERATOR_ID = "command-center/status_derive.py@v1"
NOT_STARTED = "NOT-STARTED"
MEASURED = "MEASURED"
EPOCH = "1970-01-01T00:00:00+00:00"
GREEN_TOKENS = frozenset(
    {
        "GREEN",
        "ALL-GREEN",
        "PROGRAM-GREEN",
        "PROGRAM-COMPLETE",
        "COMPLETE",
        "SUCCESS",
        "GO",
    }
)

BANNER = (
    "<!-- GENERATED by command-center/status_derive.py from EVENTS.jsonl + "
    "receipts/ + platform/lib/completion_predicate.py. Do not hand-edit: "
    "run `python command-center/status_derive.py` and "
    "`python command-center/status_gate.py`. -->"
)


@dataclass(frozen=True)
class Metric:
    name: str
    value: int | str
    query: str

    def __post_init__(self) -> None:
        if not self.query or not str(self.query).strip():
            raise ValueError(
                f"refused to emit metric {self.name!r}: every number must carry a query"
            )


@dataclass
class Measurement:
    metrics: list[Metric] = field(default_factory=list)
    board_status: str = NOT_STARTED
    generating_commit: str = "UNKNOWN"
    generation_time: str = EPOCH
    events_sha256: str = ""
    receipts_sha256: str = ""
    reducer_id: str = REDUCER_ID
    generator_id: str = GENERATOR_ID

    def add(self, name: str, value: int | str, query: str) -> None:
        self.metrics.append(Metric(name=name, value=value, query=query))


def _git_head(repo: Path) -> str:
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return "UNKNOWN"
    if proc.returncode != 0:
        return "UNKNOWN"
    return (proc.stdout or "").strip() or "UNKNOWN"


def _load_events(events_path: Path) -> tuple[list[dict[str, Any]], list[str]]:
    """Return (parsed_records, parse_errors). Blank lines are ignored, not counted."""
    if not events_path.is_file():
        return [], [f"missing:{events_path}"]
    records: list[dict[str, Any]] = []
    errors: list[str] = []
    for idx, raw in enumerate(
        events_path.read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = raw.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError as exc:
            errors.append(f"line {idx}: {exc}")
            continue
        if not isinstance(obj, dict):
            errors.append(f"line {idx}: not an object")
            continue
        records.append(obj)
    return records, errors


def _newest_event_ts(records: list[dict[str, Any]]) -> str:
    stamps: list[str] = []
    for rec in records:
        ts = rec.get("ts") or rec.get("timestamp") or rec.get("t")
        if isinstance(ts, str) and ts.strip():
            stamps.append(ts.strip())
    if not stamps:
        return EPOCH
    return max(stamps)


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path) -> str:
    if not path.is_file():
        return _sha256_bytes(b"")
    return _sha256_bytes(path.read_bytes())


def _receipt_paths(receipts_dir: Path) -> list[Path]:
    if not receipts_dir.is_dir():
        return []
    return sorted(p for p in receipts_dir.glob("*.json") if p.is_file())


def _load_predicate():
    lib = REPO / "platform" / "lib"
    if str(lib) not in sys.path:
        sys.path.insert(0, str(lib))
    import completion_predicate as cp  # noqa: WPS433

    return cp


def _evaluate_receipts(
    repo: Path, receipt_paths: list[Path], cp: Any
) -> dict[str, int]:
    counts = {"COMPLETE": 0, "INCOMPLETE": 0, "INDETERMINATE": 0, "EVAL_ERROR": 0}
    opts = cp.PredicateOptions(
        repo_root=repo,
        output_schema="command-center/schema/receipt.schema.json",
        min_evidence_anchors=1,
    )
    for path in receipt_paths:
        try:
            receipt = cp.load_receipt(path)
            result = cp.evaluate(receipt, opts)
            counts[result.verdict.value] = counts.get(result.verdict.value, 0) + 1
        except Exception:  # noqa: BLE001 — total function for the board
            counts["EVAL_ERROR"] += 1
    return counts


def _declared_state_counts(receipt_paths: list[Path]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for path in receipt_paths:
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            counts["UNPARSEABLE"] = counts.get("UNPARSEABLE", 0) + 1
            continue
        state = doc.get("state") if isinstance(doc, Mapping) else None
        key = state if isinstance(state, str) and state else "MISSING_STATE"
        counts[key] = counts.get(key, 0) + 1
    return counts


def measure(
    *,
    repo: Path | None = None,
    events_path: Path | None = None,
    receipts_dir: Path | None = None,
) -> Measurement:
    root = repo or REPO
    events = events_path or (root / EVENTS_REL)
    receipts = receipts_dir or (root / RECEIPTS_REL)

    records, parse_errors = _load_events(events)
    receipt_paths = _receipt_paths(receipts)
    cp = _load_predicate()
    pred = _evaluate_receipts(root, receipt_paths, cp)
    declared = _declared_state_counts(receipt_paths)

    event_count = len(records)
    board_status = NOT_STARTED if event_count == 0 else MEASURED
    if board_status in GREEN_TOKENS:
        raise RuntimeError("internal invariant: board_status must never be a green token")

    m = Measurement(
        board_status=board_status,
        generating_commit=_git_head(root),
        generation_time=_newest_event_ts(records) if event_count else EPOCH,
        events_sha256=_sha256_file(events),
        receipts_sha256=_sha256_bytes(
            b"\n".join(
                f"{p.name}:{_sha256_file(p)}".encode() for p in receipt_paths
            )
        ),
        reducer_id=getattr(cp, "REDUCER_ID", REDUCER_ID),
    )

    m.add(
        "event_records",
        event_count,
        "count(JSON objects parsed from non-blank lines in command-center/events/EVENTS.jsonl)",
    )
    m.add(
        "event_parse_errors",
        len(parse_errors),
        "count(non-blank EVENTS.jsonl lines that fail json.loads or are non-objects)",
    )
    m.add(
        "receipt_files",
        len(receipt_paths),
        "count(*.json files under command-center/receipts/)",
    )
    for state_name in sorted(declared):
        m.add(
            f"declared_state_{state_name}",
            declared[state_name],
            f"count(receipts where receipt.state == {state_name!r})",
        )
    for verdict_name in ("COMPLETE", "INCOMPLETE", "INDETERMINATE", "EVAL_ERROR"):
        m.add(
            f"predicate_{verdict_name}",
            pred.get(verdict_name, 0),
            (
                "count(receipts where completion_predicate.evaluate(...).verdict "
                f"== {verdict_name!r})"
            ),
        )
    m.add(
        "board_status",
        board_status,
        (
            "NOT-STARTED if event_records==0 else MEASURED; "
            "never GREEN/COMPLETE/SUCCESS when events are empty"
        ),
    )
    return m


def render_status(measurement: Measurement | None = None, **kwargs: Any) -> str:
    m = measurement or measure(**kwargs)
    if m.board_status == NOT_STARTED:
        for token in GREEN_TOKENS:
            # Defense in depth: empty-input control must never look green.
            if token == m.board_status:
                raise RuntimeError("NOT-STARTED collided with green vocabulary")

    lines: list[str] = [
        BANNER,
        "",
        "# STATUS",
        "",
        f"**Board status: {m.board_status}.**",
        "",
        "This file is a derived measurement, not a hand-written claim. "
        "Every number below names the query that produced it.",
        "",
        "## Stamps",
        "",
        f"- generating_commit: `{m.generating_commit}`",
        f"- generation_time: `{m.generation_time}` "
        "(newest event `ts`/`timestamp`/`t`, or epoch when event_records==0)",
        f"- generator: `{m.generator_id}`",
        f"- reducer: `{m.reducer_id}`",
        f"- events_sha256: `{m.events_sha256}`",
        f"- receipts_inventory_sha256: `{m.receipts_sha256}`",
        "",
        "## Metrics",
        "",
        "| metric | value | query |",
        "|---|---|---|",
    ]
    for metric in m.metrics:
        value = metric.value
        lines.append(f"| {metric.name} | {value} | `{metric.query}` |")
    lines += [
        "",
        "## Empty-input rule",
        "",
        "When `event_records` is 0 the board status is exactly `NOT-STARTED` "
        "and must not be reported as green. Regenerate with "
        "`python command-center/status_derive.py`. Verify with "
        "`python command-center/status_gate.py`.",
        "",
    ]
    text = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    # Refuse accidental green wording in the NOT-STARTED board body.
    if m.board_status == NOT_STARTED:
        upper = text.upper()
        for token in ("PROGRAM-GREEN", "ALL-GREEN", "BOARD STATUS: GREEN", "BOARD STATUS: COMPLETE", "BOARD STATUS: SUCCESS"):
            if token in upper:
                raise RuntimeError(f"refused green wording under NOT-STARTED: {token}")
    return text


def write_status(
    *,
    repo: Path | None = None,
    status_path: Path | None = None,
    events_path: Path | None = None,
    receipts_dir: Path | None = None,
) -> Path:
    root = repo or REPO
    target = status_path or (root / STATUS_REL)
    text = render_status(repo=root, events_path=events_path, receipts_dir=receipts_dir)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=str(REPO))
    parser.add_argument("--events", default=None)
    parser.add_argument("--receipts", default=None)
    parser.add_argument("--status", default=None)
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="print derived STATUS.md to stdout instead of writing",
    )
    args = parser.parse_args(argv)
    root = Path(args.repo)
    events = Path(args.events) if args.events else None
    receipts = Path(args.receipts) if args.receipts else None
    status = Path(args.status) if args.status else None
    text = render_status(repo=root, events_path=events, receipts_dir=receipts)
    if args.stdout:
        sys.stdout.write(text)
        return 0
    path = write_status(
        repo=root, status_path=status, events_path=events, receipts_dir=receipts
    )
    print(f"SUCCESS:status-derive wrote={path.as_posix()} bytes={path.stat().st_size}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
