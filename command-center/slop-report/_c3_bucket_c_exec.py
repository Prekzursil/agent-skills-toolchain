"""BUILD R1 -- bucket (c) EXECUTED, with the regenerating command proven by execution.

Bucket (c) is "reproducible scratch, safe to delete because a committed script regenerates
it". The grounding lane's finding R2 was that 31 of 32 apparent bucket-(c) outputs FAIL that
definition -- their producer is not in git -- so they are really bucket (b). That leaves a
small, honest bucket (c). Scope here is deliberately limited to a cache directory THIS lane
created, because sibling lanes are writing in this tree right now and a wider sweep races them.

Target: command-center/slop-report/__pycache__ (created by _b1_control.py importing
_b1_cited_probes).

REGENERATING COMMAND (shown, then executed):
    python command-center/slop-report/_b1_control.py

PROOF, not assertion: hash every file, delete, re-run the command, hash again, and require the
digests to be IDENTICAL. Byte-identical regeneration is the strongest available evidence that
nothing unique lived there.

CONTROL (both states): a cache that regenerates must ALSO be provably absent in between. So
assert n_files > 0 before, == 0 after deletion, and > 0 again after the command. A probe that
only checks the end state cannot tell "regenerated" from "never deleted".
"""

import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = "C:/Users/Prekzursil/source/ast-integrate"
OUT = os.path.join(ROOT, "command-center/slop-report/_c3_bucket_c_exec.out.json")
TARGET = os.path.join(ROOT, "command-center/slop-report/__pycache__")
REGEN = ["python", "command-center/slop-report/_b1_control.py"]


def snap(d):
    if not os.path.isdir(d):
        return {}
    out = {}
    for f in sorted(os.listdir(d)):
        fp = os.path.join(d, f)
        if os.path.isfile(fp):
            with open(fp, "rb") as fh:
                out[f] = hashlib.sha256(fh.read()).hexdigest()[:16]
    return out


def main():
    out = {
        "target": os.path.relpath(TARGET, ROOT).replace("\\", "/"),
        "regen_command": " ".join(REGEN),
    }
    before = snap(TARGET)
    out["before"] = {"n_files": len(before), "digests": before}

    if before:
        shutil.rmtree(TARGET, ignore_errors=True)
    mid = snap(TARGET)
    out["after_delete"] = {"n_files": len(mid)}

    r = subprocess.run(
        REGEN,
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    after = snap(TARGET)
    out["regen_rc"] = r.returncode
    out["after_regen"] = {"n_files": len(after), "digests": after}

    checks = {
        "existed_before": len(before) > 0,
        "absent_after_delete": len(mid) == 0,
        "present_after_regen": len(after) > 0,
        "byte_identical": before == after,
        "regen_succeeded": r.returncode == 0,
    }
    out["checks"] = checks
    out["controls_verdict"] = "PASS" if all(checks.values()) else "FAIL"
    out["verdict"] = (
        "BUCKET (c) CONFIRMED by execution: deleted and regenerated byte-identically"
        if all(checks.values())
        else "NOT PROVEN -- do not delete"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
    print(json.dumps(out, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
