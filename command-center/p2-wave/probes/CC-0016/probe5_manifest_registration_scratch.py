#!/usr/bin/env python3
"""CC-0016 PROBE 5: demonstrate the register-on-write + consumer-read mechanism
(platform/lib/artifact_manifest_gate.py, CC-0009) against
command-center/PHASE-GRAPH.json, on a SCRATCH manifest only.

The catalog's question_or_target literally says "register the sidecar in
ARTIFACT-MANIFEST.json". command-center/ARTIFACT-MANIFEST.json is, however, a
CLOSED-SCHEMA artifact: it is regenerated by
``tools/command-center/render.py:render_manifest`` from a fixed 14-name
``CONTRACTED_ARTIFACTS`` tuple bound to a specific spec line range
(``_USER-PROMPTS.md:10590-10603``). AGENTS.md's own instruction is explicit:
"Treat consumer-owned manifests as closed schemas. Never add a manifest key
merely to carry provenance." Bumping that tuple from 14 to 15 is a contract
change with its own line-range citation and would need an owner decision, not
a unilateral edit inside this work unit -- exactly the "record the canonical
home" question the catalog poses and leaves open.

So this probe proves the registration MECHANISM works end-to-end against
PHASE-GRAPH.json on an isolated scratch manifest (never the live
command-center/ARTIFACT-MANIFEST.json), and the receipt records live
registration as explicitly BLOCKED pending that owner decision.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "platform" / "lib"))
import artifact_manifest_gate as amg  # noqa: E402

OUT_JSON = Path(__file__).resolve().parent / "probe5-manifest-registration-scratch.json"
OUT_RAW = Path(__file__).resolve().parent / "probe5-manifest-registration-scratch.raw.txt"


def main() -> int:
    lines: list[str] = []
    lines.append("CC-0016 PROBE5 manifest-registration mechanism (scratch manifest only)")
    lines.append(f"REPO={REPO}")

    manifest_rel = "command-center/p2-wave/probes/CC-0016/scratch-manifest/ARTIFACT-MANIFEST.scratch.json"
    manifest_abs = REPO / manifest_rel
    if manifest_abs.is_file():
        manifest_abs.unlink()

    entry = amg.register_on_write(
        REPO,
        "command-center/PHASE-GRAPH.json",
        consumer="json.loads",
        manifest_rel=manifest_rel,
        unit_id="CC-0016",
    )
    lines.append(f"REGISTER_ON_WRITE entry={json.dumps(entry, indent=2)}")

    report = amg.probe_manifest_consumers(REPO, manifest_rel=manifest_rel)
    lines.append(f"PROBE_CONSUMERS sentinel={report.sentinel_line()}")
    for r in report.results:
        lines.append(f"  {r.path} via {r.consumer}: {r.summary}")

    # Confirm PHASE-GRAPH.json is NOT one of the live manifest's entries -- the
    # write above targeted the scratch manifest only.
    live_doc = json.loads((REPO / "command-center/ARTIFACT-MANIFEST.json").read_text())
    live_paths = {a.get("path") for a in live_doc.get("artifacts", [])}
    phase_graph_in_live_manifest = "command-center/PHASE-GRAPH.json" in live_paths
    lines.append(
        f"LIVE_MANIFEST_PHASE_GRAPH_ENTRY_PRESENT={phase_graph_in_live_manifest} "
        "(expected False -- live registration is BLOCKED pending owner sign-off "
        "on the closed-schema 14->15 contract bump, see receipt residual_unknowns)"
    )

    ok = report.ok and not phase_graph_in_live_manifest
    lines.append(f"PROBE5_OK={ok}")

    summary = {
        "scratch_manifest_path": manifest_rel,
        "register_on_write_entry": entry,
        "probe_report_ok": report.ok,
        "probe_report": report.to_dict(),
        "phase_graph_in_live_manifest": phase_graph_in_live_manifest,
        "live_registration_status": "BLOCKED-pending-owner-decision-on-14-to-15-contract-bump",
        "ok": ok,
    }
    OUT_JSON.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    OUT_RAW.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
